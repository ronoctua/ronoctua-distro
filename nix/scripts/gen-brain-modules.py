#!/usr/bin/env python3
"""The brain's modules, from their manifests to Rust — brain.md §3.

`nix/brain-modules.nix` reads every folder under `crates/ronoctua-brain/modules/`,
refuses what is malformed and hands this script one record per module: the
manifest with every optional field filled, the store path of its text folder
and the tables its `tables.nix` generated. What comes out, under `--out`:

    <id>/manifest.rs   ID, the key, mark, notice, action, event, why and unit
                       constants, and MANIFEST — `include!`d beside the
                       module's own `module.rs` by the crate's `build.rs`
    <id>/<table>.rs    each table, copied, and a `tables` module including it
    all.rs             IDS, MANIFESTS, ACTIONS, EVENTS, `manifest(id)` and
                       `all(birth)`: the registry the daemon, the footer and
                       the leader read without naming any module, with its own
                       test
    ids.txt            `<id> <snake>` per line: what `build.rs` compares with
                       the folders and writes one shim for

WHY A GENERATOR AND NOT A MACRO: invariant 5. The manifest is Nix, and the
Rust side reading it back would be a second parser of the same data; here it
is read once, by Nix, and what crosses is the finished table.

THE TEXT KEYS come from the module's OWN base `.ftl`, read by `gen-i18n.py`'s
parser — the one that builds the registry — so a key constant here is a key
the bundle has. A key the manifest needs (its name, its line, an action's
label or question, a mark's hint, a why) and the fragment lacks is refused
here, by name, rather than becoming a missing constant in the compiler.

The Rust is written plainly and formatted afterwards by the pinned `rustfmt`
(`nix/brain-modules-rs.nix`), so what lands is what `cargo fmt` would leave —
and the golden sample, `crates/ronoctua-brain/tests/modules/pilot-sample/
manifest.rs`, can be compared byte for byte below its header.

Usage:
    gen-brain-modules.py --modules <modules.json> --parser <gen-i18n.py>
                         --language <base> --out <dir>
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import shutil
import sys
from pathlib import Path

HEADER = """\
// GENERATED by `nix/scripts/gen-brain-modules.py` out of `modules/{id}/manifest.nix`.
// Do not edit: it vanishes at the next build.
//
// It is `include!`d into `pub mod {snake}`, beside `mod module;`, so the
// module names everything here through `super::`. Paths into the brain are
// absolute (`crate::module::…`): inside the shim `module` is the module's own
// file, not the contract.

"""

ALL_HEADER = """\
// GENERATED by `nix/scripts/gen-brain-modules.py`. Do not edit: it vanishes at
// the next build.
//
// The crate's `build.rs` writes `modules.rs` — one shim per module, then this
// file — and `src/compiled.rs` includes it, so every `<snake>::` below is a
// sibling module and `IDS` and `all` are `crate::compiled::IDS` and
// `crate::compiled::all`, the two items that file promises. Nothing here names
// a module by hand: the list is the folders.

"""

LEVELS = {"info": "Info", "warn": "Warn", "danger": "Danger", "alarm": "Alarm"}
KINDS = {"routine": "Routine", "once": "Once"}
PARTS = {"any": "Any", "night": "Night", "morning": "Morning", "afternoon": "Afternoon", "evening": "Evening"}


def fail(ident: str, what: str) -> None:
    print(f"ERROR: brain module `{ident}`: {what}", file=sys.stderr)
    raise SystemExit(1)


def const(name: str) -> str:
    """`made-up` -> `MADE_UP`, `cmd-made-up-x` -> `CMD_MADE_UP_X`."""
    return name.upper().replace("-", "_")


def rust_str(s: str) -> str:
    """A Rust string literal. Not JSON's: `\\uXXXX` is not Rust."""
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{out}"'


def load_parser(path: Path):
    """`gen-i18n.py`'s own `keys()`: one reader of a `.ftl`, not two."""
    spec = importlib.util.spec_from_file_location("gen_i18n", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.keys


def roles(m: dict) -> dict[str, str]:
    """What each key the manifest names is FOR — the key's doc comment."""
    ident = m["id"]
    out: dict[str, str] = {
        f"brain-task-{ident}": "Its name on screen.",
        f"brain-task-{ident}-does": "The line under the cursor.",
    }
    for a, spec in sorted(m["actions"].items()):
        out.setdefault(f"cmd-{ident}-{a}", f"The label of the action `{a}`.")
        if spec.get("asks"):
            out.setdefault(spec["asks"], f"The question the action `{a}` asks.")
    for k, spec in sorted(m["marks"].items()):
        out.setdefault(spec["hint"], f"The hint of the mark `{k}`.")
    for n in sorted(m["notices"]):
        out.setdefault(f"{ident}-says-{n}", f"What the notice `{n}` says.")
    for w in m["whys"]:
        out.setdefault(f"{ident}-why-{w}", f"The why `{w}`.")
    for e, spec in sorted(m["events"].items()):
        if spec.get("notification") is not None:
            out.setdefault(f"notif-{ident}-{e}-summary", f"The summary of the notification `{e}`.")
            out.setdefault(f"notif-{ident}-{e}-body", f"The body of the notification `{e}`.")
    return out


def needed(m: dict) -> list[tuple[str, str]]:
    """The keys the generated Rust refers to, with what refers to each."""
    ident = m["id"]
    out = [(f"brain-task-{ident}", "its name"), (f"brain-task-{ident}-does", "its line under the cursor")]
    for a, spec in sorted(m["actions"].items()):
        out.append((f"cmd-{ident}-{a}", f"the label of the action `{a}`"))
        if spec.get("asks"):
            out.append((spec["asks"], f"the question of the action `{a}`"))
    for k, spec in sorted(m["marks"].items()):
        out.append((spec["hint"], f"the hint of the mark `{k}`"))
    for w in m["whys"]:
        out.append((f"{ident}-why-{w}", f"the why `{w}`"))
    return out


def manifest_rs(m: dict, texts: dict[str, str], language: str, tables: list[str]) -> str:
    ident, snake = m["id"], m["snake"]
    key_of = {k: const(k) for k in texts}
    for k, what in needed(m):
        if k not in texts:
            fail(ident, f"its i18n/{language}.ftl has no `{k}` ({what})")
    role = roles(m)
    L: list[str] = []
    A = L.append

    A(HEADER.format(id=ident, snake=snake))
    A("/// The id: the folder's name, and written nowhere else.")
    A(f"pub const ID: &str = {rust_str(ident)};")
    A("")

    A(f"/// The module's text keys, from its own `i18n/{language}.ftl`.")
    A("pub mod key {")
    for k in sorted(texts):
        doc = role.get(k)
        if doc is None:
            example = texts[k].replace("\\", "\\\\")
            if len(example) > 100:
                example = example[:97] + "..."
            doc = f"`{language}`: {example}"
        A(f"    /// {doc}")
        A(f"    pub const {key_of[k]}: &str = {rust_str(k)};")
    A("}")
    A("")

    def block(doc: str, name: str, items: list[str]) -> None:
        if items:
            A(f"/// {doc}.")
            A(f"pub mod {name} {{")
            L.extend(items)
            A("}")
        else:
            A(f"/// {doc}: none.")
            A(f"pub mod {name} {{}}")
        A("")

    items = []
    for k, spec in sorted(m["marks"].items()):
        token = f"{ident}-{spec['glyph']}"
        items.append(f"    /// `brain:{ident}/{k}`, drawn with the glyph token `{token}`.")
        items.append(
            f"    pub const {const(k)}: crate::module::MarkId = crate::module::MarkId::of("
            f"{rust_str(k)}, {rust_str(token)}, super::key::{key_of[spec['hint']]});"
        )
    block("The marks it may put on the modeline", "mark", items)

    items = []
    for n, spec in sorted(m["notices"].items()):
        snooze = ", ".join(str(s) for s in spec["snooze"])
        items.append(f"    /// `{n}`.")
        items.append(
            f"    pub const {const(n)}: crate::module::NoticeKind = crate::module::NoticeKind {{"
            f" id: {rust_str(n)},"
            f" level: crate::module::Level::{LEVELS[spec['level']]},"
            f" dismiss: {'true' if spec['dismiss'] else 'false'},"
            f" snooze: &[{snooze}], }};"
        )
    block("The notices it may raise", "notice", items)

    items = []
    for a, spec in sorted(m["actions"].items()):
        command = f"{ident}-{a}"
        doc = f"`{command}`"
        if spec["row"]:
            doc += ", on a row"
        if spec.get("asks"):
            doc += f", asking `{spec['asks']}` first"
        asks = f"Some(super::key::{key_of[spec['asks']]})" if spec.get("asks") else "None"
        items.append(f"    /// {doc}.")
        items.append(
            f"    pub const {const(a)}: crate::module::Action = crate::module::Action {{"
            f" id: {rust_str(a)},"
            f" command: {rust_str(command)},"
            f" label: super::key::{key_of['cmd-' + command]},"
            f" row: {'true' if spec['row'] else 'false'},"
            f" asks: {asks}, }};"
        )
    block("What a person can ask of it by name", "action", items)

    items = []
    for e, spec in sorted(m["events"].items()):
        tag = f"{ident}-{e}"
        doc = f"`{tag}`" + (", raised as a notification" if spec.get("notification") is not None else "")
        items.append(f"    /// {doc}.")
        items.append(
            f"    pub const {const(e)}: crate::module::EventKind = crate::module::EventKind {{"
            f" name: {rust_str(e)}, tag: {rust_str(tag)}, }};"
        )
    block("What it may tell the footer", "event", items)

    items = []
    for w in m["whys"]:
        items.append(f"    /// `{w}`.")
        items.append(f"    pub const {const(w)}: &str = {rust_str(w)};")
    block("The words it may give as a reason", "why", items)

    items = []
    for w, spec in sorted(m["units"].items()):
        items.append(f"    /// `{w}`: `{spec['name']}`.")
        items.append(f"    pub const {const(w)}: &str = {rust_str(spec['name'])};")
    block("The units it starts", "unit", items)

    if tables:
        A("/// The tables its `tables.nix` generated, each beside this file.")
        A("pub mod tables {")
        for name in tables:
            stem = name[: -len(".rs")]
            A(f"    /// `{name}`.")
            A(f"    pub mod {stem.replace('-', '_')} {{")
            A(f"        include!({rust_str(name)});")
            A("    }")
        A("}")
        A("")

    s = m["schedule"]
    if s is None:
        schedule = "None"
    else:
        every = "None" if s.get("everyMinutes") is None else f"Some({s['everyMinutes']})"
        schedule = (
            "Some(crate::module::Schedule {"
            f" kind: crate::module::Kind::{KINDS[s['kind']]},"
            f" calendar: {'true' if s['calendar'] else 'false'},"
            f" interval_days: {s['intervalDays']},"
            f" part_of_day: crate::prefs::PartOfDay::{PARTS[s['partOfDay']]},"
            f" every_minutes: {every},"
            f" countdown_seconds: {s['countdownSeconds']},"
            f" runaway_minutes: {s['runawayMinutes']},"
            f" gated: {'true' if s['gated'] else 'false'}, }})"
        )

    def unit_ref(word: str) -> str:
        return f"Some(unit::{const(word)})" if word in m["units"] else "None"

    whys = ", ".join(
        f"crate::module::Why {{ word: why::{const(w)}, key: key::{key_of[f'{ident}-why-{w}']} }}" for w in m["whys"]
    )
    A("/// Everything `manifest.nix` declares.")
    A("pub static MANIFEST: crate::module::Manifest = crate::module::Manifest {")
    A("    id: ID,")
    A(f"    what: {rust_str(m['what'])},")
    A(f"    name_key: key::{key_of[f'brain-task-{ident}']},")
    A(f"    does_key: key::{key_of[f'brain-task-{ident}-does']},")
    A(
        "    needs: crate::module::Needs {"
        f" root: {'true' if m['needs']['root'] else 'false'},"
        f" network: {'true' if m['needs']['network'] else 'false'}, }},"
    )
    A(f"    schedule: {schedule},")
    A(f"    units: crate::module::Units {{ run: {unit_ref('run')}, rehearse: {unit_ref('rehearse')}, }},")
    A(f"    whys: &[{whys}],")
    A(f"    marks: &[{', '.join('mark::' + const(k) for k in sorted(m['marks']))}],")
    A(f"    notices: &[{', '.join('notice::' + const(n) for n in sorted(m['notices']))}],")
    A(f"    actions: &[{', '.join('action::' + const(a) for a in sorted(m['actions']))}],")
    A(f"    events: &[{', '.join('event::' + const(e) for e in sorted(m['events']))}],")
    A("};")
    return "\n".join(L) + "\n"


def all_rs(modules: list[dict]) -> str:
    L: list[str] = [ALL_HEADER]
    A = L.append
    actions = [(m, a) for m in modules for a in sorted(m["actions"])]
    events = [(m, e) for m in modules for e in sorted(m["events"])]

    # SLICES, NOT ARRAYS: `IDS: &[&str]` is the type `src/compiled.rs` declares
    # for the build with no module, and the type does not change with the count.
    A("/// Every module id the build compiled, in the order of their folders under")
    A("/// `crates/ronoctua-brain/modules/`.")
    A(f"pub const IDS: &[&str] = &[{', '.join(m['snake'] + '::ID' for m in modules)}];")
    A("")
    A("/// Every module's manifest, in the order of [`IDS`].")
    A(
        "pub static MANIFESTS: &[&crate::module::Manifest] = "
        f"&[{', '.join('&' + m['snake'] + '::MANIFEST' for m in modules)}];"
    )
    A("")
    A("/// Every action a module answers, with its module's id: the leader")
    A("/// registers each as the command `<module>-<action>`, by name only.")
    A(
        "pub static ACTIONS: &[(&str, &crate::module::Action)] = &["
        + ", ".join(f"({m['snake']}::ID, &{m['snake']}::action::{const(a)})" for m, a in actions)
        + "];"
    )
    A("")
    A("/// Every event a module may tell, with its module's id: the footer")
    A("/// recognises each by its tag, and the catalogue has one entry for each")
    A("/// that declared a notification.")
    A(
        "pub static EVENTS: &[(&str, &crate::module::EventKind)] = &["
        + ", ".join(f"({m['snake']}::ID, &{m['snake']}::event::{const(e)})" for m, e in events)
        + "];"
    )
    A("")
    A("/// One module's manifest, by its id.")
    A("#[must_use]")
    A("pub fn manifest(id: &str) -> Option<&'static crate::module::Manifest> {")
    A("    MANIFESTS.iter().copied().find(|m| m.id == id)")
    A("}")
    A("")
    A("/// One of each compiled module, made for this birth: what the daemon")
    A("/// registers.")
    A("#[must_use]")
    if modules:
        A("pub fn all(birth: &crate::module::Birth) -> Vec<Box<dyn crate::module::Module>> {")
        A("    vec![")
        for m in modules:
            A(f"        Box::new({m['snake']}::new(birth)) as Box<dyn crate::module::Module>,")
        A("    ]")
    else:
        A("pub fn all(_birth: &crate::module::Birth) -> Vec<Box<dyn crate::module::Module>> {")
        A("    Vec::new()")
    A("}")
    A("")
    # THE REGISTRY'S OWN TEST TRAVELS WITH IT: wherever this file is included,
    # the test is compiled beside it — so the test cannot be left behind in a
    # file the include moved away from.
    A("#[cfg(test)]")
    A("mod the_registry {")
    A("    use super::{ACTIONS, EVENTS, IDS, MANIFESTS, all, manifest};")
    A("    use crate::module::Birth;")
    A("")
    A("    /// THE FOUR VIEWS OF THE REGISTRY ARE ONE LIST: the ids, the manifests,")
    A("    /// the modules `all` makes, and the actions and events, each found")
    A("    /// again by its module's id. With no module it holds vacuously; the")
    A("    /// first folder makes every line of it count.")
    A("    #[test]")
    A("    fn is_one_list() {")
    A("        assert_eq!(IDS.len(), MANIFESTS.len());")
    A("        for (id, m) in IDS.iter().zip(MANIFESTS) {")
    A('            assert_eq!(*id, m.id, "IDS and MANIFESTS are in different orders");')
    A("            assert!(manifest(id).is_some_and(|found| found.id == *id));")
    A("        }")
    A('        assert!(manifest("no-such-module").is_none());')
    A("")
    A("        let made = all(&Birth::detached());")
    A('        assert_eq!(made.len(), IDS.len(), "a module is listed and not made");')
    A("        for (module, id) in made.iter().zip(IDS) {")
    A("            assert_eq!(module.manifest().id, *id);")
    A("        }")
    A("        for (id, action) in ACTIONS {")
    A('            let owner = manifest(id).expect("an action of a module that is not listed");')
    A("            assert!(owner.action(action.id).is_some());")
    A('            assert_eq!(action.command, format!("{id}-{}", action.id));')
    A("        }")
    A("        for (id, event) in EVENTS {")
    A('            assert_eq!(event.tag, format!("{id}-{}", event.name));')
    A("        }")
    A("    }")
    A("}")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="The brain's modules, from their manifests to Rust.")
    ap.add_argument("--modules", type=Path, required=True, help="the loader's records, as JSON")
    ap.add_argument("--parser", type=Path, required=True, help="gen-i18n.py, whose `keys()` reads a .ftl")
    ap.add_argument("--language", required=True, help="the base language, whose .ftl names the keys")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    keys = load_parser(args.parser)
    modules = sorted(json.loads(args.modules.read_text(encoding="utf-8")), key=lambda m: m["id"])
    args.out.mkdir(parents=True, exist_ok=True)

    seen: set[str] = set()
    for m in modules:
        ident = m["id"]
        if m["snake"] in seen:
            fail(ident, f"its Rust name `{m['snake']}` is another module's")
        seen.add(m["snake"])
        fragment = Path(m["i18n"]) / f"{args.language}.ftl"
        if not fragment.exists():
            fail(ident, f"no i18n/{args.language}.ftl")
        texts = keys(fragment)
        here = args.out / ident
        here.mkdir(parents=True, exist_ok=True)
        tables = []
        for name, source in sorted(m.get("tables", {}).items()):
            if not name.endswith(".rs") or "/" in name or name == "manifest.rs":
                fail(ident, f"tables.nix names `{name}`; a table is `<name>.rs`, and not `manifest.rs`")
            destination = here / name
            # DELETE FIRST: a store file is read-only, and copying over one
            # fails the second time — AGENTS.md's `fs::copy` trap, in Python.
            destination.unlink(missing_ok=True)
            shutil.copyfile(source, destination)
            tables.append(name)
        (here / "manifest.rs").write_text(manifest_rs(m, texts, args.language, tables), encoding="utf-8")

    (args.out / "all.rs").write_text(all_rs(modules), encoding="utf-8")
    (args.out / "ids.txt").write_text("".join(f"{m['id']} {m['snake']}\n" for m in modules), encoding="utf-8")
    print(f"OK: {len(modules)} brain modules -> {args.out}" + (f" ({', '.join(m['id'] for m in modules)})" if modules else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
