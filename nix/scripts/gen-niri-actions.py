#!/usr/bin/env python3
"""Extracts the PINNED niri's actions and emits the Rust table.

Usage: gen-niri-actions.py <path-to-niri> <output.rs>

# Why generated, and from the binary

niri has 142 actions and versions by calendar. A hand-written list
ages in silence: a removed action becomes a command that answers "error
parsing request", and an added one never appears. Here the list comes from
`niri msg action --help` of the SAME binary that is going to run, so bumping the tag
updates the table along with it.

# What gets extracted

The name (already in kebab-case, which is the spelling used by the config and the client), the
one-line summary, and WHETHER the action requires an argument. The last comes from each
subcommand's `Usage:`: `<REFERENCE>` between `<>` is a required argument, `[OPTIONS]` is not.

# The silent fallback this avoids

clap's `--help` has changed format before. A parser that degrades in
silence would return an empty table, and the command list simply would not
have the compositor's actions — with no error anywhere. Hence the floor: if
fewer than 100 actions come back, the build STOPS.
"""

import re
import subprocess
import sys

# A deliberately loose floor. It does not claim "142": it claims the parser
# understood the format. Nailing the exact number would break on every niri release
# for a reason that is not a defect of ours.
FLOOR = 100


def actions(niri: str) -> list[tuple[str, str, bool]]:
    help_out = subprocess.run(
        [niri, "msg", "action", "--help"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout

    # clap lists `  name` on one line and the description indented on the next.
    not_in = []
    lines = help_out.split("\n")
    for i, line in enumerate(lines):
        m = re.fullmatch(r"  ([a-z][a-z0-9-]*)", line)
        if not m:
            continue
        name = m.group(1)
        # `help` belongs to clap, not to the compositor.
        if name == "help":
            continue
        resumo = ""
        for seguinte in lines[i + 1 :]:
            if not seguinte.strip():
                break
            resumo = seguinte.strip()
            break
        not_in.append((name, resumo, takes_argument(niri, name)))
    return not_in


def takes_argument(niri: str, name: str) -> bool:
    """Does the action have a mandatory POSITIONAL argument?

    `<REFERENCE>` counts, `[OPTIONS]` and `--window-id` do not: an option has a default, and
    an action with only options runs with nothing typed.
    """
    uso = subprocess.run(
        [niri, "msg", "action", name, "--help"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    for line in uso.split("\n"):
        if line.startswith("Usage:"):
            return "<" in line.split(name, 1)[-1]
    return False


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("uso: gen-niri-actions.py <caminho-do-niri> <saida.rs>")
    niri, out_path = sys.argv[1], sys.argv[2]

    table = actions(niri)
    if len(table) < FLOOR:
        sys.exit(
            f"ERRO: so {len(table)} acoes extraidas do niri, esperava ao menos "
            f"{FLOOR}.\n"
            "      O formato do `--help` provavelmente mudou. Uma tabela curta "
            "aqui\n"
            "      nao quebra nada visivelmente: as acoes so somem da lista de "
            "comandos."
        )

    lines = [
        "// GENERATED by nix/scripts/gen-niri-actions.py. Do not edit by hand.",
        "//",
        "// The source is `niri msg action --help` of the PINNED binary — the same",
        "// list the compositor accepts, and not a copy of it.",
        "",
        "/// A compositor action, as it describes itself.",
        "pub struct NiriAction {",
        "    /// The kebab-case name, which is what niri's client receives.",
        "    pub name: &'static str,",
        "    /// The corresponding COMMAND id, `niri-<name>`.",
        "    ///",
        "    /// It is emitted here, and not built at runtime, because the",
        "    /// registry requires `&'static str`: a `format!` would give a",
        "    /// `String` and would force leaking memory to fit.",
        "    pub id: &'static str,",
        "    /// The text key, `cmd-niri-<name>`.",
        "    ///",
        "    /// Its existence in both languages is asserted by the",
        "    /// `niri-actions-translated` check — here it is only a name.",
        "    pub key: &'static str,",
        "    /// Upstream's description, in English. It is NOT UI text: the",
        "    /// interface uses the key above.",
        "    pub summary: &'static str,",
        "    /// Requires a positional argument — `focus-workspace <REFERENCE>`.",
        "    pub argument: bool,",
        "}",
        "",
        "/// Every action of this niri.",
        "pub const NIRI_ACTIONS: &[NiriAction] = &[",
    ]
    for name, resumo, arg in table:
        r = resumo.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            f'    NiriAction {{ name: "{name}", id: "niri-{name}", '
            f'key: "cmd-niri-{name}", summary: "{r}", '
            f"argument: {str(arg).lower()} }},"
        )
    lines.append("];")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(table)} acoes do niri -> {out_path}")


if __name__ == "__main__":
    main()
