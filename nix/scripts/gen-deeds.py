#!/usr/bin/env python3
"""Generates the compositor's command table from `assets/compositor-deeds.nix`.

Three jobs, and the second is the one that replaces a whole VM test:

  (a) the Rust table `ronoctua_scroll::deeds::SPOKEN`;
  (b) a REFUSAL, at build time, of a verb the pinned compositor does not have
      — read out of its own source, not out of a `--help` string;
  (c) the list of text keys every language must carry, which the i18n check
      then demands.

# Why (b) is worth the parsing

The commands are free text. A verb we renamed, or one upstream dropped, is not
a compile error and not a startup error: it is a key that does nothing, and a
reply of `{"success": false, "error": "Unknown/invalid command"}` that arrives
on a socket nobody is printing. Reading the compositor's own `command_handlers`
and `handlers` tables turns that into a build failure with the id in it.

It is a WEAKER check than it looks, and the weakness is worth naming: it proves
the verb exists, never that the arguments after it parse. What proves that is
the contract test, which sends every one of these to a live compositor.
"""

from __future__ import annotations

import argparse
import json
import re
import sys

# A deed's argument, as the vocabulary spells it.
ARITIES = {"number": "Arity::Number", "word": "Arity::Word"}

# Fewer than this and the table did not come from the file it claims to.
FLOOR = 40


def die(why: str) -> None:
    print(f"ERROR: {why}", file=sys.stderr)
    raise SystemExit(1)


def verbs_of(source: str) -> set[str]:
    """Every command name the compositor accepts.

    Both tables: `handlers[]` (config and runtime) and `command_handlers[]`
    (runtime only). They are flat C arrays of `{ "name", cmd_name }`, so a
    regex is enough and a parser would be a liability.
    """
    found = set(re.findall(r'^\s*\{\s*"([a-z_0-9]+)"\s*,\s*[a-z_0-9]+\s*\}', source, re.M))
    if len(found) < 50:
        die(
            f"only {len(found)} commands were found in the compositor's source. "
            "The tables moved or changed shape, and a check that reads nothing "
            "passes everything."
        )
    return found


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--deeds", required=True, help="the declared table, as JSON")
    ap.add_argument("--commands", required=True, help="the compositor's commands.c")
    ap.add_argument("--out", required=True)
    ap.add_argument("--out-keys", required=True)
    args = ap.parse_args()

    declared = json.loads(open(args.deeds, encoding="utf-8").read())
    known = verbs_of(open(args.commands, encoding="utf-8", errors="replace").read())

    if len(declared) < FLOOR:
        die(f"{len(declared)} deeds declared, fewer than the floor of {FLOOR}")

    rows, keys, refused = [], [], []
    for ident in sorted(declared):
        entry = declared[ident]
        text = entry.get("text")
        if not isinstance(text, str) or not text:
            die(f"`{ident}` has no text to say")
        arity = entry.get("argument")
        if arity is not None and arity not in ARITIES:
            die(f"`{ident}` takes `{arity}`, which is not a kind of argument")
        if arity is None and "{n}" in text:
            die(f"`{ident}` has a placeholder but declares no argument")
        if arity is not None and "{n}" not in text:
            die(f"`{ident}` declares an argument with nowhere to put it")

        # THE VERB IS THE FIRST WORD OF THE FIRST COMMAND. What follows it is
        # this table's business; whether it exists at all is the compositor's.
        verb = text.split(";")[0].strip().split()[0]
        if verb not in known:
            refused.append((ident, verb))

        our_id = f"wm-{ident}"
        key = f"cmd-{our_id}"
        keys.append(key)
        argument = f"Some({ARITIES[arity]})" if arity else "None"
        rows.append(
            f'    Spoken {{ deed: Deed {{ id: "{our_id}", key: "{key}", '
            f"argument: {argument} }}, text: {json.dumps(text)} }},"
        )

    if refused:
        lines = "\n".join(f"  {i} says `{v}`" for i, v in refused)
        die(
            "these deeds name a command the pinned compositor does not have:\n"
            f"{lines}\n"
            "Either the spelling is wrong, or upstream dropped it. Fix\n"
            "assets/compositor-deeds.nix — a verb that does not exist is a key\n"
            "that does nothing and says nothing."
        )

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("// GENERATED by nix/scripts/gen-deeds.py. Do not edit.\n")
        f.write("// The source is assets/compositor-deeds.nix.\n\n")
        f.write("use ronoctua_compositor::Arity;\n\n")
        f.write("/// One deed, and what it says to the compositor.\n")
        f.write("#[derive(Debug, Clone, Copy)]\npub struct Spoken {\n")
        f.write("    /// The deed itself, which is contract vocabulary.\n")
        f.write("    pub deed: Deed,\n")
        f.write("    /// What to say. `{n}` is where the argument goes.\n")
        f.write("    pub text: &'static str,\n}\n\n")
        f.write("/// Every deed, sorted by id so a diff of this file reads.\n")
        f.write("pub const SPOKEN: &[Spoken] = &[\n")
        f.write("\n".join(rows))
        f.write("\n];\n")

    with open(args.out_keys, "w", encoding="utf-8") as f:
        f.write("\n".join(keys) + "\n")

    print(f"{len(rows)} deeds, all of them commands the compositor has")


if __name__ == "__main__":
    main()
