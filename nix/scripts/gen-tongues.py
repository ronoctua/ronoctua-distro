#!/usr/bin/env python3
"""The languages of content, from Nix to Rust.

`assets/tongues.nix` becomes two things and a refusal: the table
`ronoctua_player::tongues` compiles, the text keys both languages have to
carry (`tongue-<code>`, lowercase, and `tongue-<two letters>` for a language
two rows share), and the build taken down by a row that could not work.

# What is refused, and why here

A CODE OF THE WRONG SHAPE. The code goes into a subtitle file's name, a
search the door sends and a text key; a space or a stray capital would be a
file nobody finds by its name and a key that is not kebab-case.

A TWO-LETTER CODE THAT IS NOT THE CODE'S OWN. `pt-BR` is Portuguese; a row
that said otherwise would search one language and tag files as another.

A CODE TWICE, OR A SERVICE'S CODE TWICE. Two rows the door lists as two
choices would ask the service the same thing, and a found subtitle tagged with
that code would belong to either.

A ROW NEITHER SERVICE SEARCHES IN: a language a person can add and never find
anything in, with nothing on screen to say why.

A LIST WITHOUT ENGLISH: every default search is the interface's language and
then English.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

CODE = re.compile(r"^[a-z]{2,3}(?:-(?:[A-Z]{2}|[A-Z][a-z]{3}))?$")
TWO = re.compile(r"^[a-z]{2}$")
THREE = re.compile(r"^[a-z]{3}$")
OPENSUBTITLES = re.compile(r"^[a-z]{2,3}(?:-[a-z]{2})?$")
SUBDL = re.compile(r"^[A-Z]{2,3}(?:_[A-Z]{2})?$")
FIELDS = {"code", "twoLetter", "threeLetter", "opensubtitles", "subdl"}
ENGLISH = "en"


def rust_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def rust_option(s: str | None) -> str:
    return "None" if s is None else f"Some({rust_str(s)})"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tongues", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--out-keys", required=True)
    args = ap.parse_args()

    rows = json.loads(pathlib.Path(args.tongues).read_text(encoding="utf-8"))
    gaps: list[str] = []
    if not isinstance(rows, list) or not rows:
        print("ERROR: assets/tongues.nix is not a list of rows", file=sys.stderr)
        return 1

    seen: dict[str, set[str]] = {"code": set(), "opensubtitles": set(), "subdl": set()}
    for n, row in enumerate(rows):
        if not isinstance(row, dict):
            gaps.append(f"row {n}: not an attribute set")
            continue
        keys = set(row)
        if keys != FIELDS:
            gaps.append(
                f"row {n}: fields {sorted(keys)} — expected exactly {sorted(FIELDS)}"
            )
            continue
        code = row["code"]
        where = f"`{code}`"
        if not isinstance(code, str) or not CODE.match(code):
            gaps.append(f"row {n}: code {code!r} is not a language tag (`pt`, `pt-BR`)")
            continue
        if not isinstance(row["twoLetter"], str) or not TWO.match(row["twoLetter"]):
            gaps.append(f"{where}: twoLetter {row['twoLetter']!r} is not ISO 639-1")
        elif row["twoLetter"] != code.split("-")[0]:
            gaps.append(
                f"{where}: twoLetter `{row['twoLetter']}` is not the code's own language"
            )
        if not isinstance(row["threeLetter"], str) or not THREE.match(row["threeLetter"]):
            gaps.append(f"{where}: threeLetter {row['threeLetter']!r} is not ISO 639-2/B")
        os_code, subdl = row["opensubtitles"], row["subdl"]
        if os_code is not None and (not isinstance(os_code, str) or not OPENSUBTITLES.match(os_code)):
            gaps.append(f"{where}: opensubtitles {os_code!r} is not the shape its API takes")
        if subdl is not None and (not isinstance(subdl, str) or not SUBDL.match(subdl)):
            gaps.append(f"{where}: subdl {subdl!r} is not the shape its API takes")
        if os_code is None and subdl is None:
            gaps.append(f"{where}: neither service searches in it")
        for field, value in (("code", code.lower()), ("opensubtitles", os_code), ("subdl", subdl)):
            if value is None:
                continue
            if value in seen[field]:
                gaps.append(f"{where}: {field} `{value}` is named twice")
            seen[field].add(value)

    if ENGLISH not in seen["code"]:
        gaps.append("English (`en`) is missing: it is the second of every default search")

    if gaps:
        print("ERROR: assets/tongues.nix is refused:", file=sys.stderr)
        for g in gaps:
            print(f"  - {g}", file=sys.stderr)
        return 1

    lines = [
        "// GENERATED by nix/scripts/gen-tongues.py from assets/tongues.nix.",
        "// Do not edit: change the declaration and rebuild.",
        "",
        "/// Every language of content, in the order `assets/tongues.nix` names them.",
        "pub const TONGUES: &[Tongue] = &[",
    ]
    for row in rows:
        code = row["code"]
        lines.append(
            "    Tongue { "
            f"code: {rust_str(code)}, "
            f"key: {rust_str('tongue-' + code.lower())}, "
            f"two_letter: {rust_str(row['twoLetter'])}, "
            f"three_letter: {rust_str(row['threeLetter'])}, "
            f"opensubtitles: {rust_option(row['opensubtitles'])}, "
            f"subdl: {rust_option(row['subdl'])} "
            "},"
        )
    lines.append("];")
    lines.append("")
    # A LANGUAGE TWO ROWS SHARE — Portuguese, Chinese — has a name of its own
    # too, with no region: what a film's stream (`por`) or a radio's list
    # (`pt`) says is the language, and naming it Brazilian or European would
    # be a guess on screen.
    shared: dict[str, int] = {}
    for row in rows:
        shared[row["twoLetter"]] = shared.get(row["twoLetter"], 0) + 1
    neutral = sorted(two for two, n in shared.items() if n > 1)
    clash = [two for two in neutral if two in seen["code"]]
    if clash:
        print(
            f"ERROR: assets/tongues.nix is refused: {clash} are shared by two rows "
            "and are a row's code too — the language's own name would be two keys",
            file=sys.stderr,
        )
        return 1
    lines.append(
        "/// The languages SEVERAL rows share, each with a name of its own and no"
    )
    lines.append("/// region: its ISO 639-1 code, and its text key.")
    lines.append("pub const SHARED: &[(&str, &str)] = &[")
    for two in neutral:
        lines.append(f"    ({rust_str(two)}, {rust_str('tongue-' + two)}),")
    lines.append("];")
    lines.append("")
    pathlib.Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    pathlib.Path(args.out_keys).write_text(
        "".join(f"tongue-{row['code'].lower()}\n" for row in rows)
        + "".join(f"tongue-{two}\n" for two in neutral),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
