#!/usr/bin/env python3
"""Extracts niri's DEFAULT binds and emits the Rust table.

Usage: gen-default-binds.py <default-config.kdl> <output.rs>

# Why generated, and from niri's own config

The request was "every shortcut Niri supports", and their authoritative list
is the PINNED commit's `resources/default-config.kdl` — not a list of
ours. Written by hand, it would age in silence: a shortcut upstream
adds would never appear, and one it removes would become a key that answers
"error parsing request".

# What does NOT go in, and why

- `spawn` and `spawn-sh`: the default config calls `alacritty`, `fuzzel`,
  `swaylock`, `wpctl`. Those are the choices of whoever wrote the example, and we have
  our own (`LEADER w o` opens our terminal, in our scope).
- `show-hotkey-overlay`: it is NIRI's shortcut list, a second window
  competing with our manual (`LEADER h s`). Two shortcut lists are the
  problem this project spent months undoing.
- `Space`: in nested mode the leader is `Alt+Space`, and the leader's bind is
  written by hand in the config. Emitting a chord on the same key would give two
  identical binds — niri accepts it, the last one wins, and the first disappears with no warning.
- `XF86*` keys: they take no modifier. They are media and brightness, and as a
  chord they would require holding the leader to turn the volume down, which is worse than
  the key on its own. They wait for the system to handle media keys.

# The silent fallback this avoids

A parser that degrades silently returns an empty table, and the symptom would be
"shortcuts are missing" — indistinguishable from their never having been implemented. Hence the
floor: fewer than 50 binds is an error.
"""

import re
import sys

FLOOR = 50

# `Mod+Shift+Ctrl+Left cooldown-ms=150 { move-column-to-monitor-left; }`
LINE = re.compile(
    r"""^\s+Mod\+(?P<press_key>\S+)          # the key, already without the `Mod+`
        (?P<props>(?:\s+[a-z-]+=\S+)*)   # optional properties
        \s*\{\s*(?P<action>[^}]+?);\s*\}   # the action, without the semicolon
    """,
    re.VERBOSE,
)

ACTIONS_OUT = ("spawn", "spawn-sh", "show-hotkey-overlay")
KEYS_OUT = ("Space",)


def binds(path: str) -> list[tuple[str, str, str]]:
    with open(path, encoding="utf-8") as f:
        raw_text = f.read()

    inside = False
    not_in = []
    for line in raw_text.split("\n"):
        if line.startswith("binds {"):
            inside = True
            continue
        if inside and line.startswith("}"):
            break
        if not inside:
            continue
        # A whole-line comment, and the `//` the example uses to
        # show alternatives.
        if line.lstrip().startswith("//"):
            continue

        m = LINE.match(line)
        if not m:
            continue
        press_key, action = m.group("press_key"), m.group("action").strip()
        name = action.split()[0]
        if name in ACTIONS_OUT or press_key in KEYS_OUT:
            continue
        not_in.append((press_key, action, f"niri-{name}"))
    return not_in


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: gen-default-binds.py <default-config.kdl> <out.rs>")
    entry, out_path = sys.argv[1], sys.argv[2]

    table = binds(entry)
    if len(table) < FLOOR:
        sys.exit(
            f"ERROR: only {len(table)} binds extracted from niri's default config, "
            f"expected at least {FLOOR}.\n"
            "      The file's shape has probably changed. A short table "
            "here\n"
            "      breaks nothing visibly: the shortcuts simply go away."
        )

    lines = [
        "// GENERATED by nix/scripts/gen-default-binds.py. Do not edit by hand.",
        "//",
        "// The source is the PINNED niri's `resources/default-config.kdl` — the",
        "// list upstream considers to be the compositor's keyboard.",
        "",
        "/// A shortcut niri ships by default, turned into a chord of ours.",
        "pub struct DefaultBind {",
        "    /// The key WITHOUT the modifier: it is `Mod` in production and `Alt`",
        "    /// in the nested loop, and whoever knows that generates the config.",
        "    pub key: &'static str,",
        "    /// The action in KDL, verbatim from niri's config.",
        "    pub kdl: &'static str,",
        "    /// The corresponding mirrored command, for the label and the manual.",
        "    pub command: &'static str,",
        "}",
        "",
        "/// Every default bind of this niri.",
        "pub const DEFAULT_BINDS: &[DefaultBind] = &[",
    ]
    for press_key, kdl, command in table:
        k = kdl.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            f'    DefaultBind {{ key: "{press_key}", kdl: "{k}", command: "{command}" }},'
        )
    lines.append("];")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{len(table)} of niri's default binds -> {out_path}")


if __name__ == "__main__":
    main()
