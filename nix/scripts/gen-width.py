#!/usr/bin/env python3
"""How many CELLS a character occupies — the table, from Unicode's own files.

# Why a table, when the cell used to be a count

Because until the fallback chain existed, one grapheme really was one cell:
the only face was the Iosevka, it is monospaced at `0.600 em`, and every
cluster it drew advanced exactly that. `ronoctua_protocol::cells` counted
clusters and was RIGHT.

The moment the chain reached the CJK faces that stopped being true. 日本語 is
three clusters and six cells: an ideograph is designed on a square em and
advances twice what a Latin letter does, in every monospaced CJK face ever
cut. Counting it as three put every column after it in the wrong place — and
not by a rounding error, by half the width of the text.

# Why the rule is Unicode's and not a list of blocks

`East_Asian_Width` is the property that answers exactly this question, it is
maintained per release, and it is the same one every terminal uses. A list of
ranges written here would be a second opinion about Unicode, and it would go
stale one release at a time, silently, in the direction of drawing over a
neighbouring column.

`W` (Wide) and `F` (Fullwidth) are the two cells; everything else is one. `A`
(Ambiguous) is deliberately NOT wide: it covers Cyrillic, Greek and the box
drawing this interface is built out of, and treating those as two cells would
break every existing screen to help a case this system does not have (a CJK
legacy encoding).

# And why emoji come in from the other file

Their advance is a fact about the FACE, not about `East_Asian_Width` — the
colour face draws them at `1.245 em` against the cell's `0.600`, which is what
the symbol browser's `width: 2` has recorded since before the chain existed.
`Emoji_Presentation=Yes` is the property that names them, and it is the same
one `strip-emoji.py` cuts the primary face with, so the two cannot disagree
about which codepoints are emoji.
"""

from __future__ import annotations

import argparse
import pathlib
import sys


def ranges_of(text: str, wanted: set[str], field: int = 1) -> list[tuple[int, int]]:
    """Every code point range whose property value is in `wanted`."""
    found: list[tuple[int, int]] = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(";")]
        if len(parts) <= field or parts[field] not in wanted:
            continue
        first, _, last = parts[0].partition("..")
        found.append((int(first, 16), int(last or first, 16)))
    return found


def merged(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    """Sorted, with touching and overlapping ranges joined.

    Not tidiness: the lookup is a binary search over this, and two adjacent
    entries would make `partition_point` answer correctly and the table twice
    the size it needs to be.
    """
    out: list[tuple[int, int]] = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--east-asian-width", required=True)
    ap.add_argument("--emoji-data", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    wide = ranges_of(pathlib.Path(args.east_asian_width).read_text(encoding="utf-8"), {"W", "F"})
    emoji = ranges_of(pathlib.Path(args.emoji_data).read_text(encoding="utf-8"),
                      {"Emoji_Presentation"})
    if not wide:
        print("ERROR: EastAsianWidth.txt yielded no W/F ranges at all.", file=sys.stderr)
        print("      The file's shape changed; the table would say every", file=sys.stderr)
        print("      ideograph is one cell, and every CJK line would overlap.", file=sys.stderr)
        return 1
    if not emoji:
        print("ERROR: emoji-data.txt yielded no Emoji_Presentation ranges.", file=sys.stderr)
        return 1

    table = merged(wide + emoji)

    lines = [
        "// GENERATED by nix/scripts/gen-width.py from Unicode's own files. Do not edit.",
        "//",
        "// The code points that take TWO cells: `East_Asian_Width` W or F, plus",
        "// `Emoji_Presentation`. Sorted and disjoint, so the lookup is a binary",
        "// search — see `wide_char`.",
        "",
        f"/// {len(table)} ranges, from EastAsianWidth.txt and emoji-data.txt.",
        "pub(crate) const WIDE: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in table]
    lines += ["];", ""]

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    covered = sum(hi - lo + 1 for lo, hi in table)
    print(f"OK: {len(table)} ranges, {covered} code points that take two cells")
    return 0


if __name__ == "__main__":
    sys.exit(main())
