#!/usr/bin/env python3
"""Writes every speaking crate's key file into a checkout's own directory — invariant 8.

    gen-keys.py --tree <checkout> --base <language> --into <dir> [--written-exit <n>]

THE SAME BYTES AS `nix/text-keys.nix`, which writes them at Nix evaluation for
the build (`keys-agree` compares the two). This one exists for `cargo` in a
checkout: the devshell (on entry) and `.#dev` (when a fragment changes) point
`RONOCTUA_KEYS_DIR` at a directory OUTSIDE the tree that this keeps in step,
rewriting only the files whose bytes changed — so cargo, which tracks the file
each crate's `src/key.rs` includes, recompiles only the crates whose keys moved,
and a sentence edited (a value, not a name) rewrites nothing at all.

A crate speaks when its `[package.metadata.ronoctua] env` names
`RONOCTUA_KEYS_DIR`. Its file holds one constant per key of its own
`i18n/<base>.ftl`, re-exports the `key` of every crate it stands on that speaks,
and gives the start guard its keys (`ALL`, `sets`). A file of a crate that no
longer speaks is removed. A fragment in a crate that does not speak is refused,
as the evaluation refuses it.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from pathlib import Path

SPEAKS = "RONOCTUA_KEYS_DIR"
# `nix/text-keys.nix`'s `keyOf`: a message key in column 0.
KEY = re.compile(r"([a-z][a-z0-9-]*)\s*=.*", re.S)


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    raise SystemExit(1)


def names_in(text: str) -> list[str]:
    out = []
    for line in text.split("\n"):
        m = KEY.fullmatch(line)
        if m:
            out.append(m.group(1))
    return out


def const_of(name: str) -> str:
    return name.replace("-", "_").upper()


def ident_of(name: str) -> str:
    return name.replace("-", "_")


def crates(tree: Path) -> dict[str, dict]:
    root = tomllib.loads((tree / "Cargo.toml").read_text(encoding="utf-8"))
    out = {}
    for d in root["workspace"]["members"]:
        manifest = tomllib.loads((tree / d / "Cargo.toml").read_text(encoding="utf-8"))
        out[manifest["package"]["name"]] = {"dir": d, "manifest": manifest}
    return out


def speaks(c: dict) -> bool:
    env = c["manifest"]["package"].get("metadata", {}).get("ronoctua", {}).get("env", [])
    return SPEAKS in env


def uses_of(name: str, c: dict, speaking: dict) -> list[str]:
    m = c["manifest"]
    deps = m.get("dependencies", {})

    def package_of(n, spec):
        return spec.get("package", n) if isinstance(spec, dict) else n

    theirs = [n for n, spec in deps.items() if package_of(n, spec) in speaking]
    odd = [n for n in theirs if isinstance(deps[n], dict) and (deps[n].get("optional", False) or "package" in deps[n])]
    targeted = [n for t in m.get("target", {}).values() for n in t.get("dependencies", {}) if n in speaking]
    if odd:
        fail(
            f"{c['dir']}/Cargo.toml: the crates {', '.join(sorted(odd))} speak, and an optional or renamed "
            "dependency on one is not a `key` re-export nix/text-keys.nix writes"
        )
    if targeted:
        fail(
            f"{c['dir']}/Cargo.toml: the crates {', '.join(sorted(targeted))} speak, and a dependency on one "
            "only for some targets is not a `key` re-export nix/text-keys.nix writes"
        )
    return sorted(theirs)


def rust_of(name: str, c: dict, base: str, tree: Path, speaking: dict) -> str:
    d = c["dir"]
    folder = tree / d / "i18n"
    if folder.exists() and not (folder / f"{base}.ftl").is_file():
        fail(f"{d}/i18n has no {base}.ftl: the base language's file is where a crate's keys are read from")
    names = names_in((folder / f"{base}.ftl").read_text(encoding="utf-8")) if folder.exists() else []
    every = sorted(set(names))
    uses = uses_of(name, c, speaking)
    q = lambda s: f'"{s}"'  # noqa: E731
    out = [
        "// GENERATED by nix/text-keys.nix (and by nix/scripts/gen-keys.py in a checkout)\n",
        f"// from the key NAMES of {d}/i18n/{base}.ftl. Do not edit.\n",
        "//\n",
        "// One constant per key this crate says, and the keys of every crate it stands\n",
        "// on that speaks, re-exported: `key::X` names any key the crate may say. The\n",
        "// sentences are not here: they are read at run time (`RONOCTUA_TEXTS`).\n",
        "\n",
    ]
    out += [f"pub use {ident_of(u)}::key::*;\n" for u in uses]
    if uses:
        out.append("\n")
    out += [f"pub const {const_of(n)}: &str = {q(n)};\n" for n in every]
    if every:
        out.append("\n")
    out += [
        "/// The keys this crate says, in order.\n",
        f"pub static ALL: [&str; {len(every)}] = [\n",
        *[f"    {q(n)},\n" for n in every],
        "];\n",
        "\n",
        "/// This crate's keys and those of every crate it stands on that speaks, each\n",
        "/// crate once: what a program's start guard checks its texts against\n",
        "/// (`ronoctua_i18n::Keys::of`).\n",
        "pub fn sets(into: &mut Vec<(&'static str, &'static [&'static str])>) {\n",
        f"    if into.iter().any(|(by, _)| *by == {q(name)}) {{\n",
        "        return;\n",
        "    }\n",
        f"    into.push(({q(name)}, &ALL));\n",
        *[f"    {ident_of(u)}::key::sets(into);\n" for u in uses],
        "}\n",
    ]
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description="Every speaking crate's key file, written into a directory.")
    ap.add_argument("--tree", type=Path, required=True, help="the checkout")
    ap.add_argument("--base", required=True, help="the base language, whose .ftl names the keys")
    ap.add_argument("--into", type=Path, required=True, help="the directory RONOCTUA_KEYS_DIR names")
    ap.add_argument(
        "--written-exit",
        type=int,
        default=0,
        help="the status to exit with when a file was written or removed (`.#dev` recompiles then)",
    )
    args = ap.parse_args()
    tree = args.tree.resolve()
    into = args.into
    # NEVER INSIDE THE TREE: a file there is a build product in the flake's
    # source (`lean-tree`), and cargo would track it as one.
    if into.resolve().is_relative_to(tree):
        fail(f"{into} is inside {tree}: the keys are written outside the tree")

    every = crates(tree)
    speaking = {n: c for n, c in every.items() if speaks(c)}
    silent = sorted(n for n, c in every.items() if (tree / c["dir"] / "i18n").exists() and n not in speaking)
    if silent:
        fail(
            f"{', '.join(silent)} carry an i18n/ folder and do not declare {SPEAKS} in "
            "[package.metadata.ronoctua] env: their sentences would reach the texts and no program's start guard"
        )

    into.mkdir(parents=True, exist_ok=True)
    wrote = []
    for name in sorted(speaking):
        text = rust_of(name, speaking[name], args.base, tree, speaking)
        target = into / f"{name}.rs"
        # ONLY WHAT CHANGED: cargo compares the file's time, and a file
        # rewritten with the same bytes would recompile its crate for nothing.
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        draft = into / f".{name}.rs.{os.getpid()}"
        draft.write_text(text, encoding="utf-8")
        os.replace(draft, target)
        wrote.append(name)
    gone = []
    for f in sorted(into.glob("*.rs")):
        if f.stem not in speaking:
            f.unlink()
            gone.append(f.stem)
    said = f"{len(wrote)} written" + (f" ({', '.join(wrote)})" if 0 < len(wrote) <= 6 else "")
    if gone:
        said += f", {len(gone)} removed ({', '.join(gone)})"
    print(f"keys: {len(speaking)} crates speak, {said} -> {into}")
    return args.written_exit if (wrote or gone) else 0


if __name__ == "__main__":
    raise SystemExit(main())
