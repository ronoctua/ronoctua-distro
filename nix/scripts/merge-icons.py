#!/usr/bin/env python3
"""Merges several icon themes into one — section 6.6.

WHAT IT IS FOR
--------------
Exclusively for step 2 of the tray icon resolution chain (4.2):
a pixmap fallback for FOREIGN apps that bring their own `IconName`.

**No design system component consults this package** (invariant 10).
The UI's icons are glyphs from the font, generated by gen-glyphdb.py.

WHY PARSE index.theme, AND NOT GUESS FROM THE PATH
--------------------------------------------------
The themes use mutually incompatible layouts, verified on the real packages:

    Papirus, Adwaita     size-first     16x16/actions
    Zafiro, breeze       context-first  apps/22
    MoreWaita            type-first     scalable/apps

Matching by path pattern would break on at least three of the six. Each theme's
`index.theme` declares, per directory, the real Size/Context/Type/Scale
— and it is on those fields that the merge matches, as section 6.6 asks
("name + size + context + scale").

THE SOURCES' INHERITS IS IGNORED, ON PURPOSE
--------------------------------------------
Papirus inherits from breeze; MoreWaita inherits from Adwaita; Zafiro inherits from Surfn,
Numix, Numix-Circle, breeze-dark and gnome-dark. Following those chains
would drag in themes we did not choose (and do not even have) into the
result. We merge the explicit list, in our order, and the merged theme
inherits `hicolor` last — and that is all.
"""

from __future__ import annotations

import argparse
import configparser
import json
import os
import pathlib
import shutil
import sys
from collections import Counter, defaultdict

EXTS = (".svg", ".png", ".xpm")


def parse_index(theme_dir: pathlib.Path) -> dict:
    """Reads index.theme and returns {subdir: {size, scale, context, type}}."""
    idx = theme_dir / "index.theme"
    if not idx.is_file():
        return {}

    cp = configparser.RawConfigParser(strict=False, delimiters=("=",))
    cp.optionxform = str  # preserves capitals
    try:
        cp.read(idx, encoding="utf-8")
    except configparser.Error as e:
        print(f"  warning: index.theme is unreadable in {theme_dir.name}: {e}", file=sys.stderr)
        return {}

    out = {}
    for sub in cp.sections():
        if sub == "Icon Theme":
            continue
        s = cp[sub]
        try:
            size = int(s.get("Size", "0"))
        except ValueError:
            size = 0
        try:
            scale = int(s.get("Scale", "1"))
        except ValueError:
            scale = 1
        out[sub] = {
            "size": size,
            "scale": scale,
            "context": s.get("Context", "Unknown"),
            "type": s.get("Type", "Threshold"),
        }
    return out


def target_dir(meta: dict) -> str:
    """The canonical directory in the merged theme. We normalise to size-first, which
    is the most common layout and the one the spec uses in its examples."""
    ctx = meta["context"].lower().replace(" ", "-") or "unknown"
    if meta["type"].lower() == "scalable":
        return f"scalable/{ctx}"
    size = meta["size"] or 16
    scale = meta["scale"]
    suffix = f"@{scale}" if scale > 1 else ""
    return f"{size}x{size}{suffix}/{ctx}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", action="append", required=True,
                    metavar="PRIO:NAME:PATH:LICENCE",
                    help="in decreasing order of priority")
    ap.add_argument("--out", type=pathlib.Path, required=True)
    ap.add_argument("--theme-name", default="noctua")
    args = ap.parse_args()

    sources = []
    for spec in args.source:
        prio, name, path, license_ = spec.split(":", 3)
        sources.append(
            {"prio": int(prio), "name": name, "path": pathlib.Path(path), "license": license_}
        )
    sources.sort(key=lambda s: s["prio"])

    # key -> winner.  key = (name, canonical_subdir)
    claimed: dict[tuple, dict] = {}
    losers: dict[tuple, list] = defaultdict(list)
    per_theme = Counter()
    skipped_no_index = []

    for src in sources:
        dirs = parse_index(src["path"])
        if not dirs:
            skipped_no_index.append(src["name"])
            continue

        for sub, meta in dirs.items():
            d = src["path"] / sub
            if not d.is_dir():
                continue
            tgt = target_dir(meta)
            for f in sorted(d.iterdir()):
                if not f.is_file() or f.suffix.lower() not in EXTS:
                    continue
                # `foo-symbolic` is a NAME distinct from `foo`, not a
                # variant: a request for `foo` must never receive the
                # symbolic one. We do not touch the stem, so this comes for free.
                name = f.stem
                key = (name, tgt)
                if key in claimed:
                    losers[key].append(src["name"])
                    continue
                # Papirus and breeze deduplicate with relative symlinks to a
                # canonical name in the SAME directory (`wine.svg`, `epic-games.svg`).
                # They are 50-61% of the files. Dereferencing them while copying
                # would turn every link into a whole file — the result
                # jumped to 1.9 GB. We keep the target so we can recreate the link.
                link_to = None
                if f.is_symlink():
                    raw = os.readlink(f)
                    # We only preserve the link when the target is a plain sibling,
                    # with no traversal. A target in another directory becomes a copy.
                    if "/" not in raw:
                        link_to = raw

                claimed[key] = {
                    "name": name,
                    "dir": tgt,
                    "src": f,
                    "link_to": link_to,
                    "theme": src["name"],
                    "license": src["license"],
                    "format": f.suffix.lstrip("."),
                    "size": meta["size"],
                    "scale": meta["scale"],
                    "context": meta["context"],
                    "type": meta["type"],
                }
                per_theme[src["name"]] += 1

    if skipped_no_index:
        print(f"  warning: no index.theme, skipped: {skipped_no_index}", file=sys.stderr)

    # --- writes the merged tree --------------------------------------------
    root = args.out / "share" / "icons" / args.theme_name

    # Who won each (directory, file) — so we can decide whether a symlink can
    # be preserved.
    by_file = {(e["dir"], f"{e['name']}.{e['format']}"): e for e in claimed.values()}

    n_link, n_copy, n_deref = 0, 0, 0
    for entry in claimed.values():
        dst = root / entry["dir"] / f"{entry['name']}.{entry['format']}"
        dst.parent.mkdir(parents=True, exist_ok=True)

        target = entry["link_to"]
        if target:
            winner_of_target = by_file.get((entry["dir"], target))
            # It only preserves the link if the target exists in the merged theme AND was
            # won by the SAME theme. If another theme won the target, the
            # link would point at an image different from the one the source
            # intended — so we copy the real content.
            if winner_of_target and winner_of_target["theme"] == entry["theme"]:
                dst.symlink_to(target)
                n_link += 1
                continue
            n_deref += 1

        shutil.copyfile(entry["src"], dst)  # follows the link, if there is one
        n_copy += 1

    print(f"  files: {n_copy} copied, {n_link} symlinks preserved"
          + (f", {n_deref} links dereferenced (target of another theme)" if n_deref else ""))

    # --- index.theme --------------------------------------------------------
    dirs_meta = {}
    for e in claimed.values():
        dirs_meta.setdefault(e["dir"], e)

    lines = [
        "[Icon Theme]",
        f"Name={args.theme_name}",
        "Comment=ronoctua-distro icon superpack (generated, do not edit)",
        # It inherits hicolor LAST and only that: the sources' chains are
        # ignored on purpose. See this script's header.
        "Inherits=hicolor",
        "Directories=" + ",".join(sorted(dirs_meta)),
        "",
    ]
    for d in sorted(dirs_meta):
        m = dirs_meta[d]
        lines += [
            f"[{d}]",
            f"Size={m['size'] or 16}",
            f"Context={m['context']}",
            f"Type={m['type']}",
        ]
        if m["scale"] > 1:
            lines.append(f"Scale={m['scale']}")
        lines.append("")

    root.mkdir(parents=True, exist_ok=True)
    (root / "index.theme").write_text("\n".join(lines))

    # --- manifest -----------------------------------------------------------
    entries = [
        {
            "name": e["name"],
            "dir": e["dir"],
            "size": e["size"],
            "scale": e["scale"],
            "context": e["context"],
            "winner": e["theme"],
            "format": e["format"],
            "license": e["license"],
            "losers": sorted(set(losers.get((e["name"], e["dir"]), []))),
        }
        for e in sorted(claimed.values(), key=lambda x: (x["name"], x["dir"]))
    ]
    manifest = {
        "theme": args.theme_name,
        "sources": [
            {"priority": s["prio"], "name": s["name"], "license": s["license"]} for s in sources
        ],
        "entry_count": len(entries),
        "entries": entries,
    }
    doc = args.out / "share" / "doc" / f"{args.theme_name}-icons"
    doc.mkdir(parents=True, exist_ok=True)
    (doc / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False))

    # --- coverage -----------------------------------------------------------
    unique_names = {e["name"] for e in claimed.values()}
    # Names only ONE theme provides: those are the fragile ones. If that theme goes
    # away, the icon disappears and nothing warns.
    providers = defaultdict(set)
    for (name, d), e in claimed.items():
        providers[name].add(e["theme"])
        for l in losers.get((name, d), []):
            providers[name].add(l)
    fragile = sorted(n for n, ts in providers.items() if len(ts) == 1)

    cov = [
        f"# Coverage of the `{args.theme_name}` superpack",
        "",
        "Generated by `nix/scripts/merge-icons.py`. Do not edit by hand.",
        "",
        "This package exists **only** as a pixmap fallback for foreign apps",
        "(step 2 of section 4.2's chain). No component of the design system",
        "consults it — the UI's icons are glyphs of the font (invariant 10).",
        "",
        f"- Entries: **{len(entries)}**",
        f"- Distinct names: **{len(unique_names)}**",
        f"- Directories: **{len(dirs_meta)}**",
        "",
        "## Who won how much",
        "",
        "| priority | theme | entries won | licence |",
        "|---:|---|---:|---|",
    ]
    for s in sources:
        cov.append(
            f"| {s['prio']} | {s['name']} | {per_theme.get(s['name'], 0)} | {s['license']} |"
        )
    cov += [
        "",
        f"## Names supplied by a single theme: {len(fragile)}",
        "",
        "If that theme leaves the list, these icons go away and nothing warns.",
        "",
    ]
    cov += [f"- `{n}`" for n in fragile[:80]]
    if len(fragile) > 80:
        cov.append(f"- … {len(fragile) - 80} more")
    (doc / "coverage.md").write_text("\n".join(cov) + "\n")

    print(f"OK: {len(entries)} entries, {len(unique_names)} distinct names, "
          f"{len(dirs_meta)} directories")
    for s in sources:
        print(f"      prio {s['prio']}  {s['name']:24s} {per_theme.get(s['name'], 0):6d} beaten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
