/// The generated table: `Kind`, `Numbers`, `Property`, `SniffShape`,
/// `Delimiter`, `Block`, `Attribute`, `Grammar`, `Language` and the indexes.
///
/// Included at module scope rather than inside a private `mod` so the
/// generator's own documentation reaches `cargo doc` — this crate's public
/// vocabulary is largely generated, and hiding it would hide the vocabulary.
mod table {
    include!(concat!(env!("OUT_DIR"), "/syntax.rs"));
}

pub use table::{
    Attribute, Block, Delimiter, Grammar, Kind, Language, Numbers, Property, SniffShape, counts,
};

// AN EMPTY OR TRUNCATED GENERATION TAKES COMPILATION DOWN, not a test.
//
// The counts are compile-time constants, so an `assert!` inside a `#[test]`
// would be folded away and would verify nothing. As a const assertion the
// error arrives at build time, which is where a broken generator belongs.
const _: () = assert!(
    counts::LANGUAGES >= 30,
    "the syntax table came out truncated"
);
const _: () = assert!(
    counts::MIMES >= 100,
    "the MIME expansion did not run: the reach of this table is the subclass DAG"
);

/// What a piece of text IS, which becomes a colour in whoever draws.
///
/// # Why fourteen, and why not more
///
/// Every role is a colour somebody has to choose and a case every buffer
/// carries. The test each one had to pass is: **is there a file in which,
/// without this role, two different things are drawn the same and whoever
/// reads is misled?** A role that only makes a file prettier did not get in.
///
/// Two are deliberately absent and the reasons are worth keeping.
///
/// `Normal` is not a variant: ranges carry only what is NOT ordinary, and
/// ordinary text is ordinary by omission. A range per common word would double
/// the list without saying anything.
///
/// `Operator` is not a variant either, and the argument is measured rather
/// than aesthetic: whoever draws allocates a string per range inside the frame
/// that draws, so a range per brace and per semicolon is an allocation per
/// brace and per semicolon. It also defeats the purpose — the grey wall
/// becomes a wall of confetti.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Role {
    /// A comment, of whichever shape the language has.
    Comment,
    /// Quoted text, and markdown's inline code.
    String,
    /// The one thing inside a string that is NOT string: `\n`, `&`,
    /// `${HOME}`. Without it an interpolated path reads as inert.
    Escape,
    /// A numeral.
    Number,
    /// A literal that is not a numeral: `true`, `null`, `None`, `nil`, and a
    /// SCREAMING_SNAKE name.
    Constant,
    /// A reserved word.
    Keyword,
    /// A type's name, listed or Capitalised.
    Type,
    /// A name immediately followed by an opening bracket.
    Function,
    /// A marker ABOUT the thing rather than the thing: `#[derive]`,
    /// `@Override`, `#include`, a markdown fence's own line.
    Attribute,
    /// The KEY side of a key/value pair: JSON, YAML, TOML, INI, a `.desktop`
    /// entry, an HTML attribute's name.
    Property,
    /// An element's name in HTML or XML.
    Tag,
    /// The structure of a line-oriented file: a markdown `##`, a TOML
    /// `[section]`, a diff's `@@` hunk header and its `---`/`+++` lines.
    Heading,
    /// A diff line that adds.
    Added,
    /// A diff line that removes.
    Removed,
}

/// A contiguous piece with one role.
///
/// # The contract, and it is a promise and not a habit
///
/// Ranges come out **ascending**, **non-overlapping**, never empty
/// (`start < end <= text.len()`), and with both ends on `char` boundaries.
/// Whoever draws slices by these offsets INSIDE the frame that draws, and a
/// bad one is a panic on screen. The tests lock all four.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Range {
    /// Where it starts, in bytes.
    pub start: usize,
    /// Where it ends, in bytes (exclusive).
    pub end: usize,
    /// What it is.
    pub role: Role,
}

/// What one line hands to the next.
///
/// # Why this is `Copy` and eight bytes
///
/// Because whoever consumes it SCROLLS: it starts drawing at line N and must
/// not re-tokenise the file to get there. So it keeps ONE of these per line —
/// eight bytes for a ten-thousand-line file is eighty kilobytes, and the
/// alternative is a full pass per frame. Anything that made this own a
/// `String` would take `Copy` off it and put an allocation in the frame's
/// budget.
///
/// It is also why a heredoc is not here: its terminator is arbitrary text
/// discovered at run time, and text does not fit in eight bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct State {
    /// What the FILE has open. Inside a fenced language this is the fence.
    outer: Open,
    /// What the fence's INNER language has open; `Nothing` outside a fence.
    ///
    /// ONE LEVEL, and that is the whole of it: a fence cannot contain a fence.
    /// A second level would want a stack, and a stack inside a `Copy` state is
    /// a lie.
    inner: Open,
}

/// What is still open at the end of a line.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
enum Open {
    /// Nothing; the next line starts clean.
    #[default]
    Nothing,
    /// A block comment. `depth` is 1 in a language that does not nest.
    Comment {
        /// How many opens are outstanding.
        depth: u8,
    },
    /// Quoted text across lines: WHICH delimiter of the grammar opened it, and
    /// how many `#` the raw form carried.
    Text {
        /// Its index in `Grammar::strings`.
        delimiter: u8,
        /// The `#` count, for Rust's raw form.
        hashes: u8,
    },
    /// A markdown fence: what it is made of, how long it is, and the language
    /// its content is drawn with.
    ///
    /// `None` means the info string named nothing this crate knows — and then
    /// the content gets NO highlighting, which is the prose rule again.
    Fence {
        /// Its index in `Grammar::fences`.
        marker: u8,
        /// How many characters long the opening run was.
        length: u8,
        /// The language inside, when it named one.
        inner: Option<Language>,
    },
}

// THE STATE STOPPED BEING CHEAP is a compile error, not a review comment.
const _: () = assert!(
    core::mem::size_of::<State>() <= 8,
    "the state stopped being cheap: whoever scrolls keeps one of these per line"
);

impl State {
    /// A line that starts clean.
    #[must_use]
    pub const fn fresh() -> Self {
        Self {
            outer: Open::Nothing,
            inner: Open::Nothing,
        }
    }

    /// Whether anything at all is carried into the next line.
    #[must_use]
    pub const fn is_fresh(self) -> bool {
        matches!(self.outer, Open::Nothing) && matches!(self.inner, Open::Nothing)
    }
}

impl Language {
    /// Every language the table declares.
    #[must_use]
    pub fn all() -> &'static [Grammar] {
        &table::GRAMMARS
    }

    /// Its grammar.
    #[must_use]
    pub const fn grammar(self) -> &'static Grammar {
        // The enum is generated FROM the table in the table's own order, and
        // `index` is a generated `match` over the same order, so this cannot
        // miss and needs no search.
        &table::GRAMMARS[self.index()]
    }

    /// Its id, as `assets/syntax.nix` spells it.
    #[must_use]
    pub const fn id(self) -> &'static str {
        self.grammar().id
    }

    /// Its name, which is a proper noun and is not translated.
    #[must_use]
    pub const fn label(self) -> &'static str {
        self.grammar().label
    }
}

/// The language a MIME type resolves to.
///
/// The type is expected to have been settled already — this crate does not
/// sniff a file and does not know what one is. `text/plain` resolves to
/// nothing, deliberately: colouring prose is worse than not colouring it.
#[must_use]
pub fn of_mime(mime: &str) -> Option<Language> {
    table::OF_MIME
        .binary_search_by(|(name, _)| (*name).cmp(mime))
        .ok()
        .map(|n| table::OF_MIME[n].1)
}

/// The language a markdown fence's info string names.
#[must_use]
pub fn of_tag(tag: &str) -> Option<Language> {
    table::OF_TAG
        .binary_search_by(|(name, _)| (*name).cmp(tag))
        .ok()
        .map(|n| table::OF_TAG[n].1)
}

/// The language a `#!` line names.
#[must_use]
pub fn of_shebang(line: &str) -> Option<Language> {
    let rest = line.strip_prefix("#!")?;
    // The interpreter is the last path component of the first word, and
    // `#!/usr/bin/env python3` puts it in the second.
    let mut name = None;
    for word in rest.split_whitespace() {
        let base = word.rsplit('/').next().unwrap_or(word);
        if base == "env" {
            continue;
        }
        name = Some(base);
        break;
    }
    let name = name?;
    table::OF_SHEBANG
        .binary_search_by(|(known, _)| (*known).cmp(name))
        .ok()
        .map(|n| table::OF_SHEBANG[n].1)
}

/// The language a text looks like, when nothing named one.
///
/// `None` when nothing points at one — and then there is **no highlighting**,
/// which is the right answer: colouring prose as if it were code is worse than
/// not colouring, because whoever reads starts looking for meaning in a colour
/// that means nothing.
#[must_use]
pub fn guess(text: &str) -> Option<Language> {
    if let Some(first) = text.lines().next()
        && let Some(found) = of_shebang(first)
    {
        return Some(found);
    }
    // The head only: a marker that appears for the first time forty kilobytes
    // in is not what the file looks like.
    let head = &text[..text.len().min(4096)];
    for (language, markers, shape) in table::SNIFF {
        if matches!(shape, SniffShape::JsonObject) && looks_like_json(head) {
            return Some(language);
        }
        if !markers.is_empty() && markers.iter().all(|m| head.contains(m)) {
            return Some(language);
        }
    }
    None
}

/// Whether a text opens the way a JSON document does.
///
/// JSON has no keyword to look for, so it is the one language selected by
/// shape. The vocabulary of shapes is closed and the table's generator refuses
/// a third value.
fn looks_like_json(head: &str) -> bool {
    let trimmed = head.trim_start();
    (trimmed.starts_with('{') || trimmed.starts_with('[')) && trimmed.contains('"')
}

/// Highlights ONE line, given what the line before it left open.
///
/// `line` carries no `\n`; the offsets in `out` are relative to `line`. `out`
/// is cleared first, so a caller may lend one `Vec` to a whole frame.
pub fn line_into(line: &str, grammar: &Grammar, state: State, out: &mut Vec<Range>) -> State {
    out.clear();
    match grammar.kind {
        Kind::Markdown => lines::markdown(line, grammar, state, out),
        Kind::Diff => {
            lines::diff(line, out);
            state
        }
        Kind::Markup => scan::markup(line, grammar, state, out),
        Kind::Code => scan::code(line, grammar, state, out),
    }
}

/// The same, for a caller with no buffer to lend.
#[must_use]
pub fn line(text: &str, grammar: &Grammar, state: State) -> (Vec<Range>, State) {
    let mut out = Vec::new();
    let carried = line_into(text, grammar, state, &mut out);
    (out, carried)
}

/// The state each line BEGINS in — one entry per line, entry zero fresh.
///
/// One pass, building no ranges. This is what a scrolling consumer keeps, and
/// it is what makes drawing line nine thousand cost the work of one line.
#[must_use]
pub fn states(text: &str, grammar: &Grammar) -> Vec<State> {
    let mut out = Vec::new();
    let mut carried = State::fresh();
    let mut scratch = Vec::new();
    for row in text.lines() {
        out.push(carried);
        carried = line_into(row, grammar, carried, &mut scratch);
    }
    out
}

/// The whole text at once, with offsets relative to `text`.
///
/// What a panel showing one copied fragment uses. A file being scrolled wants
/// [`states`] and [`line_into`] instead.
#[must_use]
pub fn ranges(text: &str, language: Language) -> Vec<Range> {
    let grammar = language.grammar();
    let mut out = Vec::new();
    let mut carried = State::fresh();
    let mut scratch = Vec::new();
    let mut at = 0usize;
    for row in text.split_inclusive('\n') {
        let bare = row.strip_suffix('\n').unwrap_or(row);
        carried = line_into(bare, grammar, carried, &mut scratch);
        out.extend(scratch.iter().map(|r| Range {
            start: at + r.start,
            end: at + r.end,
            role: r.role,
        }));
        at += row.len();
    }
    out
}

/// Is this byte part of a word?
///
/// THE ONE RULE, and the generator uses the same one: a keyword the scanner
/// could never match is a dead row that looks deliberate.
pub(crate) const fn is_word_char(c: u8) -> bool {
    c.is_ascii_alphanumeric() || c == b'_' || c == b'$' || c == b'?'
}

/// Pushes a range, unless it would be empty.
///
/// One place, because an empty range is an allocation for nothing in whoever
/// draws, and the contract says ranges are never empty.
pub(crate) fn push(out: &mut Vec<Range>, start: usize, end: usize, role: Role) {
    if start < end {
        out.push(Range { start, end, role });
    }
}
