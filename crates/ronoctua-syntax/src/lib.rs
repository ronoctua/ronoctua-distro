//! Where each colour of a line of text begins and ends.
//!
//! # It gives back a ROLE, and never a colour
//!
//! Because a colour is a token value, and this crate is compiled inside
//! `wasm32-wasip2` components, which do not receive token values (invariant
//! 11). What turns a role into a colour is whoever draws — the same wall
//! `ronoctua_design::Palette` already keeps for layout.
//!
//! # Why the tokeniser is ours, still
//!
//! `syntect` brings a regex engine and about a megabyte of definitions into a
//! process that has to draw inside one frame; `tree-sitter` asks for a Nix
//! dependency PER LANGUAGE. What is actually wanted is to stop a block of text
//! being a grey wall, and for that a few hundred lines and a declared table get
//! it right often enough for no dependencies at all.
//!
//! The table is `assets/syntax.nix`, generated by `nix/scripts/gen-syntax.py`.
//! Thirty-seven rows there resolve a hundred and fifty-eight MIME types,
//! because the claims are expanded through freedesktop's own subclass DAG:
//! one claim on `application/xml` brings forty-nine descendants.
//!
//! # It is one line at a time, and that is the whole design
//!
//! Whoever consumes this SCROLLS. It must be possible to start drawing at line
//! four thousand without tokenising the four thousand above it, so [`line`]
//! takes a [`State`] and gives one back, and [`states`] computes one per line
//! in a single pass. Eight bytes a line is the price; the alternative is a full
//! pass through the file on every frame.

#![no_std]
#![forbid(unsafe_code)]

