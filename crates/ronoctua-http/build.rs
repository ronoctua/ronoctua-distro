//! Copies the cache policy Nix generates (`RONOCTUA_CACHE_RS`, from
//! `assets/cache.nix`) into `OUT_DIR`, for `tlsGroupsHosts` — the most hosts
//! `groups` keeps.
//!
//! Only with the `tls` feature: the loopback transports keep nothing, and a
//! crate that links this for a chunk decoder must not need a Nix variable to
//! build. Copying and not generating, for invariant 5; the destination is
//! deleted first because a file from the store is read-only and `fs::copy`
//! carries the mode.

use std::{env, fs, path::PathBuf};

fn main() {
    println!("cargo:rerun-if-env-changed=RONOCTUA_CACHE_RS");
    if env::var_os("CARGO_FEATURE_TLS").is_none() {
        return;
    }
    let generated = env::var("RONOCTUA_CACHE_RS").unwrap_or_else(|_| {
        panic!(
            "RONOCTUA_CACHE_RS is not set.\n\
             \n\
             The cache policy is generated by Nix out of assets/cache.nix.\n\
             Enter the environment with `direnv allow` (or `nix develop`), which\n\
             sets the variable, or build through the flake with `nix build`."
        )
    });
    println!("cargo:rerun-if-changed={generated}");
    let destination = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("cache.rs");
    let _ = fs::remove_file(&destination);
    fs::copy(&generated, &destination)
        .unwrap_or_else(|e| panic!("could not copy {generated} -> {destination:?}: {e}"));
}
