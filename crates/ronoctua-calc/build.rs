//! Copies the two tables Nix generates into `OUT_DIR`: the units
//! (`RONOCTUA_UNITS_RS`, from `assets/units.nix`) and the cache policy
//! (`RONOCTUA_CACHE_RS`, for `ratesStaleHours`).
//!
//! Copying and not generating: the one source of truth is the `.nix` file, and
//! generating here would reimplement Nix logic (invariant 5). The destination
//! is deleted first because a file from the store is read-only and `fs::copy`
//! carries the mode — the second build would fail with "Permission denied".

use std::{env, fs, path::PathBuf};

fn bring(variable: &str, file: &str) {
    println!("cargo:rerun-if-env-changed={variable}");
    let generated = env::var(variable).unwrap_or_else(|_| {
        panic!(
            "{variable} is not set.\n\
             \n\
             It is generated by Nix. Enter the environment with `direnv allow`\n\
             (or `nix develop`), which sets the variable, or build through the\n\
             flake with `nix build`."
        )
    });
    println!("cargo:rerun-if-changed={generated}");
    let destination = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join(file);
    let _ = fs::remove_file(&destination);
    fs::copy(&generated, &destination)
        .unwrap_or_else(|e| panic!("could not copy {generated} -> {destination:?}: {e}"));
}

fn main() {
    bring("RONOCTUA_UNITS_RS", "units.rs");
    bring("RONOCTUA_CACHE_RS", "cache.rs");
}
