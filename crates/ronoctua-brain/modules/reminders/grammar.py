#!/usr/bin/env python3
"""The words a reminder's answer is read with, from the module's texts to Rust.

Every key of the module's fragments that begins with `<id>-grammar-` is a
CLASS of word ("tomorrow", "every", "monday"), and its value lists the words of
that class in that language, separated by commas. This writes them, per
declared language and in the languages' order, as one Rust table:

    pub const PHRASES: &[(&str, &str, &[&str])] = &[
        ("en-GB", "tomorrow", &["tomorrow", "tmrw"]),
        ...
    ];

`grammar.rs` knows the classes and the shapes; the words are the languages',
so a third language is a third `.ftl` and nothing in Rust. The `.ftl` is read
by `gen-i18n.py`'s own `keys()` — one reader of a `.ftl`, not two.

Usage:
    grammar.py --parser <gen-i18n.py> --texts <i18n dir> --prefix <id>-grammar-
               --language <lang> [--language <lang> ...] --out <file.rs>
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path


def fail(what: str) -> None:
    print(f"ERROR: the reminders' grammar: {what}", file=sys.stderr)
    raise SystemExit(1)


def rust_str(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{out}"'


def main() -> int:
    ap = argparse.ArgumentParser(description="The reminders' words, as a Rust table.")
    ap.add_argument("--parser", type=Path, required=True)
    ap.add_argument("--texts", type=Path, required=True)
    ap.add_argument("--prefix", required=True)
    ap.add_argument("--language", action="append", required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    spec = importlib.util.spec_from_file_location("gen_i18n", args.parser)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    rows: list[str] = []
    classes: dict[str, set[str]] = {}
    for language in args.language:
        texts = module.keys(args.texts / f"{language}.ftl")
        mine = {k[len(args.prefix):]: v for k, v in texts.items() if k.startswith(args.prefix)}
        if not mine:
            fail(f"{language}.ftl has no `{args.prefix}*` key")
        classes[language] = set(mine)
        for word, value in sorted(mine.items()):
            phrases = [p.strip() for p in value.split(",") if p.strip()]
            if not phrases:
                fail(f"{language}.ftl: `{args.prefix}{word}` lists no words")
            listed = ", ".join(rust_str(p) for p in phrases)
            rows.append(f"    ({rust_str(language)}, {rust_str(word)}, &[{listed}]),")

    # EVERY LANGUAGE HAS EVERY CLASS: one that forgot a class would read no
    # answer that needs it, and say nothing about why.
    first = args.language[0]
    for language, have in classes.items():
        if have != classes[first]:
            fail(f"{language} and {first} have different classes: {sorted(have ^ classes[first])}")

    out = [
        "// GENERATED by `grammar.py` out of the module's own `i18n/*.ftl`.",
        "// Do not edit: it vanishes at the next build.",
        "",
        "/// Every word of the reminders' grammar: the language, the class, and the",
        "/// words of that class in that language, as they are written in the texts.",
        "pub const PHRASES: &[(&str, &str, &[&str])] = &[",
        *rows,
        "];",
        "",
    ]
    args.out.write_text("\n".join(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
