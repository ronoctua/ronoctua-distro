//! Loads the DISTRO's brain modules as data: each manifest Nix generated, and
//! the shared half of a module another crate names.
//!
//! This build script does NOT generate anything — it only locates the
//! finished files. Generating here would be reimplementing Nix logic
//! (invariant 5) and would leave the source of truth.
//!
//! # What it compiles, and what it never does
//!
//! A module is a folder, `modules/<id>/`, and Nix generates its manifest —
//! `RONOCTUA_BRAIN_MODULES_DIR/<id>/manifest.rs` — and the views of all of
//! them, `distro.rs` (the library's part, `nix/brain-modules-rs.nix`). What
//! this script adds is the one thing Nix cannot know: where this crate is on
//! disk. It writes `manifests.rs` — one shim per module that includes its
//! manifest and, for a module whose folder carries one (`shared.txt` says
//! which), its `shared.rs` by an absolute `#[path]`; then `distro.rs` — which
//! `src/compiled.rs` includes.
//!
//! NEVER a module's `module.rs`, and never a person's module: those are the
//! daemon's (`ronoctua-brain-daemon`), whose own `build.rs` loads them. This
//! crate is what the footer links, and a module's code here would recompile
//! the footer for every line of it.
//!
//! # What it watches, and why so little
//!
//! The table (a store path, by the variable) and nothing in `modules/`: a
//! file a build script watches is one whose every edit re-runs it — and a
//! re-run build script recompiles the crate, and with it the footer. What the
//! compiler reads (a manifest, a shared half) it tracks by itself; what this
//! script decides — which modules there are, which carry a shared half — Nix
//! decided, and a new folder or a new `shared.rs` reaches here by re-entering
//! the environment. The folders and the table are still COMPARED, here
//! whenever the script runs and by the daemon's script on every edit, so a
//! stale environment is refused with what fixes it rather than compiled
//! wrong.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

/// The variable `nix/rust.nix` sets to the library's part.
const MODULES: &str = "RONOCTUA_BRAIN_MODULES_DIR";

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    manifests(&out);
}

/// Writes `manifests.rs`: one shim per distro module, then the generated
/// views (`IDS`, `MANIFESTS`, `manifest`), for `src/compiled.rs` to include.
///
/// The ids and their Rust names come from `ids.txt`, which the generator
/// wrote out of the same folders; nothing here derives a name. A mismatch
/// with the folders on disk stops the build, naming each folder and what
/// fixes it.
fn manifests(out: &Path) {
    println!("cargo:rerun-if-env-changed={MODULES}");
    let generated = PathBuf::from(env::var(MODULES).unwrap_or_else(|_| {
        panic!(
            "{MODULES} is not set.\n\
             \n\
             The brain's modules are generated by Nix out of their folders\n\
             (`nix/brain-modules.nix`). Enter the environment with `direnv allow`\n\
             (or `nix develop`), which sets the variable, or build through the\n\
             flake with `nix build`.\n\
             \n\
             Generating it here would reimplement Nix logic (invariant 5)."
        )
    }));
    let listed_at = generated.join("ids.txt");
    let shared_at = generated.join("shared.txt");
    let views = generated.join("distro.rs");
    for watched in [&listed_at, &shared_at, &views] {
        println!("cargo:rerun-if-changed={}", watched.display());
    }
    // A TABLE FROM BEFORE THE BRAIN WAS TWO CRATES has no views of its own:
    // an environment entered before, which only re-entering mends.
    if !views.is_file() || !shared_at.is_file() {
        panic!(
            "{MODULES} is {generated:?}, which is not the library's part (no `distro.rs` or\n\
             `shared.txt`): an environment entered before the brain was two crates,\n\
             or the daemon's part handed to the library. Re-enter `nix develop`\n\
             (or `direnv reload`)."
        );
    }
    let listed = fs::read_to_string(&listed_at)
        .unwrap_or_else(|e| panic!("could not read {listed_at:?}: {e}"));
    // `<id> <snake> distro` per line, in the generator's order — and only the
    // distro's: a person's module in the library's table is a table from the
    // daemon's part, handed to the wrong crate.
    let named: Vec<(&str, &str)> = listed
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let mut words = l.split(' ');
            match (words.next(), words.next(), words.next(), words.next()) {
                (Some(id), Some(snake), Some("distro"), None) => (id, snake),
                _ => panic!(
                    "{listed_at:?}: `{l}` is not `<id> <snake> distro`; the library's table \
                     lists the distro's modules alone (a person's module is the daemon's)"
                ),
            }
        })
        .collect();
    let shared_text = fs::read_to_string(&shared_at)
        .unwrap_or_else(|e| panic!("could not read {shared_at:?}: {e}"));
    let shared: Vec<&str> = shared_text
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    for id in &shared {
        if !named.iter().any(|(i, _)| i == id) {
            panic!("{shared_at:?} lists `{id}`, which {listed_at:?} does not");
        }
    }

    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let folder = crate_dir.join("modules");
    let ids: Vec<&str> = named.iter().map(|(id, _)| *id).collect();
    let mut why = disagreement(&folder, &ids, &listed_at);
    why.push_str(&halves_disagree(&folder, &ids, &shared, &shared_at));
    if !why.is_empty() {
        panic!("the brain's modules and the generated table disagree.\n{why}");
    }

    // `{:?}` OF A PATH IS A RUST STRING LITERAL, quotes and escapes included.
    let mut shims = String::new();
    for (id, snake) in &named {
        let manifest = generated.join(id).join("manifest.rs");
        if shared.contains(id) {
            let half = folder.join(id).join("shared.rs");
            shims.push_str(&format!(
                "/// The brain module `{id}`, as data: the manifest Nix generated,\n\
                 /// and the half of it its readers share (`shared.rs`).\n\
                 pub mod {snake} {{\n    \
                     include!({manifest:?});\n    \
                     #[path = {half:?}]\n    \
                     mod shared;\n    \
                     pub use shared::*;\n\
                 }}\n\n"
            ));
        } else {
            shims.push_str(&format!(
                "/// The brain module `{id}`, as data: the manifest Nix generated.\n\
                 pub mod {snake} {{\n    \
                     include!({manifest:?});\n\
                 }}\n\n"
            ));
        }
    }
    shims.push_str(&format!("include!({views:?});\n"));

    let destination = out.join("manifests.rs");
    let _ = fs::remove_file(&destination);
    fs::write(&destination, shims)
        .unwrap_or_else(|e| panic!("could not write {destination:?}: {e}"));
}

/// What differs between the folders in `folder` and the ids the table lists,
/// said with what fixes each — empty when they agree.
///
/// BOTH DIRECTIONS, EACH NAMED: what fixes a folder Nix did not list is not
/// what fixes an id with no folder.
fn disagreement(folder: &Path, ids: &[&str], listed_at: &Path) -> String {
    let present = folders_in(folder);
    let unlisted: Vec<&str> = present
        .iter()
        .map(String::as_str)
        .filter(|id| !ids.contains(id))
        .collect();
    let gone: Vec<&str> = ids
        .iter()
        .copied()
        .filter(|id| !present.iter().any(|p| p == id))
        .collect();
    let mut why = String::new();
    if !unlisted.is_empty() {
        // THE USUAL CAUSE IS GIT, NOT THE ENVIRONMENT: the table is made from
        // the folders the FLAKE sees, and the flake sees only what git tracks.
        why.push_str(&format!(
            "\n\
             folders in {folder:?} that Nix did not list: {}\n\
             \n\
             Nix reads the folders the flake sees, and the flake sees only the files\n\
             git tracks: a new folder is usually one git does not know yet.\n\
             \n\
             {}\n\
             \n\
             and then re-enter `nix develop` (or `direnv reload`).\n",
            unlisted.join(", "),
            unlisted
                .iter()
                .map(|id| format!("    git add -N crates/ronoctua-brain/modules/{id}"))
                .collect::<Vec<_>>()
                .join("\n"),
        ));
    }
    if !gone.is_empty() {
        why.push_str(&format!(
            "\n\
             ids in {listed_at:?} with no folder in {folder:?}: {}\n\
             \n\
             The table was generated when the environment was entered, and the\n\
             folder is gone since. Re-enter `nix develop` (or `direnv reload`).\n",
            gone.join(", "),
        ));
    }
    why
}

/// What differs between the shared halves on disk and the ones the table
/// lists — empty when they agree.
fn halves_disagree(folder: &Path, ids: &[&str], shared: &[&str], shared_at: &Path) -> String {
    let on_disk: Vec<&str> = ids
        .iter()
        .copied()
        .filter(|id| folder.join(id).join("shared.rs").is_file())
        .collect();
    let unlisted: Vec<&str> = on_disk
        .iter()
        .copied()
        .filter(|id| !shared.contains(id))
        .collect();
    let gone: Vec<&str> = shared
        .iter()
        .copied()
        .filter(|id| !on_disk.contains(id))
        .collect();
    let mut why = String::new();
    if !unlisted.is_empty() {
        why.push_str(&format!(
            "\n\
             modules whose folder has a `shared.rs` that {shared_at:?} does not list: {}\n\
             \n\
             Nix decides which modules carry a shared half, from the files the\n\
             flake sees: `git add -N` the new file and re-enter `nix develop`\n\
             (or `direnv reload`).\n",
            unlisted.join(", "),
        ));
    }
    if !gone.is_empty() {
        why.push_str(&format!(
            "\n\
             modules {shared_at:?} lists as carrying a `shared.rs` that has none: {}\n\
             \n\
             The table was generated when the environment was entered, and the\n\
             file is gone since. Re-enter `nix develop` (or `direnv reload`).\n",
            gone.join(", "),
        ));
    }
    why
}

/// The folders directly under `folder`, sorted; none when it is not there.
fn folders_in(folder: &Path) -> Vec<String> {
    let mut present: Vec<String> = match fs::read_dir(folder) {
        Ok(entries) => entries
            .filter_map(Result::ok)
            .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect(),
        Err(_) => Vec::new(),
    };
    present.sort();
    present
}
