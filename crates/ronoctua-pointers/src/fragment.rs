//! The file the compositor includes: `$XDG_CONFIG_HOME/ronoctua/scroll-pointers.conf`.
//!
//! # WHY A FILE, when every change is also asked live
//!
//! Because the compositor forgets everything asked over the socket when it
//! re-reads its configuration, and the display view re-reads on every screen
//! change. A cursor that went back to the first seat every time a monitor
//! was turned would be a cursor nobody could keep. The file is what survives
//! a re-read and a reboot; the live ask is what makes a change visible
//! before either.
//!
//! # AND THE ONLY WAY TO DETACH
//!
//! `seat … attach` MOVES a device, and nothing takes one back: the
//! compositor has no detach. Giving a device back to the first seat is
//! writing a file where its seat no longer names it and re-reading — the
//! re-read destroys a seat left with no configuration, and its devices fall
//! to the fallback, which is `seat0`.
//!
//! # ONE SPELLING
//!
//! A config line and an IPC command are the same text here, so this borrows
//! the adapter's builders instead of writing a second grammar that could
//! drift from the first.

use std::fmt::Write as _;

use anyhow::Result;
use ronoctua_compositor::SeatAsk;
use ronoctua_scroll::wire;

use crate::plan::Plan;
use crate::prefs::{FIRST, Preferences};

/// The file's name inside the config directory. The compositor's config
/// includes exactly this name — `pointers-fragment-has-one-name` holds the
/// two together.
pub const FILE: &str = "scroll-pointers.conf";

/// The name of the cursor theme painted with `colour`, as `nix/cursors.nix`
/// builds it. The eight colours are the same in every colour scheme — a
/// cursor's colour is how a person tells which hand is which, and a scheme
/// switch must not repaint it — so the name carries only the number.
#[must_use]
pub fn theme_name(colour: u8) -> String {
    format!("ronoctua-pointer-{}", u16::from(colour) + 1)
}

/// The text of the fragment.
///
/// # Errors
///
/// An identifier or a seat name that could end a command early — which a
/// real device never has, and which is refused rather than written.
pub fn text_of(plan: &Plan, prefs: &Preferences) -> Result<String> {
    let mut out = String::from(
        "# Generated by ronoctua-pointers. Edited by the screen at LEADER s i;\n\
         # a change made here by hand is overwritten by the next one made there.\n",
    );
    let _ = writeln!(out, "{}", wire::focus_command(prefs.focus));
    let _ = writeln!(
        out,
        "{}",
        wire::seat_command("*", &SeatAsk::HideAfter(prefs.hide_after_ms))?
    );
    let _ = writeln!(
        out,
        "{}",
        wire::seat_command("*", &SeatAsk::HideWhileTyping(prefs.hide_while_typing))?
    );
    for c in &plan.cursors {
        // THE FIRST SEAT IS NEVER ATTACHED TO: it is the fallback, and a
        // device given back to it gets there by NOT being named anywhere.
        if c.number != FIRST {
            for id in &c.devices {
                let _ = writeln!(
                    out,
                    "{}",
                    wire::seat_command(&c.seat, &SeatAsk::Attach(id.clone()))?
                );
            }
        }
        let _ = writeln!(
            out,
            "{}",
            wire::seat_command(
                &c.seat,
                &SeatAsk::Cursor {
                    theme: theme_name(c.colour),
                    size: prefs.size,
                }
            )?
        );
    }
    for d in &plan.devices {
        for s in d.settings.present() {
            let _ = writeln!(out, "{}", wire::input_command(&d.id, s)?);
        }
    }
    Ok(out)
}

/// The keyboards' lines, after the pointers': each twin attached to the seat
/// of its cursor (the first seat is the fallback, never attached to), and
/// its whole block of settings — see [`crate::keyboards`].
///
/// # Errors
///
/// A name a command cannot carry.
pub fn keyboards_text(keys: &[crate::keyboards::KeyboardPlan]) -> Result<String> {
    let mut out = String::new();
    for k in keys {
        if k.cursor != FIRST {
            let _ = writeln!(
                out,
                "{}",
                wire::seat_command(
                    &crate::plan::seat_of(k.cursor),
                    &SeatAsk::Attach(k.twin.clone())
                )?
            );
        }
        for s in &k.settings {
            let _ = writeln!(out, "{}", wire::keyboard_command(&k.twin, s)?);
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::plan::plan;
    use ronoctua_compositor::{Device, DeviceKind, PointerSettings, SendEvents};

    fn mouse(id: &str) -> Device {
        Device {
            id: id.to_owned(),
            name: id.to_owned(),
            kind: DeviceKind::Mouse,
            settings: PointerSettings {
                send_events: Some(SendEvents::Enabled),
                natural_scroll: Some(false),
                ..PointerSettings::default()
            },
        }
    }

    #[test]
    fn the_whole_grammar_comes_out_at_once() {
        // ONLY WHAT WAS CHOSEN is written: the mice report `natural_scroll`
        // and nobody chose it, so it stays whatever the device says — a
        // fragment that wrote every current value would freeze each device's
        // defaults into the file on the first look.
        let devices = vec![mouse("1:1:First_Mouse"), mouse("2:2:Second_Mouse")];
        let prefs = Preferences {
            detect: true,
            ..Preferences::default()
        };
        let text = text_of(&plan(&devices, &prefs), &prefs).unwrap();
        assert_eq!(
            text,
            "# Generated by ronoctua-pointers. Edited by the screen at LEADER s i;\n\
             # a change made here by hand is overwritten by the next one made there.\n\
             focus_follows_mouse no\n\
             seat * hide_cursor 0\n\
             seat * hide_cursor when-typing disable\n\
             seat seat0 xcursor_theme ronoctua-pointer-1 24\n\
             seat ronoctua-cursor-2 attach \"2:2:Second_Mouse\"\n\
             seat ronoctua-cursor-2 xcursor_theme ronoctua-pointer-2 24\n\
             input \"1:1:First_Mouse\" events enabled\n\
             input \"2:2:Second_Mouse\" events enabled\n"
        );
    }

    /// Every setting there is, chosen for every mouse.
    fn everything() -> PointerSettings {
        use ronoctua_compositor::{
            AccelProfile, ButtonMap, ClickMethod, DragLock, FingerDrag, ScrollMethod,
        };
        PointerSettings {
            send_events: Some(SendEvents::DisabledOnExternalMouse),
            accel_speed: Some(-0.25),
            accel_profile: Some(AccelProfile::Flat),
            natural_scroll: Some(true),
            left_handed: Some(false),
            tap: Some(true),
            tap_button_map: Some(ButtonMap::Lmr),
            tap_drag: Some(true),
            tap_drag_lock: Some(DragLock::Sticky),
            finger_drag: Some(FingerDrag::ThreeFinger),
            click_method: Some(ClickMethod::Clickfinger),
            clickfinger_button_map: Some(ButtonMap::Lrm),
            middle_emulation: Some(true),
            scroll_method: Some(ScrollMethod::OnButtonDown),
            scroll_button: Some(274),
            scroll_button_lock: Some(true),
            disable_while_typing: Some(true),
            disable_while_trackpointing: Some(false),
            scroll_factor: Some(1.5),
        }
    }

    /// EVERY LINE THE WRITER CAN EMIT, pinned as one raw literal — and it is
    /// what `pointers-fragment-validates` hands to a real compositor. A pass
    /// on the short fragment above would prove the seats and nothing about
    /// the nineteen spellings of a setting.
    #[test]
    fn every_line_the_writer_can_emit() {
        let full = Device {
            id: "1133:50498:Logitech_Wireless_Receiver_Mouse".to_owned(),
            name: "Logitech Wireless Receiver Mouse".to_owned(),
            kind: DeviceKind::Mouse,
            settings: everything(),
        };
        let devices = vec![mouse("1:1:First_Mouse"), full];
        let prefs = Preferences {
            mice: everything(),
            hide_after_ms: 3000,
            hide_while_typing: true,
            focus: ronoctua_compositor::FocusFollows::Always,
            detect: true,
            ..Preferences::default()
        };
        let text = text_of(&plan(&devices, &prefs), &prefs).unwrap();
        assert_eq!(
            text,
            r#"# Generated by ronoctua-pointers. Edited by the screen at LEADER s i;
# a change made here by hand is overwritten by the next one made there.
focus_follows_mouse always
seat * hide_cursor 3000
seat * hide_cursor when-typing enable
seat seat0 xcursor_theme ronoctua-pointer-1 24
seat ronoctua-cursor-2 attach "1133:50498:Logitech_Wireless_Receiver_Mouse"
seat ronoctua-cursor-2 xcursor_theme ronoctua-pointer-2 24
input "1:1:First_Mouse" events disabled_on_external_mouse
input "1:1:First_Mouse" natural_scroll enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" events disabled_on_external_mouse
input "1133:50498:Logitech_Wireless_Receiver_Mouse" pointer_accel -0.250
input "1133:50498:Logitech_Wireless_Receiver_Mouse" accel_profile flat
input "1133:50498:Logitech_Wireless_Receiver_Mouse" natural_scroll enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" left_handed disabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" scroll_factor 1.500
input "1133:50498:Logitech_Wireless_Receiver_Mouse" tap enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" tap_button_map lmr
input "1133:50498:Logitech_Wireless_Receiver_Mouse" drag enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" drag_lock enabled_sticky
input "1133:50498:Logitech_Wireless_Receiver_Mouse" three_finger_drag three_finger
input "1133:50498:Logitech_Wireless_Receiver_Mouse" click_method clickfinger
input "1133:50498:Logitech_Wireless_Receiver_Mouse" clickfinger_button_map lrm
input "1133:50498:Logitech_Wireless_Receiver_Mouse" middle_emulation enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" scroll_method on_button_down
input "1133:50498:Logitech_Wireless_Receiver_Mouse" scroll_button 274
input "1133:50498:Logitech_Wireless_Receiver_Mouse" scroll_button_lock enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" dwt enabled
input "1133:50498:Logitech_Wireless_Receiver_Mouse" dwtp disabled
"#
        );
    }

    #[test]
    fn a_device_given_back_is_named_nowhere() {
        let devices = vec![mouse("1:1:First_Mouse"), mouse("2:2:Second_Mouse")];
        let mut prefs = Preferences::default();
        for id in ["1:1:First_Mouse", "2:2:Second_Mouse"] {
            prefs.devices.entry(id.into()).or_default().cursor = Some(FIRST);
        }
        let text = text_of(&plan(&devices, &prefs), &prefs).unwrap();
        assert!(!text.contains("attach"), "{text}");
        assert!(!text.contains("ronoctua-cursor-2"), "{text}");
    }
}
