/// The value column, yielding in a narrow window.
fn value_column(ctx: &Context) -> u16 {
    VALUE_COLUMN.min(ctx.columns / 2)
}

/// How many cells sit between the label and the value, for the marks.
///
/// **Two, always** — including on the lines that have no mark at all. It is
/// the same rule the symbols browser wrote for its own marker: the drawing
/// starts after them on every line, because reserving space only where there
/// is a mark would make the value column move about from line to line.
const MARK_CELLS: u16 = 2;

/// What a sheet line responds to.
///
/// # Why this is a table, and not a `match` in every place
///
/// Because the affordance was scattered across `step_by`, `type_char`, `delete`
/// and the `Paste` dispatch — and the **drawing consulted none of them**. The
/// 24 lines of the sheet looked exactly alike, and the side arrow did three
/// different things without warning: it changed the value, it switched icons,
/// or (on the color line) **nothing**, silently.
///
/// Drawing the mark from a second list would only postpone the problem: it
/// would diverge on the first new adjustment, and a mark that promises a key
/// that does nothing is worse than no mark at all. Here there is one source,
/// and whoever acts asks it **before** acting.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Affordance {
    /// The side arrows change this value.
    arrows: bool,
    /// You can type (and delete, and paste) on this line.
    types_into: bool,
    /// `Enter` here RESTORES the default instead of copying.
    ///
    /// # Why it needed a mark of its own
    ///
    /// The same `Enter` does two things depending on the line: on the 5
    /// adjustments it restores, on the 19 formats it copies. Nothing said so.
    /// Whoever set the stroke to 3.5 and pressed `Enter` expecting to confirm
    /// LOST the adjustment, with nothing on screen to explain it.
    ///
    /// Making `Enter` copy everywhere would have been the other way out, and it
    /// is worse: an adjustment line is not a format, so there would be nothing
    /// to copy — the behaviour would have to be invented.
    restores: bool,
}

/// What a line shows about what it responds to.
///
/// It is the [`Affordance`] plus the state that only exists at the moment:
/// `typing` says whether the field is **receiving text right now**, and it
/// is that flag that decides whether the next digit replaces or appends. It
/// had no representation on screen — the value was identical on both sides.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
struct Mark {
    affordance: Option<Affordance>,
    typing: bool,
}

impl Mark {
    /// A line that responds to nothing — the informational ones.
    const fn no_one() -> Self {
        Self {
            affordance: None,
            typing: false,
        }
    }

    /// The mark of an action line.
    const fn kdl_of(n: usize, typing: bool) -> Self {
        Self {
            affordance: Some(affordance(n)),
            typing,
        }
    }

    /// The glyphs, in the two cells reserved before the value.
    ///
    /// Icons are **tokens** (invariant 10): whoever knows the codepoint is the
    /// host, and a name that does not exist does not compile here — the enum
    /// is generated.
    fn draw(self, line: u16, column: u16, target: bool) -> Vec<Command> {
        let Some(a) = self.affordance else {
            return Vec::new();
        };
        if column < MARK_CELLS {
            // Window too narrow: the label no longer fits, and the mark would be
            // drawn on top of it.
            return Vec::new();
        }
        let mut out = Vec::new();
        let mut mark_of = |desloc: u16, icon: Icon, aceso: bool| {
            out.push(Command::Text(TextCommand {
                line,
                column: column - MARK_CELLS + desloc,
                content: Text::Icon(icon),
                // LIT ONLY WHILE IT IS ACTING. At rest it is affordance — it says
                // what the key would do —, and affordance does not compete for
                // attention with the focused item.
                color: if aceso {
                    Color::StateAccent
                } else {
                    Color::TextDim
                },
                scale: Scale::Small,
                max_width: 1,
            }));
        };
        if a.arrows {
            mark_of(0, Icon::Adjust, target);
        }
        if a.types_into {
            // THE TYPING ONE LIGHTS UP WHILE TYPING, and not only on focus: it
            // is the only sign that the next digit appends instead of
            // replacing.
            mark_of(1, Icon::Edit, self.typing);
        }
        if a.restores {
            // `Enter` HERE RESTORES, and on the other 19 lines it copies. Without
            // this mark the two are indistinguishable, and the one who loses is
            // whoever pressed it expecting to confirm.
            mark_of(2, Icon::History, target);
        }
        out
    }
}

/// What action line `n` responds to. Outside the adjustments, nothing.
const fn affordance(n: usize) -> Affordance {
    match n {
        // Size: steps by 1 px, and is typed as a number.
        0 => Affordance {
            arrows: true,
            types_into: true,
            restores: true,
        },
        // Stroke and cap step; absolute toggles.
        1 | 2 | 4 => Affordance {
            arrows: true,
            types_into: false,
            restores: true,
        },
        // THE COLOR DOES NOT STEP. It is free text, and there is no "next color" —
        // what changes it is the typing, on the line itself.
        3 => Affordance {
            arrows: false,
            types_into: true,
            restores: true,
        },
        // The 19 forms of copy are not an adjustment: there the arrow switches
        // icons, which is how two similar drawings are compared without leaving
        // the sheet. And `Enter` COPIES — there is nothing to restore.
        _ => Affordance {
            arrows: false,
            types_into: false,
            restores: false,
        },
    }
}

fn filter_fits(ctx: &Context) -> bool {
    ctx.columns > MIN_SEARCH + FILTER_WIDTH
}

/// Is this column of the search line the filter icon?
///
/// The same function the drawing uses to know whether it emits it — if there
/// were two, one of them changing would be enough for the click to land in
/// the void.
fn in_filter(ctx: &Context, column: u16) -> bool {
    filter_fits(ctx) && column.saturating_add(FILTER_WIDTH) >= ctx.columns
}

/// The words of a query. Empty gives back empty.
///
/// Splits on space AND on ASCII punctuation, the same boundary
/// `word_prefix` uses on the text: without that `arrow-up` would be a
/// single token and would not match the name, which the text splits in two.
fn search_words(q: &str) -> Vec<&str> {
    q.split(|c: char| c.is_whitespace() || c.is_ascii_punctuation())
        .filter(|p| !p.is_empty())
        .collect()
}

/// Is `t` a prefix of some WORD of `text`?
///
/// A loose substring would give the same class of error that already cost the
/// symbols browser: searching `sun` would match `sun`glasses before `sun`, and
/// since "the name contains it" scores better than "it has the tag", the
/// obvious result would fall behind.
fn word_prefix(text: &str, t: &str) -> bool {
    text.split(|c: char| !c.is_alphanumeric())
        .any(|p| p.starts_with(t))
}

/// A label-and-value line of the sheet.
fn pair(
    ctx: &Context,
    line: u16,
    label: &str,
    value: Text,
    target: bool,
    mark: Mark,
) -> Vec<Command> {
    let column = value_column(ctx);
    let mut out = vec![Command::Text(TextCommand {
        line,
        column: 0,
        content: Text::Key(label.to_owned()),
        color: if target {
            Color::StateAccent
        } else {
            Color::TextDim
        },
        scale: Scale::Small,
        // UP TO THE VALUE COLUMN, and not one cell beyond: whoever elides is the
        // host, and without a budget a long translated label would write over the
        // value. The length changes with the language — this buffer does not know it.
        //
        // The two mark cells come out of here, and not out of the value: the label
        // already elides, and pushing the value to the right would change the
        // alignment of the whole sheet.
        max_width: column.saturating_sub(MARK_CELLS),
    })];
    out.extend(mark.draw(line, column, target));
    if ctx.columns > column {
        out.push(Command::Text(TextCommand {
            line,
            column,
            content: value,
            color: if target {
                Color::StateAccent
            } else {
                Color::TextSecondary
            },
            scale: Scale::Normal,
            max_width: ctx.columns.saturating_sub(column),
        }));
    }
    out
}

/// Which of the buffer's two screens is in use.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Screen {
    /// The icon grid.
    Grid,
    /// The sheet of one icon: what it is, how to customize it and how to copy it.
    Sheet {
        /// The focused line, in the single index of [`State::action_rows`].
        option: usize,
        /// The first action line drawn. The Lucide sheet has 24 actionable lines
        /// against the 9 of the symbols browser: in a short window it does NOT fit,
        /// and without scrolling the last ones would be unreachable.
        top: usize,
    },
}

/// The geometry of the filter panel — where each option is drawn.
///
/// [`Panel::cell`] and [`Panel::at_cell`] are the same arithmetic in both
/// directions: drawing and click have to match by CONSTRUCTION, not by luck.
struct Panel {
    columns: u16,
    step: u16,
    lines: u16,
    first: usize,
    total: usize,
}

impl Panel {
    fn new(ctx: &Context, total: usize, selection: usize) -> Self {
        let step = LABEL_WIDTH + SPACE_BETWEEN_OPTIONS;
        let columns = (ctx.columns.saturating_sub(PANEL_INDENT) / step).max(1);
        let per_row = usize::from(columns);
        // Ceiling of half the content. The panel shares the screen with the grid,
        // and the grid is the buffer.
        let ceiling = (usize::from(ctx.lines).saturating_sub(3) / 2).max(1);
        let lines = total.div_ceil(per_row).min(ceiling).max(1);
        let page = (selection / per_row) / lines;
        Self {
            columns,
            step,
            lines: u16::try_from(lines).unwrap_or(u16::MAX),
            first: page * lines * per_row,
            total,
        }
    }

    fn cell(&self, n: usize) -> Option<(u16, u16)> {
        let inside = n.checked_sub(self.first)?;
        let per_row = usize::from(self.columns);
        let line = u16::try_from(inside / per_row).ok()?;
        if line >= self.lines {
            return None;
        }
        let column = u16::try_from(inside % per_row).ok()? * self.step + PANEL_INDENT;
        Some((line, column))
    }

    fn at_cell(&self, line: u16, column: u16) -> Option<usize> {
        if line >= self.lines {
            return None;
        }
        let c = column.saturating_sub(PANEL_INDENT) / self.step;
        if c >= self.columns {
            return None;
        }
        let n = self.first + usize::from(line) * usize::from(self.columns) + usize::from(c);
        (n < self.total).then_some(n)
    }
}

/// A Lucide icon, with only what the browser uses.
///
/// `Figure` and not `Icon`: `Icon` is already the TOKEN enum that comes from
/// the WIT — the icon vocabulary of the interface itself (invariant 10). They
/// are different things, and the compiler would not let the two share a name.
struct Figure {
    /// Lucide's canonical name: `house`, `arrow-up-right`.
    name: String,
    /// What the SCREEN draws — the codepoint of the remapped face.
    cp: char,
    /// What LUCIDE publishes. It draws nothing here; it serves whoever pastes
    /// into a page that uses their font. See `LUCIDE_FONT` in the renderer.
    lcp: u32,
    cats: Vec<String>,
    aliases: Vec<String>,
    tags_pt: Vec<String>,
    tags_en: Vec<String>,
    /// The unaccented forms of the pt tags — they do not go to the screen.
    search: Vec<String>,
    /// The nodes of the drawing, encoded by the generator.
    nos: String,
}

impl Figure {
    /// The SVG nodes, decoded: `[(element, [(attribute, value)])]`.
    ///
    /// Decoding happens on the COPY, and not on load: there are 1,668 icons and
    /// instantiation has a budget of 5 ms (section 5.2) — keeping `Vec<Vec<..>>`
    /// for all of them would cost twice the allocations to serve one at a time.
    fn nos(&self) -> Vec<(&str, Vec<(&str, &str)>)> {
        self.nos
            .split(';')
            .filter(|n| !n.is_empty())
            .map(|no| {
                let mut parts = no.split('|');
                let element = parts.next().unwrap_or_default();
                let attributes = parts.filter_map(|a| a.split_once('=')).collect::<Vec<_>>();
                (element, attributes)
            })
            .collect()
    }

    /// The component name in the frameworks: `arrow-up` -> `ArrowUp`.
    fn component(&self) -> String {
        self.name
            .split('-')
            .filter(|p| !p.is_empty())
            .map(|p| {
                let mut c = p.chars();
                match c.next() {
                    Some(first) => first.to_uppercase().collect::<String>() + c.as_str(),
                    None => String::new(),
                }
            })
            .collect()
    }

    /// How well this icon matches the query. Lower is better; `None` does not match.
    ///
    /// ALL the tokens have to match, and the score is the WORST among them:
    /// whoever typed `arrow up` wants the one that has both, and not the one that
    /// has one of them very well.
    fn match_score(&self, tokens: &[&str]) -> Option<u8> {
        let mut worst = 0;
        for t in tokens {
            worst = worst.max(self.word_score(t)?);
        }
        Some(worst)
    }

    /// The score of ONE word of the query.
    fn word_score(&self, t: &str) -> Option<u8> {
        if self.name == t {
            return Some(0);
        }
        if self.name.starts_with(t) {
            return Some(1);
        }
        if word_prefix(&self.name, t) {
            return Some(2);
        }
        // THE ALIAS SCORES LIKE A NAME, almost.
        //
        // `home` is an alias of `house`, and Lucide marks it as deprecated — but
        // whoever types `home` is looking for the little house, not a deprecation
        // notice. Being behind the name is enough for `house` to win when both
        // of them match.
        if self.aliases.iter().any(|a| word_prefix(a, t)) {
            return Some(3);
        }
        if self.cats.iter().any(|c| word_prefix(c, t)) {
            return Some(4);
        }
        if self
            .tags_pt
            .iter()
            .chain(self.tags_en.iter())
            .chain(self.search.iter())
            .any(|g| word_prefix(g, t))
        {
            return Some(5);
        }
        None
    }

    /// The tags the footer shows: the Portuguese ones, and the English only as a
    /// complement. Without this the footer would show both whole lists, which for
    /// some icons are 82 words.
    fn visible_tags(&self) -> impl Iterator<Item = &String> {
        self.tags_pt.iter().chain(self.tags_en.iter()).take(8)
    }
}

