//! The Lucide icon browser — `LEADER i l`.
//!
//! The third of the family: the glyph one finds the right icon among the
//! 10,473 of Nerd Fonts, the symbol one finds the right CHARACTER, and this
//! one finds the right INTERFACE icon among Lucide's 1,668 — and, unlike the
//! other two, it delivers the icon in the form it is going to be used in: SVG,
//! JSX, framework component, data URI, CSS rule.
//!
//! # Why customization lives HERE and not on the screen
//!
//! Because they are two different things. The screen draws a GLYPH, and a
//! glyph has the stroke baked into it — Lucide publishes a single weight, and
//! no font in the world would make that weight vary. What customization
//! changes is the COPIED ARTIFACT, which is text, and where it is exact:
//! `stroke-width`, `stroke-linecap`, size, color, and the "absolute stroke"
//! arithmetic (the `strokeWidth * 24 / size` that lucide.dev does).
//!
//! The preview honors what it can honor — the size and the color are tokens,
//! and the drawing is the same. Pretending the stroke changes on screen would
//! be lying about the one place where the copy matters.
//!
//! # What this component does NOT do
//!
//! It does not read files, does not write files, does not rasterize, does not
//! translate, and does not know that `currentColor` is a color — the database
//! arrives EMBEDDED in the build, the screen goes out as a display list, and
//! whoever puts it on the clipboard is the host. Invariant 11.
//!
//! # And it no longer decides its own geometry
//!
//! Every number that said where something goes came from this file, and two
//! sibling browsers had the same numbers with different values: `ICON_COLUMNS`
//! 2 / 4 / 2, the horizontal gap 3 / 3 / 4, the label column 24 / 20 / 24, and
//! three copies each of `grid_columns`, `height`, `panel_first_row`,
//! `rule_row`, `grid_first_row`, `footer_row` and `row_step`. `ronoctua-design`
//! is the one implementation of all of them, and what is left here is the two
//! things that genuinely belong to Lucide: how wide ONE drawing is, and what
//! this buffer's own lines are made of.
//!
//! The sharpest reason it is worth it is in this file's history. `MARK_CELLS`
//! said the marks reserved two cells while [`MARKS`] drew three, and the third
//! landed on the value's own first cell — on the size line, on the `2` of
//! `24 px`, on every adjustment line. A reservation counted by hand beside a
//! list counted by hand is a pair that drifts, and no test compares two numbers
//! nobody wrote down. Reservations are what a [`Table`] is for, and the
//! reservation now IS the list: see [`MARK_CELLS`].
//!
//! # There is no rule under a heading
//!
//! Not here and not anywhere: whitespace separates, and the owner has
//! standardised on it. [`Screen::rule`] stays for the boundary between two
//! BLOCKS — the one above the icon grid, and the one between what an icon IS
//! and what one can do with it — and it is full bleed at the BOTTOM edge of the
//! row it names, which is why the row it names is a row of air.

