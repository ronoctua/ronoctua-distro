/// What the query asks for before any free term.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Filter {
    NoneOf,
    Category(String),
    Name(String),
}

/// Cuts the FIRST word off `s` and gives back `(word, rest)`.
///
/// The enumeration filter eats a single word: with the rest, `categoria:arrows
/// up` would become the category `arrows up`, which does not exist, and typing
/// with an active filter would be impossible — the defect the symbols browser
/// already had.
fn one_word(s: &str) -> (String, String) {
    match s.split_once(char::is_whitespace) {
        Some((a, b)) => (a.to_owned(), b.trim_start().to_owned()),
        None => (s.to_owned(), String::new()),
    }
}

impl Filter {
    /// Splits the query into `(filter, free term)`.
    fn split_filter(search: &str) -> (Self, String) {
        for (mark, montar) in [
            ("categoria:", Self::Category as fn(String) -> Self),
            ("category:", Self::Category as fn(String) -> Self),
            ("cat:", Self::Category as fn(String) -> Self),
            ("nome:", Self::Name as fn(String) -> Self),
            ("name:", Self::Name as fn(String) -> Self),
        ] {
            if let Some(rest) = search.strip_prefix(mark) {
                let (value, livre) = one_word(rest.trim_start());
                return (montar(value), livre);
            }
        }
        (Self::NoneOf, search.to_owned())
    }

    /// The text of the filter, without the free term. It is what `Esc` leaves.
    fn prefix(&self) -> String {
        match self {
            Self::NoneOf => String::new(),
            Self::Category(c) => format!("categoria:{c}"),
            Self::Name(n) => format!("nome:{n}"),
        }
    }

    fn matches_query(&self, i: &Figure) -> bool {
        match self {
            Self::NoneOf => true,
            Self::Category(c) => c.is_empty() || i.cats.iter().any(|x| x == c),
            Self::Name(n) => i.name.contains(n.as_str()),
        }
    }
}

