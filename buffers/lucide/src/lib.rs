//! The Lucide icon browser — `LEADER i l`.
//!
//! The third of the family: the glyph one finds the right icon among the
//! 10,473 of Nerd Fonts, the symbol one finds the right CHARACTER, and this
//! one finds the right INTERFACE icon among Lucide's 1,668 — and, unlike the
//! other two, it delivers the icon in the form it is going to be used in: SVG,
//! JSX, framework component, data URI, CSS rule.
//!
//! # Why customization lives HERE and not on the screen
//!
//! Because they are two different things. The screen draws a GLYPH, and a
//! glyph has the stroke baked into it — Lucide publishes a single weight, and
//! no font in the world would make that weight vary. What customization
//! changes is the COPIED ARTIFACT, which is text, and where it is exact:
//! `stroke-width`, `stroke-linecap`, size, color, and the "absolute stroke"
//! arithmetic (the `strokeWidth * 24 / size` that lucide.dev does).
//!
//! The preview honors what it can honor — the size and the color are tokens,
//! and the drawing is the same. Pretending the stroke changes on screen would
//! be lying about the one place where the copy matters.
//!
//! # What this component does NOT do
//!
//! It does not read files, does not write files, does not rasterize, does not
//! translate, and does not know that `currentColor` is a color — the database
//! arrives EMBEDDED in the build, the screen goes out as a display list, and
//! whoever puts it on the clipboard is the host. Invariant 11.

