/// What the query asks for before any free term.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Filter {
    NoneOf,
    Category(String),
    Name(String),
}

/// Cuts the FIRST word off `s` and gives back `(word, rest)`.
///
/// The enumeration filter eats a single word: with the rest, `categoria:arrows
/// up` would become the category `arrows up`, which does not exist, and typing
/// with an active filter would be impossible — the defect the symbols browser
/// already had.
fn one_word(s: &str) -> (String, String) {
    match s.split_once(char::is_whitespace) {
        Some((a, b)) => (a.to_owned(), b.trim_start().to_owned()),
        None => (s.to_owned(), String::new()),
    }
}

/// The two words this buffer WRITES, and the names each answers to.
///
/// `(key, english, portuguese)` — the symbol browser's `PREFIX_KEYS` carries
/// the whole reasoning. `cat:` is beside them in the parser but not here: it is
/// an abbreviation, not a translation, and the buffer never writes it.
const PREFIX_KEYS: [(&str, &str, &str); 2] = [
    (key::PREFIX_CATEGORY, "category", "categoria"),
    (key::PREFIX_NAME, "name", "nome"),
];

/// The word this buffer writes for one prefix, in the person's language.
fn word(phrases: &Phrases, key: &str) -> String {
    let english = PREFIX_KEYS
        .iter()
        .find(|(k, _, _)| *k == key)
        .map_or("", |(_, en, _)| *en);
    phrases.or(key, english)
}

impl Filter {
    /// Splits the query into `(filter, free term)`.
    ///
    /// THREE VOCABULARIES REACH THIS LINE — English, Portuguese and whatever
    /// the host resolved. The third has to be here or a language whose word is
    /// neither of the first two would write a filter on `Esc` that this buffer
    /// could not read back.
    fn split_filter(search: &str, phrases: &Phrases) -> (Self, String) {
        let category = Self::Category as fn(String) -> Self;
        let name = Self::Name as fn(String) -> Self;
        for (mark, mount) in [
            (word(phrases, key::PREFIX_CATEGORY), category),
            ("categoria".to_owned(), category),
            ("category".to_owned(), category),
            // An abbreviation, and the same three letters in every language.
            ("cat".to_owned(), category),
            (word(phrases, key::PREFIX_NAME), name),
            ("nome".to_owned(), name),
            ("name".to_owned(), name),
        ] {
            if let Some(rest) = search.strip_prefix(&format!("{mark}:")) {
                let (value, free) = one_word(rest.trim_start());
                return (mount(value), free);
            }
        }
        (Self::NoneOf, search.to_owned())
    }

    /// The text of the filter, without the free term. It is what `Esc` leaves.
    ///
    /// IN THE PERSON'S WORD, which the host resolved and handed over — and in
    /// English when it handed nothing over.
    fn prefix(&self, phrases: &Phrases) -> String {
        match self {
            Self::NoneOf => String::new(),
            Self::Category(c) => format!("{}:{c}", word(phrases, key::PREFIX_CATEGORY)),
            Self::Name(n) => format!("{}:{n}", word(phrases, key::PREFIX_NAME)),
        }
    }

    fn matches_query(&self, i: &Figure) -> bool {
        match self {
            Self::NoneOf => true,
            Self::Category(c) => c.is_empty() || i.cats.iter().any(|x| x == c),
            Self::Name(n) => i.name.contains(n.as_str()),
        }
    }
}

