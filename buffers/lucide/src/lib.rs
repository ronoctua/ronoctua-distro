/// The corners and the line caps, as Lucide offers them.
///
/// `round`/`round` is their default — the icons were drawn that way, and the
/// other two combinations exist for whoever needs to match another set.
const CAPS: [(&str, &str, &str); 3] = [
    (key::CAP_ROUND, "round", "round"),
    (key::CAP_BUTT, "butt", "miter"),
    (key::CAP_SQUARE, "square", "bevel"),
];

const SIZE_DEFAULT: u16 = 24;
const SIZE_MIN: u16 = 1;
const SIZE_MAX: u16 = 512;
/// The stroke in TENTHS: `20` is `2.0`, which is Lucide's default.
const STROKE_DEFAULT: u16 = 20;
const STROKE_MIN: u16 = 1;
const STROKE_MAX: u16 = 80;
const STROKE_STEP: u16 = 5;
const COLOR_DEFAULT: &str = "currentColor";

/// What the person chose, and which goes out in EVERY form of copy.
///
/// It lives in the [`State`] and not in the [`Screen`]: whoever set the stroke
/// to 1.5 is assembling a set, and redoing the adjustment for every icon would
/// turn the customization into an ornament.
#[derive(Debug, Clone)]
struct Adjustments {
    size: u16,
    /// In tenths.
    stroke: u16,
    absolute: bool,
    color: String,
    line_cap: usize,
    /// Has a digit already been typed on this pass through the size line?
    ///
    /// # Why this exists
    ///
    /// Without it, every digit enters from the right: arriving at the line with
    /// `24` and typing `48` gives `2448`, which the ceiling clamps to `512` — a
    /// number nobody asked for, arriving from an obvious gesture. With it, the
    /// FIRST digit replaces and the following ones append, which is how every
    /// numeric field behaves. It disappears on leaving the line, and that is why
    /// it lives here and not in the `Screen`: whoever zeroes it moves the selection.
    typing: bool,
}

impl Default for Adjustments {
    fn default() -> Self {
        Self {
            size: SIZE_DEFAULT,
            stroke: STROKE_DEFAULT,
            absolute: false,
            color: COLOR_DEFAULT.to_owned(),
            line_cap: 0,
            typing: false,
        }
    }
}

/// A number in tenths, written as a person reads it: `20` -> `2`, `15` -> `1.5`.
fn tenths(v: u16) -> String {
    if v.is_multiple_of(10) {
        format!("{}", v / 10)
    } else {
        format!("{}.{}", v / 10, v % 10)
    }
}

/// A value with up to three decimals, without needless zeros: `1.500` -> `1.5`.
fn trimmed(v: f32) -> String {
    let s = format!("{v:.3}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s.is_empty() {
        "0".to_owned()
    } else {
        s.to_owned()
    }
}

impl Adjustments {
    fn usable_size(&self) -> u16 {
        self.size.max(SIZE_MIN)
    }

    /// The weight that goes into the `stroke-width`.
    ///
    /// # What "absolute stroke" means
    ///
    /// The SVG `stroke-width` is relative to the `viewBox`, so a 48 px icon with
    /// stroke 2 comes out twice as thick in pixels as a 24 px one. Whoever mixes
    /// sizes on the same screen wants the opposite, and lucide.dev solves that by
    /// dividing: `stroke * 24 / size`. It is the same arithmetic, and it lives
    /// here because it is what changes the copied text.
    fn effective_stroke(&self) -> String {
        let stroke = f32::from(self.stroke) / 10.0;
        if self.absolute {
            #[expect(clippy::cast_precision_loss, reason = "tamanho vai ate 512")]
            let scale = VIEW_BOX as f32 / f32::from(self.usable_size());
            trimmed(stroke * scale)
        } else {
            tenths(self.stroke)
        }
    }

    /// The color, without what would break the attribute it goes into.
    ///
    /// The person types this string freely, and it comes out inside `stroke="…"`
    /// in both the SVG and the JSX. A quote there would close the attribute and
    /// the rest of the color would turn into markup — the only place in this
    /// buffer where user input becomes syntax.
    fn usable_color(&self) -> String {
        let cleaned: String = self
            .color
            .chars()
            .filter(|c| !matches!(c, '"' | '<' | '>' | '&'))
            .collect();
        if cleaned.trim().is_empty() {
            COLOR_DEFAULT.to_owned()
        } else {
            cleaned
        }
    }

    fn linecap(&self) -> &'static str {
        CAPS[self.line_cap.min(CAPS.len() - 1)].1
    }

    fn linejoin(&self) -> &'static str {
        CAPS[self.line_cap.min(CAPS.len() - 1)].2
    }

    /// The value of an adjustment, as the sheet shows it.
    fn value(&self, n: usize) -> Text {
        match n {
            0 => Text::Data(format!("{} px", self.usable_size())),
            1 => Text::Data(if self.absolute {
                format!("{} → {}", tenths(self.stroke), self.effective_stroke())
            } else {
                tenths(self.stroke)
            }),
            2 => Text::Key(if self.absolute { key::YES } else { key::NO }.to_owned()),
            3 => Text::Data(self.color.clone()),
            _ => Text::Key(CAPS[self.line_cap.min(CAPS.len() - 1)].0.to_owned()),
        }
    }

    /// The number typing is over — the selection left the line, or something else
    /// touched the value.
    const fn stop_typing(&mut self) {
        self.typing = false;
    }

    /// Steps one adjustment to one side. `+1` is to the right.
    ///
    /// Gives back `false` when the line does not step — and then the arrow means
    /// something else (switch icons). Whoever decides is [`affordance`], never
    /// this `match`: see its doc.
    fn step_by(&mut self, n: usize, step: i32) -> bool {
        if !affordance(n).arrows {
            return false;
        }
        self.typing = false;
        match n {
            0 => {
                let new = i32::from(self.usable_size()) + step;
                self.size = u16::try_from(new.clamp(i32::from(SIZE_MIN), i32::from(SIZE_MAX)))
                    .unwrap_or(SIZE_DEFAULT);
            }
            1 => {
                let new = i32::from(self.stroke) + step * i32::from(STROKE_STEP);
                self.stroke =
                    u16::try_from(new.clamp(i32::from(STROKE_MIN), i32::from(STROKE_MAX)))
                        .unwrap_or(STROKE_DEFAULT);
            }
            2 => self.absolute = !self.absolute,
            _ => {
                let total = i32::try_from(CAPS.len()).unwrap_or(3);
                let new = (i32::try_from(self.line_cap).unwrap_or(0) + step).rem_euclid(total);
                self.line_cap = usize::try_from(new).unwrap_or(0);
            }
        }
        true
    }

    /// A character typed over adjustment line `n`.
    fn type_char(&mut self, n: usize, c: char) -> bool {
        if !affordance(n).types_into {
            return false;
        }
        match n {
            0 if c.is_ascii_digit() => {
                // A NUMBER IS TYPED AS A NUMBER. Without this, reaching 512
                // would cost 488 arrow presses. See `typing`.
                let d = u32::from(c) - u32::from('0');
                let new = if self.typing {
                    u32::from(self.size) * 10 + d
                } else {
                    d
                };
                self.typing = true;
                self.size = u16::try_from(new.min(u32::from(SIZE_MAX))).unwrap_or(SIZE_MAX);
                true
            }
            3 => {
                self.color.push(c);
                true
            }
            _ => false,
        }
    }

    /// `Delete` over adjustment line `n`.
    ///
    /// The same gate as typing: what is not typed is not deleted either.
    fn delete(&mut self, n: usize) -> bool {
        if !affordance(n).types_into {
            return false;
        }
        match n {
            0 => {
                self.size /= 10;
                true
            }
            3 => self.color.pop().is_some(),
            _ => false,
        }
    }

    /// `Enter` over adjustment line `n`: back to Lucide's default.
    fn restore(&mut self, n: usize) {
        self.typing = false;
        let default_of = Self::default();
        match n {
            0 => self.size = default_of.size,
            1 => self.stroke = default_of.stroke,
            2 => self.absolute = default_of.absolute,
            3 => self.color = default_of.color,
            _ => self.line_cap = default_of.line_cap,
        }
    }
}

