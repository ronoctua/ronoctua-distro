/// How many cells the search needs before the counter is worth showing.
const MIN_SEARCH: u16 = 12;

/// How many columns an icon at the large scale takes.
///
/// **Four, and not the two of the other two browsers.** A cell is `0.600 x
/// font size` wide, and the advance of the Lucide face is `1.000 at_cell` against
/// the `0.600 at_cell` of Iosevka — the same scale yields ink 67% wider:
///
///     Iosevka, large scale    0.600 x 40 = 24.0 px = 2.22 cells
///     Lucide,  large scale    1.000 x 40 = 40.0 px = 3.70 cells
///
/// With two, the name of the focused icon was written OVER the drawing in the
/// footer, and the elision budget ended up smaller than the ink it budgets.
const ICON_COLUMNS: u16 = 4;

/// The gap between one grid column and the next.
///
/// It exists so the HORIZONTAL gap matches the VERTICAL one, which is not
/// chosen: it comes from the line box of the large scale (`40 x 1.45 = 58 px`,
/// rounded up to 3 cells of 26.1 px). With ink of 40 px:
///
///     vertical      3 x 26.1 = 78.3 px  ->  gap of 38.3 px
///     horizontal    7 x 10.8 = 75.6 px  ->  gap of 35.6 px
///
/// That is 2.7 px of difference. With the step of 5 the other buffers use, the
/// horizontal gap would drop to 14 px against 38 — the grid would come out
/// squashed sideways.
const HORIZONTAL_GAP: u16 = 3;

/// One cell of slack, where the slack is the TEXT's and not the block's.
const BREATHING: u16 = 1;

const AFTER_ICON: u16 = ICON_COLUMNS + BREATHING;
const FILTER_WIDTH: u16 = AFTER_ICON;

