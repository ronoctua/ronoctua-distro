/// The attributes of the `<svg>`, in the order Lucide writes them.
fn svg_attributes(i: &Figure, a: &Adjustments, jsx: bool) -> String {
    let size = a.usable_size();
    let (width, class, sw, cap, join) = if jsx {
        (
            "width",
            "className",
            "strokeWidth",
            "strokeLinecap",
            "strokeLinejoin",
        )
    } else {
        (
            "width",
            "class",
            "stroke-width",
            "stroke-linecap",
            "stroke-linejoin",
        )
    };
    format!(
        concat!(
            r#"xmlns="http://www.w3.org/2000/svg" {}="{}" height="{}" "#,
            r#"viewBox="0 0 {} {}" fill="none" stroke="{}" {}="{}" "#,
            r#"{}="{}" {}="{}" {}="lucide lucide-{}""#
        ),
        width,
        size,
        size,
        VIEW_BOX,
        VIEW_BOX,
        a.usable_color(),
        sw,
        a.effective_stroke(),
        cap,
        a.linecap(),
        join,
        a.linejoin(),
        class,
        i.name,
    )
}

/// The whole SVG. `jsx` swaps the hyphenated attributes for the camelCase ones.
fn svg(i: &Figure, a: &Adjustments, jsx: bool) -> String {
    let mut out = format!("<svg {}>\n", svg_attributes(i, a, jsx));
    for (element, attributes) in i.nos() {
        out.push_str("  <");
        out.push_str(element);
        for (key, value) in attributes {
            out.push(' ');
            out.push_str(key);
            out.push_str("=\"");
            out.push_str(value);
            out.push('"');
        }
        out.push_str(" />\n");
    }
    out.push_str("</svg>");
    out
}

/// The SVG on a single line, which is what fits inside a `url(...)`.
fn svg_one_line(i: &Figure, a: &Adjustments) -> String {
    svg(i, a, false).replace('\n', "").replace("  <", "<")
}

/// Percent-encoding of what would break a `data:` inside a `url(...)`.
///
/// Only what is needed, and not the whole alphabet: a readable SVG data URI is
/// more useful than a fully escaped one, and browsers accept the rest raw.
fn data_uri(svg: &str) -> String {
    // The quotes become single ones BEFORE escaping: that way the `url("…")`
    // that wraps the data URI keeps closing where it should.
    let s = svg.replace('"', "'");
    let mut out = String::from("data:image/svg+xml,");
    for c in s.chars() {
        match c {
            '<' => out.push_str("%3C"),
            '>' => out.push_str("%3E"),
            '#' => out.push_str("%23"),
            '%' => out.push_str("%25"),
            '{' => out.push_str("%7B"),
            '}' => out.push_str("%7D"),
            '|' => out.push_str("%7C"),
            '\\' => out.push_str("%5C"),
            '^' => out.push_str("%5E"),
            '~' => out.push_str("%7E"),
            '[' => out.push_str("%5B"),
            ']' => out.push_str("%5D"),
            '`' => out.push_str("%60"),
            other => out.push(other),
        }
    }
    out
}

/// Standard base64, without a dependency.
///
/// Eighteen lines against one more crate inside a component that is
/// instantiated on every buffer open — the `Cargo.toml` here has ONE
/// dependency on purpose, and that is the reason.
fn base64(data_bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data_bytes.len().div_ceil(3) * 4);
    for chunk in data_bytes.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        for i in 0..4 {
            if i <= chunk.len() {
                let index = usize::try_from((n >> (18 - 6 * i)) & 0x3F).unwrap_or(0);
                out.push(char::from(ALPHABET[index]));
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// The properties the framework components take.
fn properties(a: &Adjustments) -> String {
    format!(
        r#"color="{}" size={{{}}} strokeWidth={{{}}} absoluteStrokeWidth={{{}}}"#,
        a.usable_color(),
        a.usable_size(),
        a.effective_stroke(),
        a.absolute,
    )
}

/// One form of copy. `None` means "this id is not mine".
fn format_as(id: &str, i: &Figure, a: &Adjustments) -> Option<String> {
    let component = i.component();
    let import_line = |package: &str| format!("import {{ {component} }} from '{package}';");
    Some(match id {
        "lucide-copy-svg" => svg(i, a, false),
        "lucide-copy-jsx" => svg(i, a, true),
        "lucide-copy-vanilla" => format!(r#"<i data-lucide="{}"></i>"#, i.name),
        "lucide-copy-react" => format!(
            "{}\n\n<{component} {} />",
            import_line("lucide-react"),
            properties(a)
        ),
        "lucide-copy-vue" => format!(
            "{}\n\n<{component} {} />",
            import_line("lucide-vue-next"),
            properties(a)
        ),
        "lucide-copy-svelte" => format!(
            "{}\n\n<{component} {} />",
            import_line("@lucide/svelte"),
            properties(a)
        ),
        "lucide-copy-preact" => format!(
            "{}\n\n<{component} {} />",
            import_line("lucide-preact"),
            properties(a)
        ),
        "lucide-copy-solid" => format!(
            "{}\n\n<{component} {} />",
            import_line("lucide-solid"),
            properties(a)
        ),
        "lucide-copy-angular" => format!(
            r#"<lucide-angular name="{}" [size]="{}" [strokeWidth]="{}" color="{}"></lucide-angular>"#,
            i.name,
            a.usable_size(),
            a.effective_stroke(),
            a.usable_color(),
        ),
        "lucide-copy-font" => format!(r#"<i class="lucide lucide-{}"></i>"#, i.name),
        "lucide-copy-name" => i.name.clone(),
        "lucide-copy-component" => component,
        // LUCIDE'S CHARACTER, and not the one on the screen.
        //
        // They are different codepoints on purpose: the face here was remapped
        // to plane 15 because the original one collides with 634 of Nerd Fonts.
        // Whoever pastes this is going to paste into a page with LUCIDE's font,
        // and there the codepoint that counts is theirs.
        "lucide-copy-character" => char::from_u32(i.lcp)?.to_string(),
        "lucide-copy-hex" => format!("U+{:04X}", i.lcp),
        "lucide-copy-path" => i
            .nos()
            .into_iter()
            .filter(|(element, _)| *element == "path")
            .filter_map(|(_, attributes)| {
                attributes
                    .into_iter()
                    .find(|(k, _)| *k == "d")
                    .map(|(_, v)| v.to_owned())
            })
            .collect::<Vec<_>>()
            .join(" "),
        "lucide-copy-uri" => data_uri(&svg_one_line(i, a)),
        "lucide-copy-base64" => format!(
            "data:image/svg+xml;base64,{}",
            base64(svg_one_line(i, a).as_bytes())
        ),
        "lucide-copy-css" => format!(
            ".{}-{} {{\n  background-image: url(\"{}\");\n  background-size: {}px {}px;\n}}",
            "icone",
            i.name,
            data_uri(&svg_one_line(i, a)),
            a.usable_size(),
            a.usable_size(),
        ),
        "lucide-copy-sprite" => format!(
            "<svg class=\"lucide\" width=\"{}\" height=\"{}\">\n  <use href=\"lucide.svg#{}\" />\n</svg>",
            a.usable_size(),
            a.usable_size(),
            i.name,
        ),
        _ => return None,
    })
}

