/// What a sheet line responds to.
///
/// # Why this is a table, and not a `match` in every place
///
/// Because the affordance was scattered across `step_by`, `type_char`, `delete`
/// and the `Paste` dispatch — and the **drawing consulted none of them**. The
/// 24 lines of the sheet looked exactly alike, and the side arrow did three
/// different things without warning: it changed the value, it switched icons,
/// or (on the color line) **nothing**, silently.
///
/// Drawing the mark from a second list would only postpone the problem: it
/// would diverge on the first new adjustment, and a mark that promises a key
/// that does nothing is worse than no mark at all. Here there is one source,
/// and whoever acts asks it **before** acting.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Affordance {
    /// The side arrows change this value.
    arrows: bool,
    /// You can type (and delete, and paste) on this line.
    types_into: bool,
    /// `Enter` here RESTORES the default instead of copying.
    ///
    /// # Why it needed a mark of its own
    ///
    /// The same `Enter` does two things depending on the line: on the 5
    /// adjustments it restores, on the 19 formats it copies. Nothing said so.
    /// Whoever set the stroke to 3.5 and pressed `Enter` expecting to confirm
    /// LOST the adjustment, with nothing on screen to explain it.
    ///
    /// Making `Enter` copy everywhere would have been the other way out, and it
    /// is worse: an adjustment line is not a format, so there would be nothing
    /// to copy — the behaviour would have to be invented.
    restores: bool,
}

/// One thing a sheet line can say about what it responds to.
///
/// The three used to be an `if` each inside a `draw`, each with the cell it
/// went in written out as a number beside it. That is exactly the pair that
/// drifted: see [`MARKS`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Mark {
    /// The side arrows change this value.
    Adjusts,
    /// One can type here, and delete, and paste.
    Types,
    /// `Enter` here RESTORES the default instead of copying.
    Restores,
}

/// EVERY MARK A SHEET LINE CAN CARRY, and the order is where each one sits.
///
/// # Why the reservation is a `len()` and not a number
///
/// Because it was a number. `MARK_CELLS` said `3`, and before that it said `2`
/// while this list already had three things in it — so `History`, the third,
/// was drawn one cell past the reservation, on the value's own first cell. On
/// the size line that is the `2` of `24 px`, and every adjustment line has that
/// mark. It was found by a geometry question, not by a person reading the
/// screen; and the two numbers it compared were both written by hand, three
/// hundred lines apart.
///
/// Now there is one list. [`MARK_CELLS`] is its length and [`Mark::cell`] is a
/// position in it, so the reservation and the things reserving it are the same
/// object and cannot say different numbers. That is what a [`Table`] column is
/// for, and the column the sheet reserves is `Column::fixed(field::MARKS,
/// MARK_CELLS, …)`.
const MARKS: [Mark; 3] = [Mark::Adjusts, Mark::Types, Mark::Restores];

/// How many cells one mark takes: ONE.
///
/// It is a glyph at the smallest scale, and the host charges a glyph exactly
/// the cells its scale is worth — which at `small` is the single cell it names.
const MARK_WIDE: u16 = 1;

/// How many cells the marks reserve, DERIVED from the marks.
///
/// Reserved on every line of the sheet, including the ones that carry no mark
/// at all: the value starts after them everywhere, because a column that moved
/// from line to line would be a sheet one cannot read down.
#[expect(
    clippy::cast_possible_truncation,
    reason = "MARKS's length is known at compile time"
)]
const MARK_CELLS: u16 = MARK_WIDE * MARKS.len() as u16;

impl Mark {
    /// Where it sits inside the reserved cells: its place in [`MARKS`].
    ///
    /// The same list that decides how many cells there are decides which one
    /// this is, so a mark can never be drawn past the reservation.
    fn cell(self) -> u16 {
        let at = MARKS.iter().position(|m| *m == self).unwrap_or(0);
        u16::try_from(at).unwrap_or(0) * MARK_WIDE
    }

    /// Does a line with this affordance carry this mark?
    const fn shown(self, a: Affordance) -> bool {
        match self {
            Self::Adjusts => a.arrows,
            Self::Types => a.types_into,
            // `Enter` HERE RESTORES, and on the other 19 lines it copies.
            // Without this mark the two are indistinguishable, and the one who
            // loses is whoever pressed it expecting to confirm.
            Self::Restores => a.restores,
        }
    }

    /// Its glyph.
    ///
    /// Icons are **tokens** (invariant 10): whoever knows the codepoint is the
    /// host, and a name that does not exist does not compile here — the enum
    /// is generated.
    const fn glyph(self) -> Icon {
        match self {
            Self::Adjusts => Icon::Adjust,
            Self::Types => Icon::Edit,
            Self::Restores => Icon::History,
        }
    }

    /// Is it LIT?
    ///
    /// Only while it is acting. At rest it is affordance — it says what the key
    /// would do —, and affordance does not compete for attention with the
    /// focused item.
    const fn lit(self, target: bool, typing: bool) -> bool {
        match self {
            // THE TYPING ONE LIGHTS UP WHILE TYPING, and not only on focus: it
            // is the only sign that the next digit appends instead of
            // replacing.
            Self::Types => typing,
            Self::Adjusts | Self::Restores => target,
        }
    }
}

/// What action line `n` responds to. Outside the adjustments, nothing.
const fn affordance(n: usize) -> Affordance {
    match n {
        // Size: steps by 1 px, and is typed as a number.
        0 => Affordance {
            arrows: true,
            types_into: true,
            restores: true,
        },
        // Stroke and cap step; absolute toggles.
        1 | 2 | 4 => Affordance {
            arrows: true,
            types_into: false,
            restores: true,
        },
        // THE COLOR DOES NOT STEP. It is free text, and there is no "next color" —
        // what changes it is the typing, on the line itself.
        3 => Affordance {
            arrows: false,
            types_into: true,
            restores: true,
        },
        // The 19 forms of copy are not an adjustment: there the arrow switches
        // icons, which is how two similar drawings are compared without leaving
        // the sheet. And `Enter` COPIES — there is nothing to restore.
        _ => Affordance {
            arrows: false,
            types_into: false,
            restores: false,
        },
    }
}

/// Is this column of the search line the filter glyph?
///
/// It asks the LAYOUT, which is the same object the drawing put the glyph from
/// — so there is no second answer for one of them to drift away from, and a
/// funnel that gave way has no cells for the click to land on.
fn in_filter(search: &Layout, column: u16) -> bool {
    search
        .field(field::FILTER)
        .is_some_and(|f| column >= f.at && column < f.at.saturating_add(f.width))
}

/// The words of a query. Empty gives back empty.
///
/// Splits on space AND on ASCII punctuation, the same boundary
/// `word_prefix` uses on the text: without that `arrow-up` would be a
/// single token and would not match the name, which the text splits in two.
fn search_words(q: &str) -> Vec<&str> {
    q.split(|c: char| c.is_whitespace() || c.is_ascii_punctuation())
        .filter(|p| !p.is_empty())
        .collect()
}

/// Is `t` a prefix of some WORD of `text`?
///
/// A loose substring would give the same class of error that already cost the
/// symbols browser: searching `sun` would match `sun`glasses before `sun`, and
/// since "the name contains it" scores better than "it has the tag", the
/// obvious result would fall behind.
fn word_prefix(text: &str, t: &str) -> bool {
    text.split(|c: char| !c.is_alphanumeric())
        .any(|p| p.starts_with(t))
}

/// Which of the buffer's two screens is in use.
///
/// `View` and not `Screen`: `Screen` is the design crate's frame builder — the
/// thing that hands out rows, budgets and the answer to the host's two
/// questions. Two types of one name in one file is how a reader stops knowing
/// which is which.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum View {
    /// The icon grid.
    Grid,
    /// The sheet of one icon: what it is, how to customize it and how to copy it.
    Sheet {
        /// The focused line, in the single index of [`State::action_rows`].
        option: usize,
        /// The first action line drawn. The Lucide sheet has 24 actionable lines
        /// against the 9 of the symbols browser: in a short window it does NOT fit,
        /// and without scrolling the last ones would be unreachable.
        top: usize,
    },
}

/// Where every block of the sheet goes, for one window.
///
/// A record and not seven functions: the drawing, the click, the scrolling and
/// the cursor's ceiling all need the same rows, and every one of them that
/// recomputed a piece is a place for the pieces to disagree.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct SheetRows {
    /// The row the drawing sits on.
    title: u16,
    /// How many cells the drawing's box is worth.
    title_tall: u16,
    /// Is the drawing at the screen's own size?
    huge: bool,
    /// The first information line.
    info: u16,
    /// The row the rule between the two blocks NAMES — the hairline is at its
    /// bottom edge, so the row itself is the air.
    rule: u16,
    /// The first action line.
    action: u16,
    /// How many action lines fit.
    fit: usize,
}

impl SheetRows {
    /// The row the name sits on: one under the drawing's top, and never past
    /// the drawing's own box.
    ///
    /// The name shares the drawing's rows and not its line, because two runs on
    /// one line share its MIDDLE — and the middle of a `huge` is three cells
    /// lower than the middle of the name.
    fn name_row(self) -> u16 {
        self.title
            .saturating_add(AIR.min(self.title_tall.saturating_sub(AIR)))
    }
}

/// A Lucide icon, with only what the browser uses.
///
/// `Figure` and not `Icon`: `Icon` is already the TOKEN enum that comes from
/// the WIT — the icon vocabulary of the interface itself (invariant 10). They
/// are different things, and the compiler would not let the two share a name.
struct Figure {
    /// Lucide's canonical name: `house`, `arrow-up-right`.
    name: String,
    /// What the SCREEN draws — the codepoint of the remapped face.
    cp: char,
    /// What LUCIDE publishes. It draws nothing here; it serves whoever pastes
    /// into a page that uses their font. See `LUCIDE_FONT` in the renderer.
    lcp: u32,
    cats: Vec<String>,
    aliases: Vec<String>,
    /// One tag list per language, in [`TAG_LANGUAGES`] order.
    ///
    /// It was `tags_pt` and `tags_en`, and the pair was the shape a third
    /// language could not fit.
    tags: Vec<Vec<String>>,
    /// The unaccented forms of every tag — they do not go to the screen.
    search: Vec<String>,
    /// The nodes of the drawing, encoded by the generator.
    nos: String,
}

impl Figure {
    /// The SVG nodes, decoded: `[(element, [(attribute, value)])]`.
    ///
    /// Decoding happens on the COPY, and not on load: there are 1,668 icons and
    /// instantiation has a budget of 5 ms (section 5.2) — keeping `Vec<Vec<..>>`
    /// for all of them would cost twice the allocations to serve one at a time.
    fn nos(&self) -> Vec<(&str, Vec<(&str, &str)>)> {
        self.nos
            .split(';')
            .filter(|n| !n.is_empty())
            .map(|no| {
                let mut parts = no.split('|');
                let element = parts.next().unwrap_or_default();
                let attributes = parts.filter_map(|a| a.split_once('=')).collect::<Vec<_>>();
                (element, attributes)
            })
            .collect()
    }

    /// The component name in the frameworks: `arrow-up` -> `ArrowUp`.
    fn component(&self) -> String {
        self.name
            .split('-')
            .filter(|p| !p.is_empty())
            .map(|p| {
                let mut c = p.chars();
                match c.next() {
                    Some(first) => first.to_uppercase().collect::<String>() + c.as_str(),
                    None => String::new(),
                }
            })
            .collect()
    }

    /// How well this icon matches the query. Lower is better; `None` does not match.
    ///
    /// ALL the tokens have to match, and the score is the WORST among them:
    /// whoever typed `arrow up` wants the one that has both, and not the one that
    /// has one of them very well.
    fn match_score(&self, tokens: &[&str]) -> Option<u8> {
        let mut worst = 0;
        for t in tokens {
            worst = worst.max(self.word_score(t)?);
        }
        Some(worst)
    }

    /// The score of ONE word of the query.
    fn word_score(&self, t: &str) -> Option<u8> {
        if self.name == t {
            return Some(0);
        }
        if self.name.starts_with(t) {
            return Some(1);
        }
        if word_prefix(&self.name, t) {
            return Some(2);
        }
        // THE ALIAS SCORES LIKE A NAME, almost.
        //
        // `home` is an alias of `house`, and Lucide marks it as deprecated — but
        // whoever types `home` is looking for the little house, not a deprecation
        // notice. Being behind the name is enough for `house` to win when both
        // of them match.
        if self.aliases.iter().any(|a| word_prefix(a, t)) {
            return Some(3);
        }
        if self.cats.iter().any(|c| word_prefix(c, t)) {
            return Some(4);
        }
        // EVERY language's list: somebody reading the interface in English
        // still knows the Portuguese word for a thing, and refusing to find it
        // would be taking a search away to tidy up.
        if self
            .tags
            .iter()
            .flatten()
            .chain(self.search.iter())
            .any(|g| word_prefix(g, t))
        {
            return Some(5);
        }
        None
    }

    /// The tags the footer shows: **the reader's language first**, the others
    /// only as a complement.
    ///
    /// The eight is not decoration — some icons carry 82 words, and the footer
    /// is one line. Which eight it is was the defect: the order was fixed, so
    /// whoever read the interface in English got eight Portuguese words and
    /// none of their own.
    fn visible_tags(&self, mine: usize) -> impl Iterator<Item = &String> {
        ordered(mine, self.tags.len())
            .filter_map(|i| self.tags.get(i))
            .flatten()
            .take(8)
    }
}

