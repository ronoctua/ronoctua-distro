const TAG_LANGUAGES: &str = env!("RONOCTUA_TAG_LANGUAGES");

/// The tag lists to show, the reader's FIRST.
///
/// The order is what makes the elision cut somebody else's language before the
/// reader's on a narrow screen, and it is the whole of what the seeded language
/// buys: no word here is chosen, only the order they come in.
fn ordered(mine: usize, how_many: usize) -> impl Iterator<Item = usize> {
    core::iter::once(mine).chain((0..how_many).filter(move |i| *i != mine))
}

/// The subtags of [`TAG_LANGUAGES`], in order.
fn tag_languages() -> impl Iterator<Item = &'static str> {
    TAG_LANGUAGES.split(',').filter(|s| !s.is_empty())
}

/// The narrowest the query is worth keeping — the floor of the field that
/// takes what the search line has left over.
///
/// A PREFERENCE, in the crate's two-phase sense: it holds while the counter or
/// the filter glyph can still give way, and it is the first thing to go after
/// that. What never gives way is that nothing leaks off the screen.
const MIN_SEARCH: u16 = 12;

/// The advance of the Lucide face, in thousandths of an em: a WHOLE em.
const LUCIDE_ADVANCE: u16 = 1000;

/// The advance of the text face, in thousandths of an em — the cell's own
/// width.
///
/// `typography.nix` calls it "the constant that holds up the footer's layout",
/// and it is measured rather than chosen: every one of the 135 faces has one
/// advance per width, and at normal width it is exactly `600/1000 em`.
const CELL_ADVANCE: u16 = 600;

/// How many cells across ONE Lucide drawing takes, given how many it is tall.
///
/// **This is the only measurement the design crate cannot make for this
/// buffer, and the reason is the face.** `ICON` is two cells because a UI glyph
/// is `0.600 em` wide and the cell is `0.600 em` wide, so a glyph is as wide as
/// it is tall in cells; the Lucide face's advance is a full em, so the same
/// drawing at the same height is `1000/600` cells wider. The number used to be
/// written down as a `4` with the arithmetic in a comment beside it, and the
/// sheet then wrote `ICON_COLUMNS * 3 + 1` for the same drawing at the huge
/// scale — a second answer, from the same question, three lines apart.
///
/// The heights come from the HOST (invariant 11), so both answers move together
/// when `typography.nix` does: `large` is 2 cells and gives 4, `huge` is 6 and
/// gives 10.
const fn drawing_wide(tall: u16) -> u16 {
    tall.saturating_mul(LUCIDE_ADVANCE).div_ceil(CELL_ADVANCE)
}

/// How many cells of height a height the host reported is worth.
///
/// `max(1)`, for the same reason `ronoctua_design::tall` does it: a host that
/// reported zero would put every row of the frame on one line, and a run always
/// occupies at least the cell it names. It is written out here because the
/// crate's own helper takes a `Scale` — and a component never names one, since
/// the WIT's `Scale` and the arithmetic's are two enums of one name.
const fn cells(reported: u16) -> u16 {
    if reported == 0 { 1 } else { reported }
}

