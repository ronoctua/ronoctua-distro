//! The Unicode symbol browser — `LEADER i u`.
//!
//! Sibling of the Nerd Fonts browser, and the other half of the same question: the glyph
//! one finds the right ICON among 10,473; this one finds the right CHARACTER — the
//! arrow, the operator, the box-drawing piece, the Greek letter — without leaving for a
//! website.
//!
//! # Why the database has 7,529 and not 155,000
//!
//! Because the renderer embeds ONE face and has no fallback chain (section
//! 6.4, deliberate). A character the font does not draw would show up as
//! tofu, and showing tofu is silent fallback in different clothes. The database is the
//! intersection of UnicodeData.txt with the font's `cmap` — what can be seen, and only that.
//!
//! # What this component does NOT do
//!
//! It does not read a file, does not write a file, does not rasterise, does not translate. The database
//! arrives EMBEDDED (`include_str!` at build time), the screen comes out as a `DisplayList`, and
//! what puts things on the clipboard is the host. Invariant 11, and it is not
//! discipline: the WIT `world` offers neither a filesystem nor i18n.

