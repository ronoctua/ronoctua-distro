/// The database, generated by `gen-unicodedb.py` and embedded at build time.
const BASE: &str = include_str!(env!("RONOCTUA_UNICODE_JSON"));

/// The SUBTAGS whose tags the database carries, in the order it wrote them.
///
/// Generated from `assets/i18n/languages.nix` and handed in as a variable, the
/// same way the database itself is: the buffer cannot read a file and must not
/// carry a list of languages written by hand. The FIRST is the source, English,
/// which is where the words come from.
///
/// This is not the buffer knowing a language (invariant 11). It is the buffer
/// knowing how many tag lists it is holding and what to call the field each one
/// came out of — the words themselves it neither writes nor translates.
const TAG_LANGUAGES: &str = env!("RONOCTUA_TAG_LANGUAGES");

/// The tag lists to show, the reader's FIRST.
///
/// The order is what makes the elision cut somebody else's language before the
/// reader's on a narrow screen, and it is the whole of what the seeded language
/// buys: no word here is chosen, only the order they come in.
fn ordered(mine: usize, how_many: usize) -> impl Iterator<Item = usize> {
    core::iter::once(mine).chain((0..how_many).filter(move |i| *i != mine))
}

/// The subtags of [`TAG_LANGUAGES`], in order.
fn tag_languages() -> impl Iterator<Item = &'static str> {
    TAG_LANGUAGES.split(',').filter(|s| !s.is_empty())
}

/// The filter the buffer OPENS with.
///
/// # Why it is born WRITTEN in the field, and not as a flag
///
/// Because a filter the user did not type and cannot see is the worst variety of
/// hidden state: they would see 3.5xx of 7,529 with no clue as to why. As it
/// stands, the filter is a filter like any other — visible,
/// editable, and `Esc` undoes it.
///
/// # And why it is written in ENGLISH
///
/// Because it is the one query in this buffer that NOBODY TYPED, and a buffer
/// may not know the language (invariant 11: it does not translate, and
/// `Context` carries no language on purpose). It used to open in
/// `familia:emoji`, so an en-GB session opened showing a Portuguese word in a
/// field it never asked for. Where a single language fits, invariant 18 says
/// which one it is.
///
/// Typing is untouched: the parser takes every language's word alike, and that
/// is the half of the search that belongs to whoever is searching.
const INITIAL_VALUE: &str = "emoji";

/// The seven words this buffer WRITES, and the names each answers to.
///
/// `(key, english, portuguese)`. English is the CANONICAL one — it is what
/// `Phrases::or` falls back to when the host sent nothing, and what invariant 18
/// asks for where a single language fits. Portuguese is here because the
/// lexicon is bilingual by design (`assets/lexicon/tags.en-pt.toml`).
///
/// The THIRD name is whatever the host resolved, and the parser has to take it
/// too: a language whose word is neither of these two would otherwise write a
/// filter on `Esc` that the buffer itself could not read back.
const PREFIX_KEYS: [(&str, &str, &str); 7] = [
    (key::PREFIX_SYMBOLS, "symbols", "simbolos"),
    (key::PREFIX_FAMILY, "family", "familia"),
    (key::PREFIX_BLOCK, "block", "bloco"),
    (key::PREFIX_NAME, "name", "nome"),
    (key::PREFIX_GROUP, "group", "grupo"),
    (key::PREFIX_SUBGROUP, "subgroup", "subgrupo"),
    (key::PREFIX_TONE, "tone", "tom"),
];

/// The word this buffer writes for one prefix, in the person's language.
fn word(phrases: &Phrases, key: &str) -> String {
    let english = PREFIX_KEYS
        .iter()
        .find(|(k, _, _)| *k == key)
        .map_or("", |(_, en, _)| *en);
    phrases.or(key, english)
}

/// The filter the buffer opens with, written the way the person reads.
fn initial_filter(phrases: &Phrases) -> String {
    format!("{}:{INITIAL_VALUE}", word(phrases, key::PREFIX_FAMILY))
}

/// The CANONICAL name of a typed prefix, whichever language it came in.
///
/// Everything downstream matches on the English name, so this is the one place
/// that knows there are three. A word that is no prefix at all comes back
/// unchanged, and the match below turns it into "no filter" — which is what
/// keeps a pasted `http://` from being swallowed as a filter.
fn canonical_prefix(typed: &str, phrases: &Phrases) -> String {
    for (k, english, portuguese) in PREFIX_KEYS {
        if typed == english || typed == portuguese || typed == word(phrases, k) {
            return english.to_owned();
        }
    }
    typed.to_owned()
}

