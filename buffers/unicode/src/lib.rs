//! The Unicode symbol browser — `LEADER i u`.
//!
//! Sibling of the Nerd Fonts browser, and the other half of the same question: the glyph
//! one finds the right ICON among 10,473; this one finds the right CHARACTER — the
//! arrow, the operator, the box-drawing piece, the Greek letter — without leaving for a
//! website.
//!
//! # Why the database has 7,529 and not 155,000
//!
//! Because the renderer embeds ONE face and has no fallback chain (section
//! 6.4, deliberate). A character the font does not draw would show up as
//! tofu, and showing tofu is silent fallback in different clothes. The database is the
//! intersection of UnicodeData.txt with the font's `cmap` — what can be seen, and only that.
//!
//! # What this component does NOT do
//!
//! It does not read a file, does not write a file, does not rasterise, does not translate. The database
//! arrives EMBEDDED (`include_str!` at build time), the screen comes out as a `DisplayList`, and
//! what puts things on the clipboard is the host. Invariant 11, and it is not
//! discipline: the WIT `world` offers neither a filesystem nor i18n.
//!
//! # And it no longer decides its own geometry
//!
//! It draws through `ronoctua-design`, which is what invariant 12 names. Three
//! things follow, and all three are the point of the crate:
//!
//!   - the grid is a [`Grid`]. `grid_columns`, `height`, `panel_first_row`,
//!     `rule_row`, `grid_first_row`, `footer_row` and `row_step` were seven
//!     functions here and seven more in each of the other two browsers, each
//!     with its own constants and each with a bare `2` for air on the right
//!     that the host had already taken off both sides;
//!   - the label-and-value sheet is [`Screen::sheet`], with ONE label width for
//!     the three browsers. It was 24 here, 24 in the glyph browser and 20 in
//!     Lucide, and nothing said why the same sheet was spaced differently;
//!   - `wit_bindgen::generate!` is gone, and with it the crate-wide
//!     `#![allow(unsafe_code, missing_docs)]` this file used to need. The
//!     exemption belongs to the one crate that generates bindings.
//!
//! **A heading closes with whitespace and never with a rule.** The two rules
//! this buffer still draws are boundaries between BLOCKS — above the grid, and
//! between the sheet's three parts — and they are full bleed, at the bottom
//! edge of the row they name.

