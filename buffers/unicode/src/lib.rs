/// The filter the buffer OPENS with.
///
/// # Why it is born WRITTEN in the field, and not as a flag
///
/// Because a filter the user did not type and cannot see is the worst variety of
/// hidden state: they would see 3.5xx of 7,529 with no clue as to why. As it
/// stands, the filter is a filter like any other — visible,
/// editable, and `Esc` undoes it.
const INITIAL_FILTER: &str = "familia:emoji";

/// How many cells the search needs before the counter is worth showing.
const MIN_SEARCH: u16 = 12;

/// How many columns a character at icon scale occupies.
///
/// The cell is `0.600 x the font size` wide and the icon is drawn at
/// twice the body size: two columns, with the ink filling both entirely.
const ICON_COLUMNS: u16 = 2;

/// How many columns the 23 DOUBLE-WIDTH characters occupy.
///
/// # INVARIANT: this has to be SMALLER than [`State::STEP`]
///
/// The font gives an advance of 1200 to 23 characters (the long arrows, `U+27F5` and
/// company) against the 600 of all the others. At icon scale that is
/// four columns of ink where the grid's step reserves five — one column of
/// air is left instead of three, and nothing collides.
///
/// Whoever tightens [`HORIZONTAL_GAP`] to two tomorrow makes those 23 paint
/// over their neighbour, and nothing else on screen would say so. That is why the test
/// asserts the relation, and not the numbers.
const DOUBLE_COLUMNS: u16 = ICON_COLUMNS * 2;

/// The gap between one character and the next, horizontally.
///
/// # Why four, and not the glyph browser's three
///
/// Because there every drawing is the Iosevka's, and here 3,944 are from the emoji face — which
/// has a `1.245 at_cell` advance against the cell's `0.600`. At the large scale that
/// is **49.8 px** of ink in a step of 54, against 28.5 px of gap vertically: the
/// grid came out squashed sideways, and there was nowhere to put the selection marker without
/// writing over the drawing — which is what happened on the first attempt.
///
/// With four the step becomes 75.6 px: one cell for the marker, 49.8 for the
/// ink and 15 px of gap, against the 28.5 vertical ones. Fewer fit per row, and it is the
/// price of the selection being visible in a grid that does not obey colour.
const HORIZONTAL_GAP: u16 = 4;

/// Where the selection marker lives, within the grid's step.
///
/// The drawing starts ONE cell after it, always — including in the cells with no
/// marker. Shifting only the focused item would make the whole grid move
/// on every key.
const MARKER_COLUMN: u16 = 0;
const DRAWING_COLUMN: u16 = MARKER_COLUMN + 1;

/// The unit of spacing: one cell.
///
/// **The space between blocks already comes in the line box** — the font's box is
/// `1.25 at_cell` against a `1.45` line height, so every run carries `0.10 at_cell` of
/// air above and below. Adding an empty cell to that is slack over slack. This
/// constant measures the HORIZONTAL gap, where there is no box at all.
const BREATHING: u16 = 1;

/// Where the text starts when there is a character to its left.
const AFTER_ICON: u16 = ICON_COLUMNS + BREATHING;

/// How much the filter icon takes from the search line: it is the gap before it.
const FILTER_WIDTH: u16 = AFTER_ICON;

/// How many cells a family's label reserves in the panel.
///
/// The buffer sends a KEY and never sees the translated sentence (invariant 11), so
/// it declares how much it reserved and the `symbols-filters` check verifies both
/// languages against this budget.
const LABEL_WIDTH: u16 = 24;

/// What separates one column of options from the next.
const SPACE_BETWEEN_OPTIONS: u16 = 2;

/// Where the first column of options starts.
const PANEL_INDENT: u16 = 2;

/// The prefix of the families' text keys.
const FAMILY_PREFIX: &str = "unicode-family-";

/// The prefix of the emoji groups' text keys.
const GROUP_PREFIX: &str = "unicode-group-";

/// The prefix of a skin tone's text key.
const TONE_PREFIX: &str = "unicode-tone-";

/// The family whose SUB-FILTERS the panel shows.
const FAMILY_EMOJI: &str = "emoji";

/// The option that removes the family filter.
const FAMILY_ALL: &str = "all";

/// The prefix of the command text keys, the same the registry uses.
const KEY_PREFIX: &str = "cmd-";

/// What separates one tag from another on the line.
const SEPARATOR: &str = "  ";

/// How many rows the sheet needs BESIDES the character to justify the larger scale.
const ROWS_BESIDES_GLYPH: u16 = 6;

/// Where the value starts, on the sheet's label/value rows.
const VALUE_COLUMN: u16 = 24;

