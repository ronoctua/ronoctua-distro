/// Does the filter icon fit in this window?
fn filter_fits(ctx: &Context) -> bool {
    ctx.columns > MIN_SEARCH + AFTER_ICON
}

/// Is this column of the search line the filter icon?
///
/// The same function the drawing uses to know whether to emit it — if there were two,
/// one of them changing would be enough for the click to land in the void.
///
/// The cell of air BEFORE the icon belongs to it, like the air beside a grid
/// item: a target with slack around it is a target one does not miss.
fn in_filter(ctx: &Context, column: u16) -> bool {
    filter_fits(ctx) && column.saturating_add(AFTER_ICON) >= ctx.columns
}

/// A query's words. Empty returns empty.
fn search_words(q: &str) -> Vec<&str> {
    // It splits on whitespace AND on ASCII punctuation, the same boundary
    // `word_prefix` uses on the text: without that, `seti-ui` would be one token
    // and would not match the `seti-ui` tag, which the text splits in two.
    //
    // ASCII punctuation, and not "everything that is not alphanumeric": a pasted
    // character (`\u{2190}`) is not alphanumeric, and splitting on it would leave the
    // query EMPTY — the gesture of pasting a character to find out which it is
    // would show the whole database.
    q.split(|c: char| c.is_whitespace() || c.is_ascii_punctuation())
        .filter(|p| !p.is_empty())
        .collect()
}

/// Is `t` a prefix of some WORD of `text`?
///
/// # Why a word prefix, and not a loose substring
///
/// Because the loose substring gave two wrong answers at once. Searching
/// `seta` matched `pe·seta· sign` — and since "the name contains" scores better than
/// "has the tag", `PESETA SIGN` came BEFORE the real arrows.
///
/// And a PREFIX, and not a whole word, because the search is incremental: whoever typed
/// `arr` has not finished writing `arrow` yet.
///
/// The boundary is "not alphanumeric", which serves both vocabularies: Unicode
/// names are separated by spaces and hyphens, Nerd Fonts ones by `_` and `-`.
fn word_prefix(text: &str, t: &str) -> bool {
    text.split(|c: char| !c.is_alphanumeric())
        .any(|p| p.starts_with(t))
}

// THE LABEL-AND-VALUE ROW IS NOT WRITTEN HERE ANY MORE.
//
// It was `pair()`, with a `VALUE_COLUMN` of its own — and the glyph browser had
// the same function with the same 24, and Lucide had it with 20. It is
// `Screen::sheet` now, and the one width is `SHEET_LABEL`: the label shrinks to
// half the window rather than giving way, because a column of values with
// nothing saying what they are is not a narrower sheet.
//
// The value stays typed, and that is the half the crate did NOT flatten: two of
// this sheet's rows are KEYS (the family and the width explanation) and the
// rest are DATA, so what crosses is a `Run` and never a `String`.

/// Which of the buffer's two screens is in use.
///
/// Named `View` and not `Screen`: `Screen` is the design crate's frame builder,
/// and two types of one name in one file is how a reader stops knowing which is
/// which.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum View {
    /// The character grid.
    Grid,
    /// The focused character's sheet, with the selected copy option.
    Sheet { option: usize },
}

/// The filter panel's geometry — where each option is drawn.
///
/// [`Panel::cell`] and [`Panel::at_cell`] are the same calculation in both directions: the
/// drawing and the click have to agree by CONSTRUCTION, and not by luck.
/// What there is on a row of the panel.
#[derive(Debug, Clone, PartialEq, Eq)]
enum PanelRow {
    /// The rule that separates a section from the previous one.
    Rule,
    /// The section's label, small and dimmed.
    Label(String),
    /// Options, by their indices in the derived list.
    Options(Vec<usize>),
}

/// The filter panel's geometry — where each option is drawn.
///
/// # Why an EXPLICIT list of rows, and not arithmetic
///
/// Because the panel stopped being a rectangle. It has sections — the general
/// filters, and the emoji ones separated by a rule and a label — and with sections the
/// calculation "index n goes on row n / columns" stops holding: it does not know about the
/// rows that have no option at all.
///
/// With the rows built once and kept, [`Panel::cell`] and
/// [`Panel::at_cell`] become two readings of the SAME list, and not two calculations that
/// have to agree. The drawing and the click close by construction.
struct Panel {
    /// Every row, before the cut by height.
    all_of: Vec<PanelRow>,
    /// The first visible row — the panel SCROLLS, it does not paginate.
    ///
    /// Paginating required knowing "how many options fit on a page", and with sections
    /// of different sizes that stopped being a division. Scrolling only needs to
    /// know where the selection is.
    first: usize,
    /// How many rows fit.
    visible: usize,
    /// ONE row of options, as the design crate lays a grid out.
    ///
    /// The panel's rows are an explicit list because of the sections, so what
    /// is borrowed from [`Grid`] is the row: how many labels fit across, and
    /// which cell each one starts at. [`Grid::at`] and [`Grid::index_at`] are
    /// the same arithmetic in both directions, which is what closes the drawing
    /// and the click by construction instead of by agreement.
    row: Grid,
}

impl Panel {
    /// Builds the panel. `sections` is `(label, how many options)`, in order; the
    /// first section carries no label — it is the panel as it always was.
    ///
    /// `from` is the row the panel starts on, and it is what says how much of
    /// the window is left to share with the grid.
    fn new(
        ctx: &Context,
        from: u16,
        sections: &[(Option<String>, usize)],
        selection: usize,
    ) -> Self {
        // ONE ROW OF LABELS, from cell zero. There is no indent of its own any
        // more: the host has already moved the whole buffer in by
        // `space.buffer.marginX`, and a buffer that indents again indents
        // twice — which is the "every buffer with a margin of its own" in the
        // report this migration came from.
        let row = Grid::fitted(ctx.columns, SHEET_LABEL, 0, RULE_ROW, RULE_ROW);
        let per_row = usize::from(row.across);

        let mut all_of = Vec::new();
        let mut n = 0usize;
        for (label, how_many) in sections {
            if let Some(r) = label {
                all_of.push(PanelRow::Rule);
                all_of.push(PanelRow::Label(r.clone()));
            }
            for chunk in (n..n + how_many).collect::<Vec<_>>().chunks(per_row) {
                all_of.push(PanelRow::Options(chunk.to_vec()));
            }
            n += how_many;
        }

        // A CEILING OF HALF WHAT IS LEFT below the search line and above the
        // rule. The panel shares the screen with the grid, and the grid is the
        // buffer.
        let rest = ctx.lines.saturating_sub(from).saturating_sub(RULE_ROW);
        let ceiling = (usize::from(rest) / 2).max(1);
        let visible = all_of.len().min(ceiling).max(1);

        // IT SCROLLS TO THE SELECTION. Without this, choosing a skin tone with the panel
        // clipped would move the highlight off screen — the key moves and nothing
        // changes in what one sees.
        let where_at = all_of
            .iter()
            .position(|l| matches!(l, PanelRow::Options(v) if v.contains(&selection)))
            .unwrap_or(0);
        let last_f = all_of.len().saturating_sub(visible);
        let first = if where_at < visible {
            0
        } else {
            (where_at + 1 - visible).min(last_f)
        };

        Self {
            all_of,
            first,
            visible,
            row,
        }
    }

    /// How many rows the panel occupies on screen.
    fn lines(&self) -> u16 {
        u16::try_from(self.visible).unwrap_or(u16::MAX)
    }

    /// The visible rows, with each one's SCREEN row.
    fn visible(&self) -> impl Iterator<Item = (u16, &PanelRow)> {
        self.all_of
            .iter()
            .skip(self.first)
            .take(self.visible)
            .enumerate()
            .filter_map(|(i, l)| u16::try_from(i).ok().map(|i| (i, l)))
    }

    /// Where option `n` is drawn, if it is visible.
    fn cell(&self, n: usize) -> Option<(u16, u16)> {
        for (line, content) in self.visible() {
            if let PanelRow::Options(v) = content
                && let Some(i) = v.iter().position(|o| *o == n)
            {
                return Some((line, self.row.at(i)?.1));
            }
        }
        None
    }

    /// Which option is in the clicked cell, if any.
    ///
    /// The other direction of [`Self::cell`], and the SAME function of the
    /// design crate answers both.
    fn at_cell(&self, line: u16, column: u16) -> Option<usize> {
        let content = self.visible().find(|(l, _)| *l == line)?.1;
        let PanelRow::Options(v) = content else {
            return None;
        };
        v.get(self.row.index_at(self.row.first, column)?).copied()
    }

    /// How much a label may take: the whole column, capped by what the window
    /// still has.
    fn room(&self, ctx: &Context, column: u16) -> u16 {
        budget(ctx.columns, column, SHEET_LABEL)
    }
}

/// A character, with only what the browser uses.
struct Symbol {
    cp: u32,
    /// The codepoints that get COPIED.
    ///
    /// Almost always it is just the `cp`; in emoji it is the whole SEQUENCE — 👩‍💻 is
    /// three. It is a field separate from `shows` because the two part company on
    /// combining marks: there the drawing carries the dotted circle in front and
    /// the copy must not.
    seq: Vec<u32>,
    /// What the GRID draws. The same as the character, except in the 302 combining
    /// marks — there it comes from the generator with the dotted circle in
    /// front, because a mark drawn on its own takes up no room: it disappears
    /// or paints over its neighbour.
    ///
    /// **It is never what gets copied.** Pasting `◌́` into the user's document is the
    /// worst defect this feature can have, and the only one that survives
    /// any visual inspection. What copies is `character()`.
    shows: String,
    name: String,
    /// The lower-cased name, computed ONCE at load.
    ///
    /// It does not come from the generator: that would be 300 KB in the database to say what a
    /// `to_lowercase()` per character solves at startup. What must not
    /// exist is the conversion per KEY, which is what there was.
    name_min: String,
    aliases: Vec<String>,
    /// Unicode's general category, two letters (`Sm`, `Mn`, `Lu`).
    cat: String,
    /// The family: the 25 categories grouped into seven, which is how one searches.
    family: String,
    block: String,
    /// The emoji group (`carinhas`, `bandeiras`). Empty outside the emoji.
    group: String,
    /// The emoji subgroup, as the CLDR names it. Empty outside the emoji.
    subgroup: String,
    /// The skin tone, when the sequence has a modifier. Empty when it does not.
    ///
    /// It comes from the SEQUENCE, and not from the name: in English the CLDR writes "light skin
    /// tone" at the end, in Portuguese it writes "pele clara", and there are emoji whose name
    /// mentions skin without having any modifier. The codepoint is there, or it is not.
    tone: String,
    /// The canonical decomposition, in hexadecimal. Empty when there is none.
    decomp: String,
    /// How many cells of ADVANCE the font gives this character: 0, 1 or 2.
    ///
    /// It comes from the `hmtx`, measured by the generator, and not from the category: there are 302 with
    /// zero advance and only 283 with category `Mn`. What decides what is going to be
    /// drawn is the font.
    width: u8,
    /// One tag list per language, in [`TAG_LANGUAGES`] order.
    ///
    /// It was `tags_pt` and `tags_en`, and the pair was the shape a third
    /// language could not fit: the struct, the parser, the search and the
    /// footer all said "two" out loud.
    tags: Vec<Vec<String>>,
    /// The UNACCENTED forms of every tag, only the ones that differ.
    search: Vec<String>,
}

impl Symbol {
    /// The real character — the one that gets copied.
    fn character(&self) -> Option<char> {
        char::from_u32(self.cp)
    }

    /// The TEXT that gets copied: one character, or the emoji's whole sequence.
    ///
    /// Copying only the `cp` of 👩‍💻 would give 👩 — the emoji truncated at the first
    /// codepoint, which is the easiest defect to miss: the screen looks right and
    /// what goes into the user's document is wrong.
    fn text(&self) -> String {
        self.seq.iter().filter_map(|c| char::from_u32(*c)).collect()
    }

    /// Is this record an emoji?
    fn is_emoji(&self) -> bool {
        self.family == FAMILY_EMOJI
    }

    /// How many cells of INK the drawing takes, at a scale worth `cells` cells.
    ///
    /// # The arithmetic, so there is no loose number
    ///
    /// [`Self::width`] is what the generator measured from the font's `hmtx`,
    /// in columns at the body's size: one for the 135 ordinary faces, two for
    /// the 23 long arrows (`U+27F5` and company) **and for the whole emoji
    /// face**, whose advance is `2550/2048 = 1.245 em` against the cell's
    /// `0.600`. And the scale widens as much as it raises — the cell is
    /// `0.600 em`, so a character drawn at twice the body's size has twice the
    /// advance, which is the same rule `DisplayList::columns_of` charges data
    /// by on the other side.
    ///
    /// So the ink is `width x cells`, and `cells` comes from the HOST
    /// (invariant 11): a buffer has neither the font size nor the line height.
    /// It used to be two constants — `ICON_COLUMNS` and `DOUBLE_COLUMNS` — that
    /// happened to equal this product at the one scale the grid uses, and said
    /// nothing at the scale the sheet uses.
    ///
    /// A zero-advance mark takes ONE column and not none: what is drawn is the
    /// dotted circle it sits on (see [`Self::shows`]).
    fn ink(&self, cells: u16) -> u16 {
        u16::from(self.width.max(1)).saturating_mul(cells)
    }

    /// Does any tag of this character contain `termo`?
    ///
    /// EVERY language's list, and not only the reader's: somebody who reads the
    /// interface in English still knows the Portuguese word for a thing, and
    /// refusing to find it would be taking a search away to tidy up.
    fn has_tag(&self, term: &str) -> bool {
        self.tags
            .iter()
            .flatten()
            .chain(&self.search)
            .any(|t| t.contains(term))
    }

    /// Is the typed term **this** character?
    ///
    /// Copying a character and pasting it back to find out which it is the most
    /// natural gesture there is here, and this is the score that puts it first.
    ///
    /// # Why ONE character, and not "the term contains"
    ///
    /// The glyph browser can ask whether the term CONTAINS the glyph, because
    /// its glyphs are all in the PUA and nobody types them by accident. Here the
    /// database has the letters of the alphabet: with the broad form, typing
    /// `LONG LEFTWARDS ARROW` would give an identity score to `a`, and the letter `a`
    /// would appear first in a search for an arrow. It happened.
    ///
    /// It compares against the CHARACTER, never against the drawing — otherwise a pasted
    /// combining mark would not find itself, because its drawing carries the
    /// dotted circle in front.
    fn is_this(&self, term: &str) -> bool {
        // EQUALITY WITH THE WHOLE TEXT, and not with a single character.
        //
        // An emoji is a SEQUENCE — 👩‍💻 is three codepoints — and the single-character
        // rule made pasting an emoji find nothing. Exact equality,
        // and not "contains": the database has the alphabet, and the broad form would put
        // the letter `a` first in a search for an arrow. It happened.
        term.trim() == self.text()
    }

    /// How well this character matches the term — lower is better. `None` when it
    /// does not match.
    ///
    /// One function, used by the list's scoring AND by the filter: the two
    /// asked the same question with their own code in the glyph browser, and
    /// nothing stopped one from gaining a criterion the other did not have.
    fn match_score(&self, tokens: &[&str]) -> Option<u8> {
        // ALL the words have to match, and the score is the WORST of them.
        //
        // The query used to be a single string, matched whole against the name and
        // against each tag — and the tags are loose words, so `seta para
        // up` matched nothing and returned zero. Requiring all of them is what makes a
        // phrase worth more than a word, and not less.
        let mut worst = 0;
        for t in tokens {
            worst = worst.max(self.word_score(t)?);
        }
        Some(worst)
    }

    /// How well ONE word matches. Lower is better; `None` when it does not match.
    ///
    /// The order is the searcher's: the character itself is identity and beats
    /// everything; then the start of the name, a word of the name, a word of an
    /// alias, and finally a tag.
    fn word_score(&self, t: &str) -> Option<u8> {
        if self.is_this(t) {
            Some(0)
        } else if self.name_min.starts_with(t) {
            Some(1)
        } else if word_prefix(&self.name_min, t) {
            Some(2)
        } else if self.aliases.iter().any(|a| word_prefix(a, t)) {
            Some(3)
        } else if self.has_tag(t) {
            Some(4)
        } else {
            None
        }
    }

    /// The NAME and the aliases only — what the `name:` filter asks about.
    fn matches_name(&self, term: &str) -> bool {
        term.is_empty()
            || search_words(term).iter().all(|t| {
                word_prefix(&self.name_min, t) || self.aliases.iter().any(|a| word_prefix(a, t))
            })
    }

    /// The tags as they appear on screen: **the reader's language first**.
    ///
    /// The order is what makes the elision cut somebody ELSE's language on a
    /// narrow screen. It was fixed — Portuguese first — and that was a defect
    /// the moment there were two readers.
    /// FROM `ordered`, which is the same order the two sibling browsers ask
    /// for. This file had that order written out inline instead — so the
    /// shared helper was dead code here, and the three answers to "whose
    /// language comes first" were free to drift apart with nothing saying so.
    /// Clippy could not see it either: these three carry a baked table and
    /// need its path at compile time, so a lint run outside Nix does not get
    /// as far as the code.
    ///
    /// AND A WORD IS SHOWN ONCE, which is this browser's own and stays: the
    /// lists repeat across languages — a tag that is the same word in both is
    /// in both — and the reader's copy is the one that is kept.
    fn visible_tags(&self, mine: usize) -> impl Iterator<Item = &String> {
        let first = self.tags.get(mine).map(Vec::as_slice).unwrap_or(&[]);
        first.iter().chain(
            ordered(mine, self.tags.len())
                // `ordered` OPENS with the reader's own list, and that list is
                // the `first` above — what is wanted here is what follows it.
                .skip(1)
                .filter_map(move |i| self.tags.get(i))
                .flatten()
                .filter(move |t| !first.contains(t)),
        )
    }
}

/// The copy formats. One command id per format, and the same id in the keymap.
///
/// Nine, and they are the ones derivable from a codepoint. Left out are the two the
/// glyph browser has and that here would always come out empty: there is no CSS class
/// and no design system token for `U+2200`.
