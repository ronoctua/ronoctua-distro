    /// The three states the descriptor declares, as the screen they draw.
    ///
    /// `normal` is the grid, `filter` is the grid with the panel open and
    /// `sheet` is the focused glyph's — the same precedence `State::state_id`
    /// reports, because the modeline and the drawing have to agree.
    fn in_state(id: &str) -> State {
        let mut state = State::new();
        match id {
            "filter" => state.toggle_panel(),
            "sheet" => state.view = View::Sheet { option: 0 },
            _ => {}
        }
        assert_eq!(state.state_id(), id);
        state
    }

    /// The frame this buffer would return, ready to be interrogated.
    fn frame(state: &State, ctx: &Context) -> Screen<Wit> {
        let mut screen = Screen::<Wit>::of(ctx);
        match state.view {
            View::Sheet { option } => state.draw_sheet(&mut screen, ctx, option),
            View::Grid => state.draw_grid(&mut screen, ctx),
        }
        screen
    }

    /// Every text command of a frame: `(line, column, budget)`.
    fn fields(screen: &Screen<Wit>) -> Vec<(u16, u16, u16)> {
        screen
            .finish_wit()
            .iter()
            .filter_map(|c| match c {
                Command::Text(t) => Some((t.line, t.column, t.max_width)),
                _ => None,
            })
            .collect()
    }

    /// The rows a frame draws a rule on.
    fn rules(screen: &Screen<Wit>) -> Vec<u16> {
        screen
            .finish_wit()
            .iter()
            .filter_map(|c| match c {
                Command::Rule(r) => Some(r.line),
                _ => None,
            })
            .collect()
    }

    /// THE HOST'S TWO QUESTIONS, ASKED HERE — in every state and at every width
    /// the owner named.
    ///
    /// `Screen::check` runs `DisplayList::nothing_is_covered` and
    /// `nothing_overlaps`, which are the host's own code and not a second
    /// implementation of the question. Until this crate existed a buffer only
    /// met them minutes later, in Nix; this browser had never been asked at all
    /// — `browser-filters` drives the component and reads what it drew, and
    /// calls neither.
    #[test]
    fn every_state_answers_the_hosts_two_questions() {
        for id in ["normal", "filter", "sheet"] {
            let state = in_state(id);
            for columns in [46u16, 80, 110] {
                for lines in [12u16, 24, 60] {
                    let ctx = context(columns, lines);
                    frame(&state, &ctx)
                        .check()
                        .unwrap_or_else(|e| panic!("{id} at {columns}x{lines}: {e}"));
                }
            }
        }
    }

    /// NO FIELD ENDS PAST THE RIGHT EDGE.
    ///
    /// `nothing_overlaps` charges DATA for its own length, so a run that
    /// declared more than the window has and happens to be short still passes.
    /// This asks the other question: what was DECLARED fits. A budget of zero is
    /// the protocol's "to the edge" and is the only exception.
    #[test]
    fn no_field_is_declared_past_the_edge() {
        for id in ["normal", "filter", "sheet"] {
            let state = in_state(id);
            for columns in [46u16, 80, 110] {
                let ctx = context(columns, 40);
                for (line, column, budget) in fields(&frame(&state, &ctx)) {
                    assert!(
                        budget == 0 || column.saturating_add(budget) <= columns,
                        "{id}: on line {line} a field at {column} asks for {budget} \
                         cells in a window of {columns}"
                    );
                }
            }
        }
    }

    /// A RULE IS A BOUNDARY BETWEEN BLOCKS, AND NEVER AN UNDERLINE.
    ///
    /// There is no heading in this buffer and therefore no rule under one:
    /// `Screen::heading` does not draw one at all any more, because what
    /// separates a title from its content is whitespace. What is left is the
    /// boundary between the query and the content — one rule, on a row that
    /// carries no text, so the hairline the host paints at that row's bottom
    /// edge is a seam and not a line through somebody's descenders.
    #[test]
    fn a_rule_only_ever_separates_blocks() {
        let ctx = context(80, 40);

        let grid = in_state("normal");
        let drawn = rules(&frame(&grid, &ctx));
        assert_eq!(drawn, vec![grid.rule_row(&ctx)], "the grid");

        let sheet = in_state("sheet");
        let (_, cells) = State::sheet_glyph(&ctx);
        let info = u16::try_from(sheet.sheet_info().len()).unwrap_or(0);
        let step = State::sheet_step(&ctx);
        assert_eq!(
            rules(&frame(&sheet, &ctx)),
            vec![cells, cells + 1 + info * step],
            "the sheet"
        );

        // AND NOT ONE OF THEM SHARES A ROW WITH A WORD.
        for id in ["normal", "filter", "sheet"] {
            let state = in_state(id);
            let screen = frame(&state, &ctx);
            let busy: Vec<u16> = fields(&screen).into_iter().map(|(l, _, _)| l).collect();
            for line in rules(&screen) {
                assert!(
                    !busy.contains(&line),
                    "{id}: the rule on line {line} runs under a text"
                );
            }
        }
    }

    /// WHERE IT DRAWS IS WHERE IT IS FOUND — the grid.
    ///
    /// The drawing walks `Grid::at` and the click walks `Grid::index_at`, which
    /// are the same sum read forwards and backwards. They used to be two blocks
    /// of arithmetic in two functions, and the symptom of them drifting was the
    /// click landing on one glyph while the screen showed another.
    #[test]
    fn the_click_lands_on_the_glyph_that_was_drawn() {
        let state = in_state("normal");
        for columns in [46u16, 80, 110] {
            let ctx = context(columns, 40);
            let grid = state.grid(&ctx);
            for n in 0..state.visible(&ctx).len() {
                let (line, column) = grid.at(n).expect("inside the page");
                assert_eq!(
                    state.glyph_at(&ctx, column, line),
                    Some(state.top + n),
                    "{columns} columns, glyph {n}"
                );
                // The air beside a glyph belongs to it: a target with slack is a
                // target one does not miss.
                assert_eq!(
                    state.glyph_at(&ctx, column + grid.step - 1, line),
                    Some(state.top + n),
                    "{columns} columns, the air of glyph {n}"
                );
            }
            // Above the grid there is the search, and below it the name line.
            assert_eq!(state.glyph_at(&ctx, 0, grid.first - 1), None);
            assert_eq!(state.glyph_at(&ctx, 0, State::footer_row(&ctx)), None);
        }
    }

    /// The same question of the filter panel, which is a [`Grid`] too.
    #[test]
    fn the_click_lands_on_the_option_that_was_drawn() {
        let state = in_state("filter");
        for columns in [46u16, 80, 110] {
            let ctx = context(columns, 40);
            let panel = Panel::new(&ctx, state.options(), 0);
            for n in 0..state.options() {
                let Some((line, column)) = panel.cell(n) else {
                    continue;
                };
                assert_eq!(
                    panel.at_cell(line, column),
                    Some(n),
                    "{columns}: option {n}"
                );
            }
        }
    }

    /// And of the sheet's copy options, whose rows are counted from the same
    /// two numbers the drawing counts them from.
    #[test]
    fn the_click_lands_on_the_copy_option_that_was_drawn() {
        let ctx = context(80, 60);
        let state = in_state("sheet");
        let (_, cells) = State::sheet_glyph(&ctx);
        let step = State::sheet_step(&ctx);
        let info = u16::try_from(state.sheet_info().len()).unwrap_or(0);
        let first = cells + 1 + info * step + 1;
        for n in 0..FORMATS.len() {
            let line = first + u16::try_from(n).unwrap() * step;
            assert_eq!(state.option_at(&ctx, line), Some(n), "option {n}");
        }
        assert_eq!(state.option_at(&ctx, first - 1), None);
    }

    /// ONE LABEL-AND-VALUE LINE IS ONE `sheet_step`.
    ///
    /// The drawing steps by that number and the click divides by it; what
    /// `Screen::sheet` actually took is the third answer, and the three have to
    /// be one. It is the same class of defect as the click above, one level down.
    #[test]
    fn a_sheet_line_takes_exactly_the_step_the_click_divides_by() {
        for columns in [46u16, 80, 110] {
            let ctx = context(columns, 40);
            let mut screen = Screen::<Wit>::of(&ctx);
            let took = screen.sheet(0, key::CODEPOINT, Run::datum("U+F0A0"), false);
            assert_eq!(took, State::sheet_step(&ctx), "{columns} columns");
        }
    }

    /// THE GRID GIVES WAY BEFORE THE WINDOW DOES.
    ///
    /// `Grid::fitted` never answers fewer than one row, because a grid of no
    /// rows shows nothing. In a window too short for that one row its box
    /// reaches the footer's line — and there the footer is what disappears,
    /// which is what keeps the two from being drawn on top of each other.
    #[test]
    fn a_window_too_short_for_a_row_of_glyphs_drops_the_footer() {
        let state = in_state("normal");
        for lines in 1..=40u16 {
            let ctx = context(80, lines);
            frame(&state, &ctx)
                .check()
                .unwrap_or_else(|e| panic!("{lines} lines: {e}"));
        }
    }

    /// AND AT EVERY SIZE, IN EVERY STATE, WITH AND WITHOUT A QUERY.
    ///
    /// Three lucky numbers are not an answer, and this is where the two real
    /// defects turned up — both of them in the corner where the window is
    /// narrower than one drawing:
    ///
    ///   - a two-cell magnifier went out asking for its two cells in a window
    ///     of one, and a six-cell `huge` glyph for its six in a window of two.
    ///     A glyph cannot elide itself; what caps it is the BUDGET, and the
    ///     budget was the ink's own width rather than what the window had.
    ///   - the footer's name, the sheet's name and the panel's label all start
    ///     at a cell that a two-column window does not have. `room` there is
    ///     zero — and zero is the protocol's spelling for "to the right edge",
    ///     so each of them went out claiming the whole window from a cell
    ///     outside it. That is the one shape `nothing_overlaps` refuses, and
    ///     `Screen::sheet` was already guarding it two files away.
    ///
    /// Both are [`fits`] now, and both are why this test sweeps instead of
    /// sampling: neither reaches a window anybody uses, and neither was
    /// reachable at all by a check that reads what the component DREW.
    #[test]
    fn no_size_and_no_query_breaks_the_frame() {
        for id in ["normal", "filter", "sheet"] {
            for query in ["", "folder", "xyzzyquux"] {
                let mut state = State::new();
                state.search.push_str(query);
                state.filter_now();
                match id {
                    "filter" => state.toggle_panel(),
                    "sheet" => state.view = View::Sheet { option: 4 },
                    _ => {}
                }
                for columns in 1..=140u16 {
                    for lines in [1u16, 2, 3, 4, 5, 6, 8, 12, 13, 20, 24, 40, 60] {
                        let ctx = context(columns, lines);
                        frame(&state, &ctx).check().unwrap_or_else(|e| {
                            panic!("{id} with {query:?} at {columns}x{lines}: {e}")
                        });
                    }
                }
            }
        }
    }
