/// The glyph database, generated by `ronoctua-glyphgen` and embedded at build time.
///
/// Embedded and not read from a file: the component has no file system, and
/// should not have one. The memory cost is what the `memory_init_cow` trap in
/// `CLAUDE.md` deals with.
const BASE: &str = include_str!(env!("RONOCTUA_GLYPHS_JSON"));

/// How many cells the search needs before the counter is worth showing.
///
/// Twelve: enough to see what was typed. Below that the counter disappears —
/// it is the least important information on the line, and two things fighting
/// over the same narrow line leave neither of them legible.
const MIN_SEARCH: u16 = 12;

/// How many cells separate the glyph's name from its tags.
///
/// Two: enough for the eye to see two blocks and not a single sentence.
const SPACE_BEFORE_TAGS: u16 = 2;

/// Any less room than this and the tags are not emitted.
///
/// Twelve, the same as [`MIN_SEARCH`] and for the same reason: below that
/// you do not show a word, you show an elided stump, which takes up the line
/// to say nothing. In a narrow window the glyph's name is worth more than the
/// beginning of a word that cannot be read.
const MIN_TAGS: u16 = MIN_SEARCH;

/// What separates one tag from the next on the line.
const TAG_SEPARATOR: &str = "  ";

/// How many lines the sheet needs BESIDES the glyph for the larger scale to pay off.
///
/// Six: the ruler, four pieces of information and the help line. Below that
/// the glyph would eat the screen and no sheet would be left under it.
const ROWS_BESIDES_GLYPH: u16 = 6;

/// THE BUFFER'S UNIT OF SPACING: one cell.
///
/// # The reasoning, so that there is no loose number
///
/// **The space between blocks already comes in the line box.** The font box is
/// `1.25 at_cell` (ascender 0.965 + descender 0.285) and the line height is `1.45`,
/// so every span already carries `0.10 at_cell` of air above and `0.10 at_cell` below.
/// Adding an empty cell on top of that is slack over slack — that is what
/// filled the screen with blank lines and took a third of the icons out of view.
///
/// So this constant does **not** separate blocks: they are adjacent, and the
/// air between them is the box's. It measures only the HORIZONTAL gap, where
/// there is no box at all: the Nerd glyphs go from 0 to 600 units in an
/// advance of 600, with no side slack — there the space has to be put in by hand.
const BREATHING: u16 = 1;

/// How many columns a glyph at the icon scale takes.
///
/// A cell is `0.600 × font size` wide, and the icon is drawn at twice the
/// body — so it takes exactly two columns, and the ink takes both of them whole.
const ICON_COLUMNS: u16 = 2;

/// The gap between one icon and the next, horizontally.
///
/// # Why THREE, and not two
///
/// Because the gap has to look the same in every direction, and the cell is
/// taller than it is wide. Vertically the gap is what is left of the box:
/// `1.45 at_cell` of box minus `0.60 at_cell` of ink gives `0.85 at_cell` — at 40 px,
/// **34 px**. Horizontally it is what you put in: each column is worth
/// `0.600 × 20 = 12 px`, so two give 24 px and three give **36 px**.
///
/// Three is what comes close to 34 without overshooting by far. There is no
/// hitting it dead on: the vertical gap is fixed by the box and the horizontal
/// one only steps twelve pixels at a time.
const HORIZONTAL_GAP: u16 = 3;

/// Where the text starts when there is an icon to the left of it.
const AFTER_ICON: u16 = ICON_COLUMNS + BREATHING;

/// How many columns the `Huge` glyph takes.
///
/// A cell is `0.600 × font size` wide, so 116 px of glyph fit in six cells
/// with slack enough for the next column not to touch it.
const GLYPH_WIDTH: u16 = 7;

/// Where the value starts, in the label/value lines of the sheet.
///
/// Aligned, and not "right after the label": that way the eye goes down the
/// column of values without meeting the margin again on every line.
///
/// **Twenty-four because it is what fits the longest label we send**
/// ("Token do design system", 22) with slack. It was 16, and four labels came
/// out cut off in `…` — at any window size, because the cut came from the
/// budget and not from the space.
///
/// The buffer can **not** measure that on its own: it sends a key, and whoever
/// translates is the host (invariant 11). What guarantees that no label
/// overflows is the check `browser-filters`, which compares both languages
/// against this budget — the buffer says how much it reserved, and the test
/// reads the `.ftl`.
const VALUE_COLUMN: u16 = 24;

/// The value column, yielding in a narrow window.
///
/// Without this, a window of thirty columns would spend twenty-four on the
/// label and six on the value. Half for each is the worst acceptable case.
fn value_column(ctx: &Context) -> u16 {
    VALUE_COLUMN.min(ctx.columns / 2)
}

/// Does the filter icon fit in this window?
///
/// In a narrow window it disappears, like the counter. What never yields is
/// the search field: without the counter you can still search, without the
/// icon you can still filter by the command's name — without the field, no.
fn filter_fits(ctx: &Context) -> bool {
    ctx.columns > MIN_SEARCH + FILTER_WIDTH
}

/// Is this column of the search line the filter icon?
///
/// The same function the drawing uses to know whether it emits it — if there
/// were two, one of them changing would be enough for the click to land in the void.
fn in_filter(ctx: &Context, column: u16) -> bool {
    filter_fits(ctx) && column.saturating_add(FILTER_WIDTH) >= ctx.columns
}

/// How many options a panel row has, as a cursor step.
///
/// `isize` because it is added to the selection, and the up arrow goes backwards.
fn panel_row(ctx: &Context, total: usize, selection: usize) -> isize {
    isize::try_from(Panel::new(ctx, total, selection).columns).unwrap_or(1)
}

/// How many cells a set's label reserves in the filter panel.
///
/// Twenty-four, the same as [`VALUE_COLUMN`] and for the same reason: the
/// buffer sends a KEY and never sees the translated sentence (invariant 11),
/// so it declares how much it reserved and the check `browser-filters`
/// compares both languages against this budget. The longest one today is
/// "Símbolos kdl_of energia IEC", with 23.
const LABEL_WIDTH: u16 = 24;

/// What separates one column of options from the next.
const SPACE_BETWEEN_OPTIONS: u16 = 2;

/// Where the first column of options starts.
///
/// Two cells: the options line up with the TEXT of the search, not with the
/// magnifier. They hang from the field, and that is what says they belong to it.
const PANEL_INDENT: u16 = 2;

/// How much the filter icon takes of the search line: it and the gap before it.
///
/// The click area is the same — the gap beside the icon has no other owner,
/// and a target with slack is a target you do not miss.
const FILTER_WIDTH: u16 = AFTER_ICON;

/// The prefix of the text keys of the source sets.
const SET_PREFIX: &str = "glyphs-set-";

/// The option that removes the set filter.
///
/// It is not the prefix of any set — it is the "no filter", and that is why it
/// has its own key instead of coming from the database.
const SET_ALL: &str = "all";

/// The prefix of the command text keys, the same one the registry uses.
///
/// It is here as a literal because the buffer does **not** depend on the
/// host's crate (invariant 11) — and the check `browser-filters` is what stops
/// the two from diverging.
const KEY_PREFIX: &str = "cmd-";

/// The text keys of the sheet.
///
/// Constants, and not literals scattered around: invariant 8 requires every UI
/// text to be a key, and a key written by hand in two places is the easiest
/// way for one of them to fall behind.
mod key {
    pub const CODEPOINT: &str = "glyphs-sheet-codepoint";
    pub const DECIMAL_N: &str = "glyphs-sheet-decimal";
    pub const BLOCK: &str = "glyphs-sheet-block";
    pub const SET: &str = "glyphs-sheet-set";
    pub const TOKEN: &str = "glyphs-sheet-token";
    pub const TRAY: &str = "glyphs-sheet-tray";
    pub const TAGS_PT: &str = "glyphs-sheet-tags-pt";
    pub const TAGS_EN: &str = "glyphs-sheet-tags-en";
    pub const HELP: &str = "glyphs-sheet-help";
    pub const COPIED: &str = "glyphs-sheet-copied";
    pub const FAILED: &str = "glyphs-sheet-copy-failed";
}

/// The words of a query. Empty gives back empty.
fn search_words(q: &str) -> Vec<&str> {
    // Splits on space AND on ASCII punctuation, the same boundary
    // `word_prefix` uses on the text: without that, `seti-ui` would be a
    // single token and would not match the tag `seti-ui`, which the text splits
    // in two.
    //
    // ASCII punctuation, and not "everything that is not alphanumeric": a pasted
    // character (`\u{2190}`) is not alphanumeric, and splitting on it would leave
    // the query EMPTY — the gesture of pasting a character to find out which one
    // it is would show the whole database.
    q.split(|c: char| c.is_whitespace() || c.is_ascii_punctuation())
        .filter(|p| !p.is_empty())
        .collect()
}

/// Is `t` a prefix of some WORD of `text`?
///
/// The same rule as the symbols browser, and for the same reason: a loose
/// substring matches in the middle of a word (`pe·seta·`) and still scores
/// better than the tag, so the Portuguese search lost to a coincidence in
/// English. A prefix — and not a whole word — because the search is incremental.
fn word_prefix(text: &str, t: &str) -> bool {
    text.split(|c: char| !c.is_alphanumeric())
        .any(|p| p.starts_with(t))
}

/// A label-and-value line of the sheet.
///
/// `target` marks the selected copy option — by COLOR, never by box or outline
/// (invariant 15), which is the same thing the grid does with focus.
fn pair(ctx: &Context, line: u16, label: &str, value: Text, target: bool) -> Vec<Command> {
    let column = value_column(ctx);
    let mut out = vec![Command::Text(TextCommand {
        line,
        column: 0,
        content: Text::Key(label.to_owned()),
        color: if target {
            Color::StateAccent
        } else {
            Color::TextDim
        },
        scale: Scale::Small,
        // UP TO THE VALUE COLUMN, and not one cell beyond: whoever elides is the
        // host, and without a budget a long translated label would write over the
        // value. The length changes with the language — this buffer does not know it.
        max_width: column.saturating_sub(1),
    })];
    if ctx.columns > column {
        out.push(Command::Text(TextCommand {
            line,
            column,
            content: value,
            color: if target {
                Color::StateAccent
            } else {
                Color::TextSecondary
            },
            scale: Scale::Normal,
            max_width: ctx.columns.saturating_sub(column),
        }));
    }
    out
}

/// Which of the buffer's two screens is in use.
///
/// # Why a VIEW, and not a second buffer
///
/// The sheet replaces the content of the SAME buffer, as the owner asked — and
/// as invariant 14 requires: there is no new window, there is no popup. And
/// also because going back is cheap: the listing state (search, cursor, top)
/// is not touched, so `Esc` gives the screen back exactly as it was.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Screen {
    /// The glyph grid.
    Grid,
    /// The sheet of the focused glyph, with the selected copy option.
    Sheet { option: usize },
}

/// The geometry of the filter panel — where each option is drawn.
///
/// # Why a struct, and not two similar sums
///
/// Because the drawing and the click have to match BY CONSTRUCTION. They have
/// already diverged in this file (the list of information on the sheet), and
/// the symptom was the click hitting one item and the screen showing another.
/// [`Panel::cell`] and [`Panel::at_cell`] are the same arithmetic both ways.
struct Panel {
    /// How many options fit side by side.
    columns: u16,
    /// How many cells a column of options takes.
    step: u16,
    /// How many lines the panel takes on the screen.
    lines: u16,
    /// The first option drawn. The panel PAGINATES when it does not fit.
    first: usize,
    /// How many options there are in all.
    total: usize,
}

impl Panel {
    /// The geometry for this context, with the selection where it is.
    ///
    /// # Why it PAGINATES instead of growing
    ///
    /// Because the panel shares the screen with the grid, and the grid is the
    /// buffer. In a narrow window the options become a single column and fifteen
    /// rows — more than the whole grid. The ceiling is half the content, and what
    /// does not fit comes in through the selection's page: the arithmetic comes
    /// from where the cursor is, and **not** from a stored field, otherwise there
    /// would be two states saying the same thing and one of them would fall behind.
    fn new(ctx: &Context, total: usize, selection: usize) -> Self {
        let step = LABEL_WIDTH + SPACE_BETWEEN_OPTIONS;
        let columns = (ctx.columns.saturating_sub(PANEL_INDENT) / step).max(1);
        let per_row = usize::from(columns);
        // THE CEILING: half of what is left after the search, the ruler and the name
        // line. Never zero — a panel of zero rows is an open panel that does not
        // show up, which is worse than a closed one.
        let ceiling = (usize::from(ctx.lines).saturating_sub(3) / 2).max(1);
        let lines = total.div_ceil(per_row).min(ceiling).max(1);
        let page = (selection / per_row) / lines;
        Self {
            columns,
            step,
            lines: u16::try_from(lines).unwrap_or(u16::MAX),
            first: page * lines * per_row,
            total,
        }
    }

    /// Where option `n` is drawn: `(row inside the panel, column)`.
    ///
    /// `None` when it is on another page.
    fn cell(&self, n: usize) -> Option<(u16, u16)> {
        let inside = n.checked_sub(self.first)?;
        let per_row = usize::from(self.columns);
        let line = u16::try_from(inside / per_row).ok()?;
        if line >= self.lines {
            return None;
        }
        let column = u16::try_from(inside % per_row).ok()? * self.step + PANEL_INDENT;
        Some((line, column))
    }

    /// Which option is on the clicked cell, if any.
    fn at_cell(&self, line: u16, column: u16) -> Option<usize> {
        if line >= self.lines {
            return None;
        }
        // `saturating_sub` on the indent: clicking on the left gutter lands on the
        // first option of the row. It has no other owner, and a target that ignores
        // two pixels of margin is a target you miss.
        let c = column.saturating_sub(PANEL_INDENT) / self.step;
        if c >= self.columns {
            return None;
        }
        let n = self.first + usize::from(line) * usize::from(self.columns) + usize::from(c);
        (n < self.total).then_some(n)
    }
}

/// A glyph, with only what the browser uses.
struct Glyph {
    ch: char,
    name: String,
    /// The OTHER names of the same codepoint, when there are any.
    ///
    /// A codepoint can have several names in `glyphnames.json` (aliases). The grid
    /// shows only the first one — on the sheet they fit, and they are the answer
    /// to "I could have sworn this icon was called something else".
    aliases: Vec<String>,
    set_of: String,
    /// Tags in Portuguese — ACCENTED, which is how they appear on screen.
    tags_pt: Vec<String>,
    /// Tags in English.
    tags_en: Vec<String>,
    /// The forms of the pt tags WITHOUT accents, only the ones that differ.
    ///
    /// They do not go to the screen: they exist so that `localizacao` finds what
    /// is written `localização`. What computes them is the GENERATOR — normalizing
    /// here would cost walking 10,473 glyphs on every keystroke.
    search: Vec<String>,
    /// The icon token that uses this glyph, if any. It comes computed from the
    /// database (`gen-glyphdb.py`), because what knows that is the table of
    /// section 6.3 — and the component does not read files to find out on its own.
    token: Option<String>,
    /// Is this glyph assigned to some app id in the tray?
    in_tray: bool,
}

