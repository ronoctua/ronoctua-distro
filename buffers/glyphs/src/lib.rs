/// Paints the copy's verdict, which is the one thing on this screen that has no
/// ROLE.
///
/// # A gap, written down instead of worked around
///
/// `ronoctua_design::Role` is seven parts wide — title, body, quiet, dim,
/// accent, rule and band — and a VERDICT is none of them: "it copied" is
/// `state-success` and "it failed" is `state-error`, two tokens the palette
/// resolves for nobody. So the line itself is a `Run` like every other one on
/// the sheet, at the same row, the same cell and the same budget as the help
/// text it replaces — `Screen::check()` measures it exactly as it measures
/// that — and what happens here, after the frame is built, is only the colour,
/// on the one command whose key it is.
///
/// The day the crate grows a role for a verdict, this function and its call
/// site are what disappear.
fn tint(frame: &mut [Command], notice: Option<bool>) {
    let Some(ok) = notice else {
        return;
    };
    let key = if ok { key::COPIED } else { key::FAILED };
    let color = if ok {
        Color::StateSuccess
    } else {
        Color::StateError
    };
    for c in frame.iter_mut() {
        if let Command::Text(t) = c
            && let Text::Key(k) = &t.content
            && k == key
        {
            t.color = color;
        }
    }
}

impl Guest for Component {
    fn render(ctx: Context) -> Vec<Command> {
        with_state(|e| {
            // Saved for the `event`, which receives no context at all.
            e.ctx = ctx;

            let mut screen = Screen::<Wit>::of(&ctx);
            match e.view {
                // THE SHEET REPLACES THE WHOLE CONTENT. There is no search, no
                // grid, no counter — the screen is about ONE glyph. See [`View`].
                View::Sheet { option } => e.draw_sheet(&mut screen, &ctx, option),
                View::Grid => e.draw_grid(&mut screen, &ctx),
            }
            let mut frame = screen.finish_wit();
            tint(&mut frame, e.notice);
            frame
        })
    }

    fn init() -> Descriptor {
        let mut keymap = vec![
            // Assign the focused glyph to an app id — section 4.2 calls this
            // "the real answer to *easily*".
            Binding {
                keys: ", a".into(),
                command: "glyphs-assign".into(),
            },
        ];
        keymap.extend(FORMATS.iter().map(|(id, key)| Binding {
            // EVERYTHING under `SPC m`: the host rejects at load whoever leaves it.
            keys: format!(", c {key}"),
            command: (*id).to_owned(),
        }));
        keymap.extend(FILTERS.iter().map(|(id, key)| Binding {
            keys: format!(", f {key}"),
            command: (*id).to_owned(),
        }));

        let mut commands: Vec<String> = FORMATS
            .iter()
            .chain(FILTERS.iter())
            .map(|(id, _)| (*id).to_owned())
            .collect();
        commands.push("glyphs-assign".into());

        Descriptor {
            name: "glyphs".into(),
            mode: "glyphs".into(),
            // THREE STATES, and all three already existed — the grid, the
            // filter panel and the focused item's sheet. What they did not have
            // was a name, so the modeline said the same word with any of the
            // three on screen.
            states: vec![
                BufferState {
                    id: "normal".into(),
                    letter: 'n',
                    tone: Tone::Standard,
                },
                BufferState {
                    id: "filter".into(),
                    letter: 'f',
                    tone: Tone::Standard,
                },
                BufferState {
                    id: "sheet".into(),
                    letter: 's',
                    tone: Tone::Standard,
                },
            ],
            keymap,
            commands,
            segments: vec![],
            // Neither PTY nor pixels: the browser draws with glyph and text.
            capabilities: vec![],
            // The words this buffer writes into the search field — see
            // `Phrase`, and the symbol browser's `PREFIX_KEYS` for the whole
            // reasoning.
            phrases: PREFIX_KEYS
                .iter()
                .map(|(k, _, _)| (*k).to_owned())
                // AND THE READER'S LANGUAGE, which is not a phrase and is not
                // drawn: it says which of the tag lists this buffer is already
                // holding belongs to whoever is looking. See `Phrases::LANGUAGE`.
                .chain(core::iter::once(Phrases::LANGUAGE.to_owned()))
                .collect(),
        }
    }

    fn event(input: Input) -> Vec<Effect> {
        // THE STATE IS REPORTED FROM ONE PLACE. `screen` and `panel` are
        // assigned from a dozen sites between the sheet, the panel and the
        // grid; a report per site is a report somebody forgets, and the cost is
        // a modeline that says `normal` with a sheet on screen.
        with_state(|e| {
            let before = e.state_id();
            let mut out = e.act(input);
            let after = e.state_id();
            if before != after {
                out.push(Effect::StateChanged(after.into()));
            }
            out
        })
    }
}

impl State {
    /// Which of the declared states this is, right now.
    ///
    /// DERIVED and never stored: `screen` and `panel` already answer it, and a
    /// stored copy is a second truth that drifts on the first path that forgets
    /// to update it. The order is the precedence — a sheet is open ON TOP of
    /// whatever the grid was showing.
    fn state_id(&self) -> &'static str {
        if matches!(self.view, View::Sheet { .. }) {
            "sheet"
        } else if self.panel.is_some() {
            "filter"
        } else {
            "normal"
        }
    }

    /// One input, before the state is compared.
    fn act(&mut self, input: Input) -> Vec<Effect> {
        let e = self;
        {
            // The context is the one from the last `render` — see the `ctx` field.

            // THE HOST SENDS AN ID THIS BUFFER DECLARED, and anything else is a
            // bug on the other side — ignored rather than guessed at.
            //
            // `sheet` REFUSES when there is nothing under the cursor, the same
            // guard `Confirm` uses: a sheet of nothing is a screen of empty
            // fields that `Esc` is the only way out of.
            if let Input::EnterState(id) = &input {
                match id.as_str() {
                    "sheet" => {
                        if e.chosen().is_none() {
                            return vec![];
                        }
                        e.view = View::Sheet { option: 0 };
                    }
                    "filter" => {
                        e.view = View::Grid;
                        if e.panel.is_none() {
                            e.toggle_panel();
                        }
                    }
                    _ => {
                        e.view = View::Grid;
                        e.panel = None;
                    }
                }
                return vec![Effect::Redraw];
            }
            let ctx = e.ctx;

            // THE SHEET HAS THE WHOLE KEYBOARD while it is open.
            //
            // There is no search there, so a letter does not filter; and the arrows
            // change meaning: up/down step through the copy options, left and right
            // switch GLYPHS. Letting the keys fall into the grid's handling would
            // make the sheet show one glyph while the cursor was on another — the
            // class of defect this project has been undoing.
            if let View::Sheet { option } = e.view {
                return e.sheet_key(&ctx, option, &input);
            }

            // THE OPEN PANEL KEEPS THE ARROWS, the Enter and the Esc.
            //
            // Only those three: the search field is still right above and is still
            // what one types into, so letter, delete and paste go on to it. A panel
            // that swallowed the whole keyboard would force closing it to type —
            // and it exists precisely to be used TOGETHER with the search (`md:`
            // plus the term).
            if let Some(sel) = e.panel
                && let Some(effects) = e.panel_key(&ctx, sel, &input)
            {
                return effects;
            }

            match input {
                Input::Character(c) => {
                    e.search.push(c);
                    e.filter_now();
                    vec![Effect::Redraw]
                }
                // PASTE GOES INTO THE SEARCH, as if it had been typed.
                //
                // The text arrives already resolved from the host: the buffer does
                // not read the clipboard (invariant 11). A line break becomes a
                // space — pasting a whole paragraph into the search is a mistake,
                // and a raw `\n` would become a character that matches nothing.
                Input::Paste(t) => {
                    if t.is_empty() {
                        return vec![];
                    }
                    e.search.push_str(&t.replace(['\n', '\r'], " "));
                    e.filter_now();
                    vec![Effect::Redraw]
                }
                // On the GRID there is nothing to copy with Enter, so this verdict
                // only arrives if a copy command has been dispatched. There is
                // nowhere to show it here — the footer line belongs to the glyph's
                // name —, and inventing a place would be new chrome.
                Input::Copied(_) => vec![],
                Input::Delete => {
                    if e.search.pop().is_none() {
                        return vec![];
                    }
                    e.filter_now();
                    vec![Effect::Redraw]
                }
                // The `Tab` OPENS AND CLOSES THE FILTERS.
                //
                // The cheapest key on the screen for the panel: the finger is already
                // on the keyboard, the search field is still below it, and there is no
                // need to let go of the mouse nor to remember the command's name.
                //
                // It does not fight with the field: the panel writes INTO the search
                // (`md:`) and the search stays editable — toggling does not lose what
                // was typed.
                Input::Toggle => {
                    e.toggle_panel();
                    vec![Effect::Redraw]
                }
                // On a GRID, up and down step a whole ROW. Stepping one glyph would
                // make the down arrow move sideways, which is the opposite of what
                // the drawing on the screen promises.
                Input::Down => e.move_by(&ctx, grid_row(&ctx, e)),
                Input::Up => e.move_by(&ctx, -grid_row(&ctx, e)),
                Input::Right => e.move_by(&ctx, 1),
                Input::Left => e.move_by(&ctx, -1),
                // A command dispatched by the host. The component does NOT write
                // files nor touch the clipboard — see the top of the module: it
                // ASKS, and the host does it.
                Input::Command(id) => {
                    // The filter first: `glyphs-filter-clear` and `tag:` do not
                    // depend on a focused glyph, and with an empty list (which is
                    // exactly when one wants to clear) there is none.
                    if id.starts_with("glyphs-filter-") {
                        return match e.apply_filter(&id) {
                            Some(()) => vec![Effect::Redraw],
                            None => vec![],
                        };
                    }
                    let Some(g) = e.chosen() else {
                        return vec![];
                    };
                    if id == "glyphs-assign" {
                        // The host knows which app id is focused; the buffer only
                        // says which glyph, and by which command.
                        return vec![Effect::Copy(g.ch.to_string()), Effect::Command(id)];
                    }
                    match format_as(&id, g) {
                        Some(s) => vec![Effect::Copy(s)],
                        None => vec![],
                    }
                }
                // CLICKING SELECTS; IT DOES NOT COPY.
                //
                // Here the list is DATA to be navigated, and not a menu of actions:
                // clicking a glyph is the same as stepping to it with the arrow, and
                // the `Enter` is still the one that copies. Copying on click would
                // swap the clipboard on every glyph looked at, which is losing work
                // by moving the mouse.
                //
                // (In the footer's shortcut list the click DOES RUN — but there
                // each row is an action, and clicking it is pressing its key.
                // Different things, different behaviors.)
                Input::Click(p) => {
                    // THE FILTER ICON OPENS AND CLOSES THE PANEL. It is the only
                    // target of the header — clicking on the rest of it must not
                    // touch the grid's cursor.
                    //
                    // THE WHOLE HEADER, and not line zero: it has the height of
                    // the icon, and the icon is drawn along it. Accepting only
                    // the first cell would make half of the drawing not respond
                    // to the click.
                    if p.line < State::glyph_cells(&ctx) {
                        if in_filter(&ctx, p.column) {
                            e.toggle_panel();
                            return vec![Effect::Redraw];
                        }
                        return vec![];
                    }
                    // ON THE PANEL THE CLICK RUNS, and does not select: there each
                    // row IS an action, and clicking it is pressing its key. (On the
                    // grid, right below, it is the opposite — see the next
                    // paragraph.)
                    if let Some(sel) = e.panel {
                        let panel = Panel::new(&ctx, e.options(), sel);
                        // THE PANEL'S ROWS ARE THE BUFFER'S. `Grid` places
                        // in absolute lines, so the click needs no subtraction
                        // — and the subtraction was the second place the
                        // panel's first row was written down.
                        if let Some(n) = panel.at_cell(p.line, p.column) {
                            e.panel = None;
                            e.apply_set(n);
                            return vec![Effect::Redraw];
                        }
                    }
                    match e.glyph_at(&ctx, p.column, p.line) {
                        Some(i) if i != e.cursor => {
                            e.cursor = i;
                            vec![Effect::Redraw]
                        }
                        // A click outside the grid, or on the glyph that is already
                        // focused: nothing changed, and asking for a redraw would spend
                        // a frame painting exactly the same screen.
                        _ => vec![],
                    }
                }
                // ENTER OPENS THE SHEET, and no longer copies the glyph directly.
                //
                // Copying still exists — it is the first option of the sheet, and
                // also the command `glyphs-copy-glyph`. What is gained is the
                // rest: codepoint, aliases, tags, and the other eight formats,
                // which until now had no way of being reached (the buffer's local
                // keymap is not dispatched — see docs/PENDING.md).
                Input::Confirm => {
                    if e.chosen().is_none() {
                        return vec![];
                    }
                    e.view = View::Sheet { option: 0 };
                    vec![Effect::Redraw]
                }
                // `Esc` DOES NOT KILL THE BUFFER.
                //
                // It cancels what is under way — the search — and stops there. It is
                // what Esc does in Doom: it undoes the transient state, it never
                // destroys the buffer. Closing is a NAMED command (`SPC w d`),
                // because destroying work has to be deliberate and cannot depend on
                // a key one presses by reflex on leaving anything at all.
                //
                // With the search already empty it does nothing — and it does not
                // ask for a redraw, otherwise holding `Esc` would spend a frame per
                // repeat without changing a pixel.
                Input::Cancel => {
                    if e.search.is_empty() {
                        return vec![];
                    }
                    e.search.clear();
                    e.filter_now();
                    vec![Effect::Redraw]
                }
                // NOT OURS — see the identical arm in `buffers/unicode`: the
                // survey only reaches whoever declared `capability::system`,
                // and the arm is explicit so the next case cannot arrive mute.
                // Not this buffer's: it declared no capability, so neither
                // ever arrives — the arm exists because the match is exhaustive.
                // WHAT THIS BUFFER DECLARED NO CAPABILITY FOR. It is never
                // sent any of them — the host raises no thread and no clock for
                // a buffer that did not ask — and the arm exists because the
                // `match` is exhaustive and the WIT is a contract shared by
                // six components: an `input` case added for one of them has to
                // be answered by all, and "answered" here is "ignored".
                Input::Phrases(said) => {
                    e.phrases = Phrases::of(said.into_iter().map(|p| (p.key, p.text)).collect());
                    e.filter_now();
                    vec![Effect::Redraw]
                }
                // THE WHEEL AND THE BAR MOVE THE GRID, by whole rows, and leave the
                // cursor where it is — the window moves, not the choice.
                Input::Wheel(w) => {
                    let grid = e.grid(&e.ctx);
                    e.top = grid.wheeled(e.top, i64::from(w.lines), e.result.len());
                    vec![Effect::Redraw]
                }
                Input::Scrolled(d) => {
                    let grid = e.grid(&e.ctx);
                    e.top = grid.top_at_row(d.first as usize, e.result.len());
                    vec![Effect::Redraw]
                }
                Input::Survey(_)
                | Input::Queue(_)
                | Input::Rack(_)
                | Input::Mind(_)
                | Input::Log(_)
                | Input::Hover { .. }
                | Input::Unhover(_)
                | Input::KeyboardSeat(_)
                | Input::KeyboardLeft(_)
                | Input::Keyboards(_)
                | Input::Formatted(_)
                | Input::EnterState(_) => {
                    vec![]
                }
            }
        }
    }
}

