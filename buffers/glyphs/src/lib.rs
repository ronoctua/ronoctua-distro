//! The glyph browser — section 6.5, milestone 7.
//!
//! Searches the 10,473 glyphs by name, set and tag (en and pt), with the
//! active locale weighing more. Once a glyph is chosen, the assignment
//! command writes layer 2 of `assets/icons/tray-glyphs.nix` — the user
//! override, read at runtime with hot reload. **Node rebuild**: if customizing
//! required a `nixos-rebuild`, the "easy" requirement of section 4.2 would
//! not be met.
//!
//! # What this component does NOT do
//!
//! It does not read files, does not write files, does not rasterize, does not
//! translate. The glyph database arrives EMBEDDED (`include_str!` at build
//! time), the list goes out as a `DisplayList`, and writing the override is a
//! command the HOST runs — the component only says which glyph was chosen.
//!
//! That is invariant 11, and it is not discipline: the WIT `world` offers
//! neither a file system nor i18n.
//!
//! # Why the list is virtualized
//!
//! Section 9.5 of the plan settled on two atlases so that the browser would
//! not touch the guarantee of 5.2. That only holds if it rasterizes **only
//! the visible rows**: that is why [`State::visible`] slices before
//! emitting, and the `DisplayList` never has 10,473 commands.
//!
//! # And it no longer decides its own geometry
//!
//! Three browsers drew the same grid — this one, the symbol one and the Lucide
//! one — from three copies of `grid_columns`, `height`, `panel_first_row`,
//! `rule_row`, `grid_first_row`, `footer_row` and `row_step`, each with its own
//! constants: two icon columns here against four there, a horizontal gap of
//! three against four, a label column of twenty-four against twenty. Three
//! answers to one question is the same thing as no design system, which is what
//! the owner reported from a photograph of the screen.
//!
//! So the arithmetic left: [`Grid`] is the grid, `Screen::sheet` is the
//! label-and-value sheet, and [`SHEET_LABEL`] is the one label column. What
//! stays here is what is genuinely this browser's — what a query means, what a
//! filter selects, and which of the two screens is on. `wit_bindgen::generate!`
//! left with it, and so did the crate-wide `#![allow(unsafe_code,
//! missing_docs)]` that generating bindings used to owe.

