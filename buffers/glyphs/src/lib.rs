/// The glyph database, generated by `ronoctua-glyphgen` and embedded at build time.
///
/// Embedded and not read from a file: the component has no file system, and
/// should not have one. The memory cost is what the `memory_init_cow` trap in
/// `AGENTS.md` deals with.
const BASE: &str = include_str!(env!("RONOCTUA_GLYPHS_JSON"));

/// The SUBTAGS whose tags the database carries, in the order it wrote them.
///
/// Generated from `assets/i18n/languages.nix` and handed in as a variable, the
/// same way the database itself is: the buffer cannot read a file and must not
/// carry a list of languages written by hand. The FIRST is the source, English,
/// which is where the words come from.
///
/// This is not the buffer knowing a language (invariant 11). It is the buffer
/// knowing how many tag lists it is holding and what to call the field each one
/// came out of — the words themselves it neither writes nor translates.
const TAG_LANGUAGES: &str = env!("RONOCTUA_TAG_LANGUAGES");

/// The tag lists to show, the reader's FIRST.
///
/// The order is what makes the elision cut somebody else's language before the
/// reader's on a narrow screen, and it is the whole of what the seeded language
/// buys: no word here is chosen, only the order they come in.
fn ordered(mine: usize, how_many: usize) -> impl Iterator<Item = usize> {
    core::iter::once(mine).chain((0..how_many).filter(move |i| *i != mine))
}

/// The subtags of [`TAG_LANGUAGES`], in order.
fn tag_languages() -> impl Iterator<Item = &'static str> {
    TAG_LANGUAGES.split(',').filter(|s| !s.is_empty())
}

/// How many cells the search needs before the counter is worth showing.
///
/// Twelve: enough to see what was typed. Below that the counter disappears —
/// it is the least important information on the line, and two things fighting
/// over the same narrow line leave neither of them legible.
const MIN_SEARCH: u16 = 12;

/// The two words this buffer WRITES, and the names each answers to.
///
/// `(key, english, portuguese)` — the symbol browser's `PREFIX_KEYS` carries
/// the whole reasoning. `token:` and `app:` are not here: they have no twin in
/// the lexicon, and where a single language fits invariant 18 says which.
const PREFIX_KEYS: [(&str, &str, &str); 2] = [
    (key::PREFIX_BLOCK, "block", "bloco"),
    (key::PREFIX_TAG, "tag", "etiqueta"),
];

/// The word this buffer writes for one prefix, in the person's language.
fn word(phrases: &Phrases, key: &str) -> String {
    let english = PREFIX_KEYS
        .iter()
        .find(|(k, _, _)| *k == key)
        .map_or("", |(_, en, _)| *en);
    phrases.or(key, english)
}

/// The CANONICAL name of a typed prefix, whichever language it came in.
///
/// A word that is no prefix of ours comes back unchanged, and the arm below
/// turns it into a SET name — which is what keeps `fa:` and `md:` working
/// without this file learning every set the Nerd Fonts ship.
fn canonical_prefix(typed: &str, phrases: &Phrases) -> String {
    for (k, english, portuguese) in PREFIX_KEYS {
        if typed == english || typed == portuguese || typed == word(phrases, k) {
            return english.to_owned();
        }
    }
    typed.to_owned()
}

/// How many cells separate the glyph's name from its tags.
///
/// TWO GAPS, and not one. [`GAP`] is what separates two columns of the same
/// block — and the name and the tags are two BLOCKS sharing a line: enough for
/// the eye to see two things and not a single sentence. Doubling the one number
/// the design crate owns is what keeps this from becoming a number of its own.
const SPACE_BEFORE_TAGS: u16 = GAP * 2;

/// Any less room than this and the tags are not emitted.
///
/// Twelve, the same as [`MIN_SEARCH`] and for the same reason: below that
/// you do not show a word, you show an elided stump, which takes up the line
/// to say nothing. In a narrow window the glyph's name is worth more than the
/// beginning of a word that cannot be read.
const MIN_TAGS: u16 = MIN_SEARCH;

/// What separates one tag from the next on the line.
const TAG_SEPARATOR: &str = "  ";

/// How many lines the sheet needs BESIDES the glyph for the larger scale to pay off.
///
/// Six: the rule, four pieces of information and the help line. Below that
/// the glyph would eat the screen and no sheet would be left under it.
const ROWS_BESIDES_GLYPH: u16 = 6;

/// Where the text starts when there is an icon to the left of it.
///
/// The icon's own width plus [`GAP`], and the icon's width is the GRID's:
/// every glyph this buffer shows as an icon — the magnifier, the filter, the
/// focused one in the footer — is drawn at the grid's scale, and the scale
/// widens as much as it raises. A constant here would be assuming a theme.
///
/// (`ronoctua_design::ICON` is the width of an icon at the DEFAULT scale, and
/// it is what `Run::glyph` reserves on its own. Every icon on this screen
/// restates its width for that reason.)
fn after_icon(ctx: &Context) -> u16 {
    State::glyph_cells(ctx).saturating_add(GAP)
}

/// How much the filter icon takes of the search line: it and the gap before it.
///
/// The click area is the same — the gap beside the icon has no other owner,
/// and a target with slack is a target you do not miss.
fn filter_width(ctx: &Context) -> u16 {
    after_icon(ctx)
}

/// Does the filter icon fit in this window?
///
/// In a narrow window it disappears, like the counter. What never yields is
/// the search field: without the counter you can still search, without the
/// icon you can still filter by the command's name — without the field, no.
fn filter_fits(ctx: &Context) -> bool {
    ctx.columns > MIN_SEARCH + filter_width(ctx)
}

/// Is this column of the search line the filter icon?
///
/// The same function the drawing uses to know whether it emits it — if there
/// were two, one of them changing would be enough for the click to land in the void.
fn in_filter(ctx: &Context, column: u16) -> bool {
    filter_fits(ctx) && column.saturating_add(filter_width(ctx)) >= ctx.columns
}

/// The budget a run at `column` may declare — or `None` when it has no room.
///
/// # The zero that means the opposite of zero
///
/// `ronoctua_design::budget` caps what was asked for by what is LEFT, which is
/// what stops a run from reaching past the right edge. What it answers when
/// nothing is left is `0`, and `0` is the protocol's own spelling for "to the
/// right edge" — so a run that starts past the edge and then claims all of it
/// is exactly the shape `nothing_overlaps` refuses. `Screen::sheet` guards it
/// by drawing nothing at all, and this is the same guard for the runs this
/// buffer places itself: the footer's name at cell three in a window of two,
/// the panel's label, the sheet's.
///
/// The other half is the glyphs: a two-cell icon in a one-cell window used to
/// go out asking for its two cells. Capped, it asks for the one there is and
/// the host elides it — which is what the budget is for.
fn fits(columns: u16, column: u16, wanted: u16) -> Option<u16> {
    (room(columns, column) > 0).then(|| budget(columns, column, wanted))
}

/// How many glyphs a grid row has, as a cursor step.
///
/// `isize` because it is added to the cursor, and the up arrow goes backwards.
/// `try_from` and not `from`: `isize` is only guaranteed to be as wide as a
/// pointer, so the standard library refuses a `u16` conversion that would be
/// lossless on every target this actually compiles for.
fn grid_row(ctx: &Context, state: &State) -> isize {
    isize::try_from(state.grid(ctx).across).unwrap_or(1)
}

/// How many options a panel row has, as a cursor step.
///
/// `isize` because it is added to the selection, and the up arrow goes backwards.
fn panel_row(ctx: &Context, total: usize, selection: usize) -> isize {
    isize::try_from(Panel::new(ctx, total, selection).across()).unwrap_or(1)
}

