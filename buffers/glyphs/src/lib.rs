/// The words of a query. Empty gives back empty.
fn search_words(q: &str) -> Vec<&str> {
    // Splits on space AND on ASCII punctuation, the same boundary
    // `word_prefix` uses on the text: without that, `seti-ui` would be a
    // single token and would not match the tag `seti-ui`, which the text splits
    // in two.
    //
    // ASCII punctuation, and not "everything that is not alphanumeric": a pasted
    // character (`\u{2190}`) is not alphanumeric, and splitting on it would leave
    // the query EMPTY — the gesture of pasting a character to find out which one
    // it is would show the whole database.
    q.split(|c: char| c.is_whitespace() || c.is_ascii_punctuation())
        .filter(|p| !p.is_empty())
        .collect()
}

/// Is `t` a prefix of some WORD of `text`?
///
/// The same rule as the symbols browser, and for the same reason: a loose
/// substring matches in the middle of a word (`pe·seta·`) and still scores
/// better than the tag, so the Portuguese search lost to a coincidence in
/// English. A prefix — and not a whole word — because the search is incremental.
fn word_prefix(text: &str, t: &str) -> bool {
    text.split(|c: char| !c.is_alphanumeric())
        .any(|p| p.starts_with(t))
}

/// Which of the buffer's two screens is in use.
///
/// # Why a VIEW, and not a second buffer
///
/// The sheet replaces the content of the SAME buffer, as the owner asked — and
/// as invariant 14 requires: there is no new window, there is no popup. And
/// also because going back is cheap: the listing state (search, cursor, top)
/// is not touched, so `Esc` gives the screen back exactly as it was.
///
/// (`View`, and not `Screen`: [`Screen`] is now the design crate's frame
/// builder, and two types of one name in one file is how a reader stops
/// knowing which is which.)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum View {
    /// The glyph grid.
    Grid,
    /// The sheet of the focused glyph, with the selected copy option.
    Sheet { option: usize },
}

/// The geometry of the filter panel — where each option is drawn.
///
/// # Why a struct, and not two similar sums
///
/// Because the drawing and the click have to match BY CONSTRUCTION. They have
/// already diverged in this file (the list of information on the sheet), and
/// the symptom was the click hitting one item and the screen showing another.
/// [`Panel::cell`] and [`Panel::at_cell`] are the same arithmetic both ways —
/// and now they are the same arithmetic as the GRID's, because both are a
/// [`Grid`]: a panel is a grid of labels the way the browser is a grid of
/// glyphs, and the two used to say so in two copies of the same sum.
struct Panel {
    /// Where the options go, and where a click finds one again.
    grid: Grid,
    /// How far in from the left edge the first column of options sits.
    ///
    /// It is kept because [`Grid`] counts from cell zero: the indent goes on in
    /// [`Panel::cell`] and comes off again in [`Panel::at_cell`], and holding it
    /// here is what stops those two from taking it from two places.
    indent: u16,
    /// The first option drawn. The panel PAGINATES when it does not fit.
    first: usize,
    /// How many options there are in all.
    total: usize,
}

impl Panel {
    /// The geometry for this context, with the selection where it is.
    ///
    /// # Why it PAGINATES instead of growing
    ///
    /// Because the panel shares the screen with the grid, and the grid is the
    /// buffer. In a narrow window the options become a single column and fifteen
    /// rows — more than the whole grid. The ceiling is half the content, and what
    /// does not fit comes in through the selection's page: the arithmetic comes
    /// from where the cursor is, and **not** from a stored field, otherwise there
    /// would be two states saying the same thing and one of them would fall behind.
    ///
    /// # Why the grid is built twice
    ///
    /// Because [`Grid::fitted`] answers "how many rows FIT between these two
    /// lines", and what the panel draws is "how many rows the options ASK for",
    /// which is the smaller of the two. The first grid is read for its width
    /// only; the second is the one that is kept, and it is as tall as the
    /// options need. Both are integer arithmetic over five numbers.
    fn new(ctx: &Context, total: usize, selection: usize) -> Self {
        let first_row = State::panel_first_row(ctx);
        // THE CEILING: half of what is left after the search, the rule and the
        // name line. Never zero — a panel of zero rows is an open panel that
        // does not show up, which is worse than a closed one.
        //
        // COUNTED, and not the literal 3 it used to be. The search line is as
        // tall as the glyph it carries and so is the name line, which is two
        // cells each and not one; the sentence above has always said so and the
        // arithmetic did not.
        let around = State::panel_first_row(ctx)
            .saturating_add(1)
            .saturating_add(State::glyph_cells(ctx));
        let ceiling = (ctx.lines.saturating_sub(around) / 2).max(1);
        // THE INDENT IS NOT PART OF THE GRID. `Grid` counts from cell zero, so
        // what it is given is the width that is LEFT after the indent, and the
        // indent goes back on in `cell` and comes off again in `at_cell`.
        let indent = State::panel_indent(ctx);
        let wide = ctx.columns.saturating_sub(indent);
        let probe = Grid::fitted(wide, SHEET_LABEL, first_row, first_row + ceiling, 1);
        let per_row = usize::from(probe.across);
        let lines = total.div_ceil(per_row).min(usize::from(probe.rows)).max(1);
        let tall = u16::try_from(lines).unwrap_or(u16::MAX);
        let grid = Grid::fitted(wide, SHEET_LABEL, first_row, first_row + tall, 1);
        Self {
            grid,
            indent,
            first: (selection / per_row) / lines * lines * per_row,
            total,
        }
    }

    /// How many options fit side by side.
    fn across(&self) -> u16 {
        self.grid.across
    }

    /// How many lines the panel takes on the screen.
    fn lines(&self) -> u16 {
        self.grid.rows
    }

    /// Where option `n` is drawn: `(line, first cell)`, in the buffer's own rows.
    ///
    /// `None` when it is on another page.
    fn cell(&self, n: usize) -> Option<(u16, u16)> {
        let (line, column) = self.grid.at(n.checked_sub(self.first)?)?;
        Some((line, column.saturating_add(self.indent)))
    }

    /// Which option is on the clicked cell, if any.
    fn at_cell(&self, line: u16, column: u16) -> Option<usize> {
        // `saturating_sub` on the indent: clicking on the left gutter lands on the
        // first option of the row. It has no other owner, and a target that ignores
        // two pixels of margin is a target you miss.
        let n = self.first
            + self
                .grid
                .index_at(line, column.saturating_sub(self.indent))?;
        (n < self.total).then_some(n)
    }
}

/// A glyph, with only what the browser uses.
struct Glyph {
    ch: char,
    name: String,
    /// The OTHER names of the same codepoint, when there are any.
    ///
    /// A codepoint can have several names in `glyphnames.json` (aliases). The grid
    /// shows only the first one — on the sheet they fit, and they are the answer
    /// to "I could have sworn this icon was called something else".
    aliases: Vec<String>,
    set_of: String,
    /// One tag list per language, in [`TAG_LANGUAGES`] order.
    ///
    /// The words that FIND this glyph, accented as they appear on screen. It
    /// was two named fields, `tags_pt` and `tags_en`, and the pair was the
    /// shape a third language could not fit: the struct, the parser, the
    /// search and the sheet all said "two" out loud.
    tags: Vec<Vec<String>>,
    /// The forms of the pt tags WITHOUT accents, only the ones that differ.
    ///
    /// They do not go to the screen: they exist so that `localizacao` finds what
    /// is written `localização`. What computes them is the GENERATOR — normalizing
    /// here would cost walking 10,473 glyphs on every keystroke.
    search: Vec<String>,
    /// The icon token that uses this glyph, if any. It comes computed from the
    /// database (`gen-glyphdb.py`), because what knows that is the table of
    /// section 6.3 — and the component does not read files to find out on its own.
    token: Option<String>,
    /// Is this glyph assigned to some app id in the tray?
    in_tray: bool,
}

